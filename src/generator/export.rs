pub(super) fn config_suffix(config: &str) -> String {
    if config.is_empty() { "noconfig".into() } else { config.to_ascii_lowercase() }
}

struct Record<'a> {
    target: &'a Target,
    installed: Option<&'a ExportTarget>,
    kind: TargetKind,
    name: String,
}

fn records<'a>(
    ctx: &GenCtx<'a>, options: &ExportOptions, set: Option<&'a ExportSet>,
    targets: &'a [String], installed: bool,
) -> Vec<Record<'a>> {
    let make = |name: &str, item: Option<&'a ExportTarget>| {
        let target = ctx.target(name)?;
        let kind = if installed && target.kind == TargetKind::ObjectLibrary &&
            item.is_some_and(|item| item.artifact.is_none()) {
            TargetKind::InterfaceLibrary
        } else { target.kind };
        let export_name = target.props.get("EXPORT_NAME").filter(|name| !name.is_empty()).unwrap_or(name);
        Some(Record { target, installed: item, kind, name: format!("{}{export_name}", options.namespace) })
    };
    if let Some(set) = set {
        set.targets.iter().filter(|item| !item.namelink_only).filter_map(|item| make(&item.name, Some(item))).collect()
    } else {
        targets.iter().filter_map(|name| make(name, None)).collect()
    }
}

pub fn write_build_exports(ctx: &GenCtx) -> std::io::Result<()> {
    for (file, export) in &ctx.interp.ext.install.build_exports {
        let set = export.set.as_ref().and_then(|name| ctx.interp.ext.install.export_sets.get(name));
        let records = records(ctx, &export.options, set, &export.targets, false);
        let mut seen = HashSet::new();
        if let Some(duplicate) = records.iter().find(|record| !seen.insert(&record.target.name)) {
            ctx.error(export.backtrace.clone(), format!(
                "export() given target \"{}\" more than once.", duplicate.target.name
            ));
            continue;
        }
        if export.set.is_some() && set.is_none() {
            ctx.error(export.backtrace.clone(), "Could not write export file.");
            continue;
        }
        let mut script = main_header(&records);
        write_package_dependencies(&mut script, &export.options, set);
        write_targets(ctx, &mut script, &records, &export.options, false);
        if !export.options.modules_directory.is_empty() {
            let name = export.set.as_deref().unwrap_or("");
            if name.is_empty() {
                ctx.error(export.backtrace.clone(), "export(TARGETS) with CXX_MODULES_DIRECTORY is not supported by cmake-rust.");
            } else {
                let parent = Path::new(file).parent().unwrap_or(Path::new(""));
                let modules = parent.join(&export.options.modules_directory);
                module_include(&mut script, &export.options.modules_directory, name);
                write_build_modules(ctx, &modules, name)?;
            }
        }
        write_config(ctx, &mut script, &records, &export.options, false);
        missing_targets(&mut script, false, &records, &[]);
        script.push_str(END);
        if export.append && Path::new(file).exists() {
            use std::io::Write as _;
            std::fs::OpenOptions::new().append(true).open(file)?.write_all(script.as_bytes())?;
        } else {
            let _makefile = export.makefile;
            write_if_different(Path::new(file), script.as_bytes())?;
        }
    }
    Ok(())
}

pub(super) fn write_install_export(
    ctx: &GenCtx, out: &mut String, index: usize, rule: &InstallRule,
    export: &InstallExport, indent: &str,
) -> std::io::Result<()> {
    let set = ctx.interp.ext.install.export_sets.get(&export.set);
    if set.is_none_or(|set| set.targets.is_empty()) {
        ctx.error(Vec::new(), format!("INSTALL(EXPORT) given unknown export \"{}\"", export.set));
        return Ok(());
    }
    let records = records(ctx, &export.options, set, &[], true);
    let mut seen = HashSet::new();
    if let Some(duplicate) = records.iter().find(|record| !seen.insert(&record.target.name)) {
        ctx.error(rule.backtrace.clone(), format!(
            "install(EXPORT \"{}\" ...) includes target \"{}\" more than once in the export set.",
            export.set, duplicate.target.name
        ));
        return Ok(());
    }
    let dest = &rule.options.destination;
    let binary = &ctx.interp.makefiles[index].binary_dir;
    let temp = format!("{binary}/CMakeFiles/Export/{:x}", Md5::digest(dest.as_bytes()));
    let file = format!("{temp}/{}", export.filename);
    let stem = export.filename.strip_suffix(".cmake").unwrap_or(&export.filename);
    let glob = format!("{stem}-*.cmake");
    let mut script = main_header(&records);
    write_package_dependencies(&mut script, &export.options, set);
    write_prefix(ctx, &mut script, index, dest);
    write_targets(ctx, &mut script, &records, &export.options, true);
    writeln!(script, "# Load information for each installed configuration.").unwrap();
    write!(script, "file(GLOB _cmake_config_files \"${{CMAKE_CURRENT_LIST_DIR}}/{glob}\")\n").unwrap();
    script.push_str(r#"foreach(_cmake_config_file IN LISTS _cmake_config_files)
  include("${_cmake_config_file}")
endforeach()
unset(_cmake_config_file)
unset(_cmake_config_files)

"#);
    let has_config = records.iter().any(|record| record.kind != TargetKind::InterfaceLibrary);
    let module_dir = &export.options.modules_directory;
    let suffix = config_suffix(&ctx.config);
    if !module_dir.is_empty() {
        module_include(&mut script, module_dir, &export.set);
    }
    script.push_str(INSTALL_CHECKS);
    script.push_str(END);
    write_if_different(Path::new(&file), script.as_bytes())?;
    let opts = crate::install_model::InstallOptions { optional: false, ..rule.options.clone() };
    let installed_dir = format!("$ENV{{DESTDIR}}{}/", absolute_dest(dest));
    let installed_file = format!("{installed_dir}{}", export.filename);
    replacement_check(out, indent, &installed_file, &file, &format!("{installed_dir}{glob}"), "export");
    write_copy(out, indent, &opts, CopyRule::new(dest, CopyKind::File, &[file]));
    if has_config {
        let config_file = format!("{temp}/{stem}-{suffix}.cmake");
        let mut config = String::from(
            "#----------------------------------------------------------------\n# Generated CMake target import file.\n#----------------------------------------------------------------\n\n# Commands may need to know the format version.\nset(CMAKE_IMPORT_FILE_VERSION 1)\n\n"
        );
        write_config(ctx, &mut config, &records, &export.options, true);
        config.push_str("# Commands beyond this point should not need to know the version.\nset(CMAKE_IMPORT_FILE_VERSION)\n");
        write_if_different(Path::new(&config_file), config.as_bytes())?;
        if opts.configurations.is_empty() || opts.configurations.iter().any(|c| c.eq_ignore_ascii_case(&ctx.config)) {
            write_config_copy(ctx, out, indent, &opts, dest, config_file);
        }
    }
    if !module_dir.is_empty() {
        let modules = Path::new(&temp).join(module_dir);
        let main = modules.join(format!("cxx-modules-{}.cmake", export.set));
        let per_config = modules.join(format!("cxx-modules-{}-{suffix}.cmake", export.set));
        let glob = format!("cxx-modules-{}-*.cmake", export.set);
        let module_destination = format!("{dest}/{module_dir}");
        let installed_dir = format!("$ENV{{DESTDIR}}{}/", absolute_dest(&module_destination));
        let content = format!(
            "file(GLOB _cmake_cxx_module_includes \"${{CMAKE_CURRENT_LIST_DIR}}/{glob}\")\nforeach (_cmake_cxx_module_include IN LISTS _cmake_cxx_module_includes)\n  include(\"${{_cmake_cxx_module_include}}\")\nendforeach ()\n"
        );
        write_if_different(&main, content.as_bytes())?;
        let main = main.to_string_lossy().into_owned();
        replacement_check(out, indent, &format!("{installed_dir}cxx-modules-{}.cmake", export.set), &main,
            &format!("{installed_dir}{glob}"), "C++ module export");
        write_copy(out, indent, &opts, CopyRule::new(&module_destination, CopyKind::File, &[main]));
        if has_config {
            write_if_different(&per_config, b"")?;
            write_config_copy(ctx, out, indent, &opts, &module_destination, per_config.to_string_lossy().into_owned());
        }
    }
    Ok(())
}

fn write_config_copy(
    ctx: &GenCtx, out: &mut String, indent: &str, opts: &crate::install_model::InstallOptions,
    dest: &str, config_file: String,
) {
    writeln!(out, "{indent}if({})", config_test("CMAKE_INSTALL_CONFIG_NAME", std::slice::from_ref(&ctx.config))).unwrap();
    write_copy(out, &format!("{indent}  "), opts, CopyRule::new(dest, CopyKind::File, &[config_file]));
    writeln!(out, "{indent}endif()").unwrap();
}

fn replacement_check(out: &mut String, indent: &str, installed: &str, file: &str, glob: &str, label: &str) {
    write!(out, r#"{indent}if(EXISTS "{installed}")
{indent}  file(DIFFERENT _cmake_export_file_changed FILES
{indent}       "{installed}"
{indent}       "{file}")
{indent}  if(_cmake_export_file_changed)
{indent}    file(GLOB _cmake_old_config_files "{glob}")
{indent}    if(_cmake_old_config_files)
{indent}      string(REPLACE ";" ", " _cmake_old_config_files_text "${{_cmake_old_config_files}}")
{indent}      message(STATUS "Old {label} file \"{installed}\" will be replaced.  Removing files [${{_cmake_old_config_files_text}}].")
{indent}      unset(_cmake_old_config_files_text)
{indent}      file(REMOVE ${{_cmake_old_config_files}})
{indent}    endif()
{indent}    unset(_cmake_old_config_files)
{indent}  endif()
{indent}  unset(_cmake_export_file_changed)
{indent}endif()
"#).unwrap();
}

fn main_header(records: &[Record<'_>]) -> String {
    let mut out = String::from(HEADER);
    let names: Vec<_> = records.iter().map(|record| record.name.as_str()).collect();
    let space = if names.is_empty() { "" } else { " " };
    writeln!(out, "foreach(_cmake_expected_target IN ITEMS{space}{})", names.join(" ")).unwrap();
    out.push_str(TARGET_GUARD);
    out
}

fn write_prefix(ctx: &GenCtx, out: &mut String, index: usize, dest: &str) {
    let prefix = ctx.var_safe(index, "CMAKE_INSTALL_PREFIX");
    if is_full_path(dest) {
        write!(out, "# The installation prefix configured by this project.\nset(_IMPORT_PREFIX \"{prefix}\")\n\n").unwrap();
    } else {
        out.push_str("# Compute the installation prefix relative to this file.\nget_filename_component(_IMPORT_PREFIX \"${CMAKE_CURRENT_LIST_FILE}\" PATH)\n");
        let absolute = format!("{prefix}/{dest}");
        if ["/lib/", "/lib64/", "/libx32/", "/usr/lib/", "/usr/lib64/", "/usr/libx32/"].iter().any(|path| format!("{absolute}/").starts_with(path)) {
            write!(out, r#"# Use original install prefix when loaded through a
# cross-prefix symbolic link such as /lib -> /usr/lib.
get_filename_component(_realCurr "${{_IMPORT_PREFIX}}" REALPATH)
get_filename_component(_realOrig "{absolute}" REALPATH)
if(_realCurr STREQUAL _realOrig)
  set(_IMPORT_PREFIX "{absolute}")
endif()
unset(_realOrig)
unset(_realCurr)
"#).unwrap();
        }
        for _ in dest.split('/').filter(|part| !part.is_empty()) {
            out.push_str("get_filename_component(_IMPORT_PREFIX \"${_IMPORT_PREFIX}\" PATH)\n");
        }
        out.push_str("if(_IMPORT_PREFIX STREQUAL \"/\")\n  set(_IMPORT_PREFIX \"\")\nendif()\n\n");
    }
}

fn export_quote(value: &str) -> String {
    format!("\"{}\"", value.replace('"', "\\\""))
}

fn write_targets(ctx: &GenCtx, out: &mut String, records: &[Record<'_>], options: &ExportOptions, installed: bool) {
    for record in records {
        let tgt = record.target;
        let name = &record.name;
        writeln!(out, "# Create imported target {name}").unwrap();
        if record.kind == TargetKind::Executable {
            writeln!(out, "add_executable({name} IMPORTED)").unwrap();
        } else {
            let kind = match record.kind {
                TargetKind::StaticLibrary => "STATIC",
                TargetKind::SharedLibrary => "SHARED",
                TargetKind::ModuleLibrary => "MODULE",
                TargetKind::ObjectLibrary => "OBJECT",
                TargetKind::InterfaceLibrary => "INTERFACE",
                _ => "UNKNOWN",
            };
            writeln!(out, "add_library({name} {kind} IMPORTED)").unwrap();
        }
        if record.kind == TargetKind::Executable && is_on_opt(tgt.props.get("ENABLE_EXPORTS")) {
            writeln!(out, "set_property(TARGET {name} PROPERTY ENABLE_EXPORTS 1)").unwrap();
        }
        if let Some(value) = tgt.props.get("DEPRECATION").filter(|value| !value.is_empty()) {
            writeln!(out, "set_property(TARGET {name} PROPERTY DEPRECATION {})", export_quote(value)).unwrap();
        }
        if is_on_opt(tgt.props.get("IMPORTED_NO_SYSTEM")) {
            writeln!(out, "set_property(TARGET {name} PROPERTY IMPORTED_NO_SYSTEM 1)").unwrap();
        }
        if is_on_opt(tgt.props.get("EXPORT_NO_SYSTEM")) {
            writeln!(out, "set_property(TARGET {name} PROPERTY SYSTEM 0)").unwrap();
        }
        out.push('\n');
        let properties = interface_properties(tgt, records, options, record.installed.filter(|_| installed), installed);
        if !properties.is_empty() {
            writeln!(out, "set_target_properties({name} PROPERTIES").unwrap();
            write_properties(out, &properties);
            out.push_str(")\n\n");
        }
        write_file_sets(ctx, out, record, installed);
    }
}

fn interface_properties(
    tgt: &Target, records: &[Record<'_>], options: &ExportOptions, export: Option<&ExportTarget>, installed: bool,
) -> BTreeMap<String, String> {
    let mut properties = BTreeMap::new();
    let exported = [
        "INTERFACE_INCLUDE_DIRECTORIES", "INTERFACE_SYSTEM_INCLUDE_DIRECTORIES", "INTERFACE_LINK_DIRECTORIES",
        "INTERFACE_LINK_DEPENDS", "INTERFACE_LINK_LIBRARIES", "INTERFACE_LINK_LIBRARIES_DIRECT",
        "INTERFACE_LINK_LIBRARIES_DIRECT_EXCLUDE", "INTERFACE_COMPILE_DEFINITIONS",
        "INTERFACE_COMPILE_OPTIONS", "INTERFACE_PRECOMPILE_HEADERS", "INTERFACE_AUTOUIC_OPTIONS",
        "INTERFACE_AUTOMOC_MACRO_NAMES", "INTERFACE_COMPILE_FEATURES", "INTERFACE_LINK_OPTIONS",
        "INTERFACE_POSITION_INDEPENDENT_CODE", "INTERFACE_SOURCES", "COMPATIBLE_INTERFACE_BOOL",
        "COMPATIBLE_INTERFACE_STRING", "COMPATIBLE_INTERFACE_NUMBER_MIN", "COMPATIBLE_INTERFACE_NUMBER_MAX",
        "SPDX_LICENSE", "TRANSITIVE_COMPILE_PROPERTIES", "TRANSITIVE_LINK_PROPERTIES",
    ];
    let custom = expand_list(tgt.props.get("EXPORT_PROPERTIES").unwrap_or(""), false);
    for key in exported.into_iter().chain(custom.iter().map(String::as_str)) {
        let Some(value) = tgt.props.get(key) else { continue; };
        let mut value = preprocess(value, installed, key != "INTERFACE_LINK_LIBRARIES");
        if matches!(key, "INTERFACE_LINK_LIBRARIES" | "INTERFACE_LINK_LIBRARIES_DIRECT" | "INTERFACE_LINK_LIBRARIES_DIRECT_EXCLUDE") {
            value = link_names(&value, records, options);
        }
        if !value.is_empty() || tgt.props.get(key) == Some("") {
            properties.insert(key.to_owned(), value);
        }
    }
    if let Some(export) = export.filter(|export| !export.includes.is_empty()) {
        let includes = export.includes.iter().map(|path| import_path(path)).collect::<Vec<_>>().join(";");
        let value = properties.entry("INTERFACE_INCLUDE_DIRECTORIES".into()).or_default();
        if !value.is_empty() { value.push(';'); }
        value.push_str(&includes);
    }
    for key in ["COMPATIBLE_INTERFACE_BOOL", "COMPATIBLE_INTERFACE_STRING", "COMPATIBLE_INTERFACE_NUMBER_MIN", "COMPATIBLE_INTERFACE_NUMBER_MAX"] {
        for property in expand_list(tgt.props.get(key).unwrap_or(""), false) {
            let key = format!("INTERFACE_{property}");
            if let Some(value) = tgt.props.get(&key) {
                properties.insert(key, value.to_owned());
            }
        }
    }
    properties
}

fn preprocess(value: &str, installed: bool, rewrite_relative: bool) -> String {
    let mut out = String::new();
    let mut tail = value;
    while let Some(start) = tail.find("$<") {
        out.push_str(&tail[..start]);
        let expression = &tail[start + 2..];
        let mut depth = 1;
        let mut end = None;
        for (i, byte) in expression.bytes().enumerate() {
            if byte == b'<' && i > 0 && expression.as_bytes()[i - 1] == b'$' { depth += 1; }
            if byte == b'>' {
                depth -= 1;
                if depth == 0 { end = Some(i); break; }
            }
        }
        let Some(end) = end else { out.push_str(&tail[start..]); return out; };
        let inside = &expression[..end];
        match inside.split_once(':') {
            Some(("BUILD_INTERFACE", body)) if !installed => out.push_str(&preprocess(body, installed, rewrite_relative)),
            Some(("INSTALL_INTERFACE", body)) if installed => {
                let body = preprocess(body, installed, rewrite_relative);
                if rewrite_relative {
                    let prefixed = expand_list(&body, false).iter().map(|p| import_path(p)).collect::<Vec<_>>().join(";");
                    out.push_str(&prefixed);
                } else { out.push_str(&body); }
            }
            Some(("BUILD_INTERFACE" | "INSTALL_INTERFACE" | "BUILD_LOCAL_INTERFACE", _)) => {}
            _ if inside == "INSTALL_PREFIX" && installed => out.push_str("${_IMPORT_PREFIX}"),
            _ => {
                out.push_str("$<");
                out.push_str(&preprocess(inside, installed, rewrite_relative));
                out.push('>');
            }
        }
        tail = &expression[end + 1..];
    }
    out.push_str(tail);
    out.split(';').filter(|v| !v.is_empty() && !v.starts_with("::@")).collect::<Vec<_>>().join(";")
}

fn import_path(path: &str) -> String {
    if is_full_path(path) || path.starts_with("$<") || path.starts_with("${_IMPORT_PREFIX}") {
        path.to_owned()
    } else { format!("${{_IMPORT_PREFIX}}/{path}") }
}

fn link_names(value: &str, records: &[Record<'_>], _options: &ExportOptions) -> String {
    let convert = |arg: &str| records.iter().find(|r| r.target.name == arg).map_or_else(|| arg.to_owned(), |r| r.name.clone());
    expand_list(value, false).iter().map(|arg| {
        if let Some(inner) = arg.strip_prefix("$<LINK_ONLY:").and_then(|v| v.strip_suffix('>')) {
            format!("$<LINK_ONLY:{}>", convert(inner))
        } else { convert(arg) }
    }).collect::<Vec<_>>().join(";")
}

fn write_properties(out: &mut String, properties: &BTreeMap<String, String>) {
    for (key, value) in properties {
        writeln!(out, "  {key} {}", export_quote(value)).unwrap();
    }
}

fn write_config(ctx: &GenCtx, out: &mut String, records: &[Record<'_>], options: &ExportOptions, installed: bool) {
    let config = &ctx.config;
    let upper = config_suffix(config).to_ascii_uppercase();
    let suffix = format!("_{upper}");
    for record in records.iter().filter(|r| r.kind != TargetKind::InterfaceLibrary) {
        let tgt = record.target;
        let name = &record.name;
        let mut properties = BTreeMap::new();
        let artifact = record.installed.and_then(|item| item.artifact.as_ref());
        if installed && artifact.is_none_or(|arg| !arg.configurations.is_empty() &&
            !arg.configurations.iter().any(|c| c.eq_ignore_ascii_case(config))) {
            continue;
        }
        let mut check = Vec::new();
        if record.kind == TargetKind::ObjectLibrary {
            let base = if let Some(arg) = artifact.filter(|_| installed) {
                format!("{}/{}", import_path(&arg.destination), object_subdir(tgt, config))
            } else { format!("{}.", target::object_directory(ctx, tgt, config)) };
            let files: Vec<_> = object_names(ctx, tgt).iter().map(|name| format!("{base}/{name}")).collect();
            properties.insert(format!("IMPORTED_OBJECTS{suffix}"), files.join(";"));
            check.extend(files);
        } else {
            let names = target::names(ctx, tgt, config);
            // INTEGRATION: install destinations accept generator expressions.
            let location = if let Some(arg) = artifact.filter(|_| installed) {
                let dest = ctx.genex(&arg.destination, None, None);
                format!("{}/{}", import_path(&dest), names.real)
            } else {
                target::full_path(ctx, tgt, config, target::ArtifactType::Runtime, true)
            };
            properties.insert(format!("IMPORTED_LOCATION{suffix}"), location.clone());
            check.push(location);
            if record.kind == TargetKind::SharedLibrary {
                if names.shared_object.is_empty() {
                    properties.insert(format!("IMPORTED_NO_SONAME{suffix}"), "TRUE".into());
                } else {
                    properties.insert(format!("IMPORTED_SONAME{suffix}"), names.shared_object);
                }
            }
        }
        if matches!(record.kind, TargetKind::StaticLibrary | TargetKind::ObjectLibrary) {
            let language = target::linker_language(ctx, tgt, config);
            if !language.is_empty() {
                properties.insert(format!("IMPORTED_LINK_INTERFACE_LANGUAGES{suffix}"), language);
            }
        }
        if options.old_link_interface {
            let key = format!("LINK_INTERFACE_LIBRARIES{suffix}");
            if let Some(value) = tgt.props.get(&key).or_else(|| tgt.props.get("LINK_INTERFACE_LIBRARIES")) {
                properties.insert(format!("IMPORTED_LINK_INTERFACE_LIBRARIES{suffix}"), link_names(&preprocess(value, installed, false), records, options));
            }
        }
        write!(out, "# Import target \"{name}\" for configuration \"{config}\"\nset_property(TARGET {name} APPEND PROPERTY IMPORTED_CONFIGURATIONS {upper})\nset_target_properties({name} PROPERTIES\n").unwrap();
        write_properties(out, &properties);
        out.push_str("  )\n\n");
        if installed && !check.is_empty() {
            writeln!(out, "list(APPEND _cmake_import_check_targets {name} )").unwrap();
            write!(out, "list(APPEND _cmake_import_check_files_for_{name} ").unwrap();
            for file in &check { write!(out, "{} ", export_quote(file)).unwrap(); }
            out.push_str(")\n\n");
        }
    }
}

fn write_package_dependencies(out: &mut String, options: &ExportOptions, set: Option<&ExportSet>) {
    if !options.package_dependencies { return; }
    out.push_str("include(CMakeFindDependencyMacro)\n");
    for (pkg, enabled, args) in set.into_iter().flat_map(|set| &set.package_dependencies) {
        if !is_on(enabled) { continue; }
        write!(out, "find_dependency({pkg}").unwrap();
        for arg in args { write!(out, " {}", escape_for_cmake(arg)).unwrap(); }
        out.push_str(")\n");
    }
    out.push_str("\n\n");
}

fn module_include(out: &mut String, dir: &str, name: &str) {
    write!(out, "# Include C++ module properties\ninclude(\"${{CMAKE_CURRENT_LIST_DIR}}/{dir}/cxx-modules-{name}.cmake\")\n\n").unwrap();
}

fn write_build_modules(ctx: &GenCtx, dir: &Path, name: &str) -> std::io::Result<()> {
    let config = config_suffix(&ctx.config);
    let config_file = format!("cxx-modules-{name}-{config}.cmake");
    let content = format!("include(\"${{CMAKE_CURRENT_LIST_DIR}}/{config_file}\")\n");
    write_if_different(&dir.join(format!("cxx-modules-{name}.cmake")), content.as_bytes())?;
    write_if_different(&dir.join(config_file), b"")
}

fn missing_targets(out: &mut String, _installed: bool, _records: &[Record<'_>], _missing: &[String]) {
    out.push_str("# This file does not depend on other imported targets which have\n# been exported from the same project but in a separate export set.\n\n");
}

fn write_file_sets(ctx: &GenCtx, out: &mut String, record: &Record<'_>, installed: bool) {
    let tgt = record.target;
    for key in ["INTERFACE_HEADER_SETS", "INTERFACE_CXX_MODULE_SETS"] {
        for set in expand_list(tgt.props.get(key).unwrap_or(""), false) {
            let Some((paths, bases, kind)) = file_set_properties(tgt, &set) else { continue; };
            // INTEGRATION: FILE_SET declarations may be config-specific.
            let mut paths = expand_list(&ctx.genex(&paths, Some(tgt), None), false);
            let mut bases = expand_list(&ctx.genex(&bases, Some(tgt), None), false);
            if installed {
                let Some(dest) = record.installed.and_then(|r| r.file_sets.get(&set)) else { continue; };
                let dest = import_path(dest);
                for path in &mut paths {
                    if let Some(tail) = bases.iter().find_map(|base| Path::new(path).strip_prefix(base).ok()) {
                        *path = format!("{dest}/{}", tail.display());
                    }
                }
                bases = vec![dest];
            }
            out.push_str("if(NOT CMAKE_VERSION VERSION_LESS \"3.23.0\")\n");
            writeln!(out, "  target_sources({}\n    INTERFACE\n      FILE_SET \"{set}\"\n      TYPE \"{kind}\"", record.name).unwrap();
            for (key, values) in [("BASE_DIRS", bases), ("FILES", paths)] {
                write!(out, "      {key}").unwrap();
                for value in values { write!(out, " {}", export_quote(&value)).unwrap(); }
                out.push('\n');
            }
            out.push_str("  )\nendif()\n\n");
        }
    }
}
