pub(super) struct Exporter<'a, 'b> {
    pub ctx: &'b GenCtx<'a>,
    pub options: &'b ExportOptions,
    pub installed: bool,
    pub append: bool,
    /// Makefile index whose backtrace anchors `ReportError` calls.
    pub error_dir: usize,
    /// `install(EXPORT "x" ...)`: the export name for error text.
    pub export_label: String,
    pub required: Cell<(u32, u32, u32)>,
    /// Non-imported targets carried by this export (cmGeneratorTarget ptrs).
    pub exported: HashSet<*const Target>,
    /// Linked targets needing find_dependency calls.
    pub external: Vec<*const Target>,
    pub missing: Vec<String>,
    /// Effective namespace of the exported targets (`<package>::` for CPS).
    pub namespace: String,
    /// `cmExportPackageInfoGenerator` arguments; `Some` for CPS exports.
    pub package: Option<&'b crate::package_info::PackageInfoArguments>,
    /// CPS `LinkTargets`: the property-visible name of each resolved linked
    /// target → `:component` or `package:component`.
    pub link_targets: std::collections::HashMap<String, String>,
    /// CPS `Requirements`: package name → required component names.
    pub requirements: BTreeMap<String, BTreeSet<String>>,
}

impl<'a, 'b> Exporter<'a, 'b> {
    fn bump(&self, version: (u32, u32, u32)) {
        if version > self.required.get() {
            self.required.set(version);
        }
    }

    pub(super) fn report_error(&self, message: impl Into<String>) {
        self.ctx
            .error(dir_backtrace(self.ctx, self.error_dir), message.into());
    }

    pub(super) fn depender_backtrace(&self, depender: &Target) -> Vec<Frame> {
        dir_backtrace(self.ctx, depender.makefile)
    }

    /// `cmGeneratorTarget::ResolveTargetReference` +
    /// `cmLocalGenerator::FindGeneratorTargetToUse` from `dir`.
    fn resolve(&self, dir: usize, name: &str) -> Option<&'a Target> {
        target::target_in_directory(self.ctx, dir, name)
    }

    pub(super) fn find(&self, dir: usize, name: &str) -> Option<&'a Target> {
        self.ctx
            .target_at(dir, name)
            .or_else(|| self.ctx.target(name))
    }

    /// `GetInstallPrefix` / `GetImportPrefix` (`"@prefix@"` for CPS).
    pub fn import_prefix(&self) -> &'static str {
        if self.options.android {
            "$(_IMPORT_PREFIX)"
        } else if self.package.is_some() {
            "@prefix@"
        } else {
            IMPORT_PREFIX
        }
    }

    /// `GetImportPrefixWithSlash`.
    pub fn import_prefix_slash(&self) -> &'static str {
        if self.options.android {
            "$(_IMPORT_PREFIX)/"
        } else if self.package.is_some() {
            "@prefix@/"
        } else {
            IMPORT_PREFIX_SLASH
        }
    }

    /// `cmExportBuildFileGenerator`/`cmExportInstallFileGenerator`
    /// `::FindExportInfo`.
    fn find_export_info(&self, dependee: &Target) -> ExportInfo {
        let mut files = Vec::new();
        let mut sets = BTreeSet::new();
        let mut namespaces = BTreeSet::new();
        let inst = &self.ctx.interp.ext.install;
        if self.installed {
            for (set_name, set) in &inst.export_sets {
                if !set.targets.iter().any(|t| t.name == dependee.name) {
                    continue;
                }
                let installs: Vec<(String, String)> = inst
                    .rules
                    .values()
                    .flatten()
                    .filter_map(|rule| match &rule.action {
                        InstallAction::Export(export) if export.set == *set_name => Some((
                            format!("{}/{}", rule.options.destination, export.filename),
                            export.options.namespace.clone(),
                        )),
                        InstallAction::PackageInfo { set, arguments } if set == set_name => Some((
                            format!(
                                "{}/{}",
                                rule.options.destination,
                                arguments.package_file_name()
                            ),
                            arguments.namespace(),
                        )),
                        _ => None,
                    })
                    .collect();
                if installs.is_empty() {
                    continue;
                }
                sets.insert(set_name.clone());
                for (file, namespace) in installs {
                    files.push(file);
                    namespaces.insert(namespace);
                }
            }
        } else {
            for (file, exp) in &inst.build_exports {
                let names: Vec<&str> = if let Some(set_name) = &exp.set {
                    inst.export_sets.get(set_name).map_or(Vec::new(), |set| {
                        set.targets
                            .iter()
                            .filter(|t| !t.namelink_only)
                            .map(|t| t.name.as_str())
                            .collect()
                    })
                } else {
                    exp.targets.iter().map(String::as_str).collect()
                };
                if names.contains(&dependee.name.as_str()) {
                    files.push(file.clone());
                    sets.insert(exp.set.clone().unwrap_or_else(|| file.clone()));
                    namespaces.insert(
                        exp.package_info
                            .as_ref()
                            .map_or_else(|| exp.options.namespace.clone(), |p| p.namespace()),
                    );
                }
            }
        }
        ExportInfo {
            files,
            sets,
            namespaces,
        }
    }

    /// `HandleMissingTarget`.
    fn handle_missing(&mut self, out: &mut String, depender: &Target, dependee: &'a Target) {
        if !self.installed && self.append {
            // Assume the target will be exported by another command.
            out.push_str(&format!("{}{}", self.namespace, export_name(dependee)));
            return;
        }
        let info = self.find_export_info(dependee);
        if info.namespaces.len() == 1 && info.sets.len() == 1 {
            let missing = format!(
                "{}{}",
                info.namespaces.iter().next().unwrap(),
                export_name(dependee)
            );
            out.push_str(&missing);
            self.missing.push(missing);
        } else {
            self.complain_missing(depender, dependee, &info);
            if !self.installed {
                // cmExportBuildFileGenerator::HandleMissingTarget: after the
                // complaint, assume another command exports it and append it
                // with this export's namespace.
                out.push_str(&format!("{}{}", self.namespace, export_name(dependee)));
            }
        }
    }

    /// `ComplainAboutMissingTarget`.
    fn complain_missing(&self, depender: &Target, dependee: &Target, info: &ExportInfo) {
        let mut e = if self.installed {
            format!(
                "install({} \"{}\" ...) includes target \"{}\" which requires target \"{}\" ",
                if self.package.is_some() {
                    "PACKAGE_INFO"
                } else {
                    "EXPORT"
                },
                self.export_label,
                depender.name,
                dependee.name
            )
        } else {
            format!(
                "export called with target \"{}\" which requires target \"{}\" ",
                depender.name, dependee.name
            )
        };
        if info.sets.is_empty() {
            e.push_str("that is not in any export set.");
        } else {
            if info.sets.len() == 1 {
                e.push_str(
                    "that is not in this export set, but in another export set which is exported multiple times with different namespaces: ",
                );
            } else {
                e.push_str("that is not in this export set, but in multiple other export sets: ");
            }
            e.push_str(&info.files.join(", "));
            e.push_str(&format!(
                ".\nAn exported target cannot depend upon another target which is exported in more than one export set or with more than one namespace. Consider consolidating the exports of the \"{}\" target to a single export.",
                dependee.name
            ));
        }
        self.report_error(e);
    }

    /// `AddTargetNamespace`; `dir` is the current link lookup scope.
    /// Returns false when the reference does not resolve to a target.
    fn add_target_namespace(&mut self, input: &mut String, depender: &Target, dir: usize) -> bool {
        let Some(tgt) = self.resolve(dir, input) else {
            return false;
        };
        if !tgt.find_package_stack.is_empty() || tgt.props.contains("EXPORT_FIND_PACKAGE_NAME") {
            let ptr = std::ptr::from_ref(tgt);
            if !self.external.contains(&ptr) {
                self.external.push(ptr);
            }
        }
        if tgt.imported {
            *input = tgt.name.clone();
            return self.note_linked_target(depender, input, tgt);
        }
        if self.exported.contains(&std::ptr::from_ref(tgt)) {
            *input = format!("{}{}", self.namespace, export_name(tgt));
        } else {
            let mut namespaced = String::new();
            self.handle_missing(&mut namespaced, depender, tgt);
            *input = if namespaced.is_empty() {
                tgt.name.clone()
            } else {
                namespaced
            };
        }
        self.note_linked_target(depender, input, tgt)
    }

    /// `cmExportPackageInfoGenerator::NoteLinkedTarget`: record the CPS
    /// component name for a linked target and, for external packages, the
    /// package requirement.  No-op for non-CPS exports.
    fn note_linked_target(
        &mut self,
        depender: &Target,
        linked_name: &str,
        linked: &'a Target,
    ) -> bool {
        let Some(package) = self.package else {
            return true;
        };
        if self.exported.contains(&std::ptr::from_ref(linked)) {
            // Target is internal to this package.
            self.link_targets
                .entry(linked_name.to_owned())
                .or_insert_with(|| format!(":{}", export_name(linked)));
            return true;
        }
        if linked.imported {
            // Target is imported from a found package.
            let pkg = linked
                .find_package_stack
                .last()
                .map(|(name, _)| name.clone())
                .or_else(|| {
                    linked
                        .props
                        .get("EXPORT_FIND_PACKAGE_NAME")
                        .filter(|name| !name.is_empty())
                        .map(str::to_owned)
                })
                .unwrap_or_default();
            if pkg.is_empty() {
                self.ctx.error(
                    self.depender_backtrace(depender),
                    format!(
                        "Target \"{}\" references imported target \"{linked_name}\" which does not come from any known package.",
                        depender.name
                    ),
                );
                return false;
            }
            let prefix = format!("{pkg}::");
            if !linked_name.starts_with(&prefix) {
                self.ctx.error(
                    self.depender_backtrace(depender),
                    format!(
                        "Target \"{}\" references target \"{linked_name}\", which comes from the \"{pkg}\" package, but does not belong to the package's canonical namespace. This is not allowed.",
                        depender.name
                    ),
                );
                return false;
            }
            let component = &linked_name[prefix.len()..];
            self.link_targets
                .entry(linked_name.to_owned())
                .or_insert_with(|| format!("{pkg}:{component}"));
            self.requirements
                .entry(pkg)
                .or_default()
                .insert(component.to_owned());
            return true;
        }
        // Target belongs to another export from this build.
        let info = self.find_export_info(linked);
        if info.namespaces.len() == 1 && info.sets.len() == 1 {
            let link_namespace = info.namespaces.iter().next().unwrap();
            if !link_namespace.ends_with("::") {
                self.ctx.error(
                    self.depender_backtrace(depender),
                    format!(
                        "Target \"{}\" references target \"{linked_name}\", which does not use the standard namespace separator. This is not allowed.",
                        depender.name
                    ),
                );
                return false;
            }
            let pkg = &link_namespace[..link_namespace.len() - 2];
            let component = export_name(linked);
            if pkg == package.package_name {
                self.link_targets
                    .entry(linked_name.to_owned())
                    .or_insert_with(|| format!(":{component}"));
            } else {
                self.link_targets
                    .entry(linked_name.to_owned())
                    .or_insert_with(|| format!("{pkg}:{component}"));
                self.requirements
                    .entry(pkg.to_owned())
                    .or_default()
                    .insert(component.to_owned());
            }
            return true;
        }
        // Target belongs to multiple namespaces or multiple export sets.
        // handle_missing should have complained about this already.
        false
    }

    /// `ResolveTargetsInGeneratorExpression`: target names embedded in
    /// TARGET_PROPERTY, TARGET_NAME and LINK_ONLY/COMPILE_ONLY expressions.
    fn resolve_genex(&mut self, input: &mut String, depender: &Target) {
        let dir = depender.makefile;
        let mut last = 0usize;
        while let Some(pos) = input[last..].find("$<TARGET_PROPERTY:").map(|o| last + o) {
            let name_start = pos + "$<TARGET_PROPERTY:".len();
            let close = input[name_start..].find('>').map(|o| name_start + o);
            let comma = input[name_start..].find(',').map(|o| name_start + o);
            let next_open = input[name_start..].find("$<").map(|o| name_start + o);
            let skip = match (comma, close) {
                (Some(comma), Some(close)) => {
                    close < comma || next_open.is_some_and(|open| open < comma)
                }
                _ => true,
            };
            if skip {
                last = name_start;
                continue;
            }
            let comma = comma.unwrap();
            let mut name = input[name_start..comma].to_owned();
            if self.add_target_namespace(&mut name, depender, dir) {
                input.replace_range(name_start..comma, &name);
            }
            last = name_start + name.len() + 1;
        }

        let mut error = String::new();
        let mut last = 0usize;
        while error.is_empty() {
            let Some(pos) = input[last..].find("$<TARGET_NAME:").map(|o| last + o) else {
                break;
            };
            let name_start = pos + "$<TARGET_NAME:".len();
            let Some(end) = input[name_start..].find('>').map(|o| name_start + o) else {
                error = "$<TARGET_NAME:...> expression incomplete".into();
                break;
            };
            let mut name = input[name_start..end].to_owned();
            if name.contains("$<") {
                error = "$<TARGET_NAME:...> requires its parameter to be a literal.".into();
                break;
            }
            if !self.add_target_namespace(&mut name, depender, dir) {
                error =
                    "$<TARGET_NAME:...> requires its parameter to be a reachable target.".into();
                break;
            }
            input.replace_range(pos..end + 1, &name);
            last = pos + name.len();
        }

        for tag in ["LINK_ONLY", "COMPILE_ONLY"] {
            let mut last = 0usize;
            let marker = format!("$<{tag}:");
            while error.is_empty() {
                let Some(pos) = input[last..].find(&marker).map(|o| last + o) else {
                    break;
                };
                let name_start = pos + marker.len();
                let Some(end) = input[name_start..].find('>').map(|o| name_start + o) else {
                    error = format!("$<{tag}:...> expression incomplete");
                    break;
                };
                let mut lib = input[name_start..end].to_owned();
                if genex::is_valid_target_name(&lib)
                    && self.add_target_namespace(&mut lib, depender, dir)
                {
                    input.replace_range(name_start..end, &lib);
                }
                last = name_start + lib.len() + 1;
            }
        }

        self.replace_install_prefix(input);
        if !error.is_empty() {
            self.ctx.error(self.depender_backtrace(depender), error);
        }
    }

    /// `ResolveTargetsInGeneratorExpressions`: split link lists into items,
    /// follow `::@` directory lookup scopes, and rewrite free-standing
    /// target names as well as names inside generator expressions.
    fn resolve_genexes(&mut self, input: &mut String, depender: &Target) {
        let mut dir = depender.makefile;
        let mut out = String::new();
        for mut item in genex::split(input) {
            if item == "::@" {
                dir = depender.makefile;
                continue;
            }
            if let Some(id) = item
                .strip_prefix("::@(0x")
                .and_then(|id| id.strip_suffix(')'))
                && let Ok(index) = usize::from_str_radix(id, 16)
            {
                dir = index;
                continue;
            }
            if genex::find(&item).is_none() {
                self.add_target_namespace(&mut item, depender, dir);
            } else {
                self.resolve_genex(&mut item, depender);
            }
            if !out.is_empty() {
                out.push(';');
            }
            out.push_str(&item);
        }
        *input = out;
    }

    /// `ReplaceInstallPrefix`: `${_IMPORT_PREFIX}` (`@prefix@` for CPS).
    fn replace_install_prefix(&self, input: &mut String) {
        if self.installed {
            *input = genex::replace_install_prefix(input, self.import_prefix());
        }
    }

    /// `AddImportPrefix`.
    fn add_import_prefix(&self, value: &str) -> String {
        let mut out = String::new();
        for entry in genex::split(value) {
            if !out.is_empty() {
                out.push(';');
            }
            if !is_full_path(&entry) && !entry.starts_with(self.import_prefix_slash()) {
                out.push_str(self.import_prefix_slash());
            }
            out.push_str(&entry);
        }
        out
    }

    /// `cmGeneratorExpression::Preprocess` + `CheckInterfaceDirs` +
    /// target-name resolution for a path-valued interface property.
    fn path_property(&mut self, key: &str, tgt: &Target, props: &mut BTreeMap<String, String>) {
        let Some(input) = tgt.props.get(key) else {
            return;
        };
        if input.is_empty() {
            props.insert(key.to_owned(), String::new());
            return;
        }
        let mut prepro = genex::preprocess(
            input,
            genex::PreprocessContext::InstallInterface,
            self.import_prefix_slash(),
        );
        if !prepro.is_empty() {
            self.resolve_genex(&mut prepro, tgt);
            if !self.check_interface_dirs(&prepro, tgt, key) {
                return;
            }
            props.insert(key.to_owned(), prepro);
        }
    }

    /// `PopulateInterfaceProperty` (preprocess + resolve variant).
    fn interface_property(
        &mut self,
        key: &str,
        out_key: &str,
        tgt: &Target,
        rule: genex::PreprocessContext,
        props: &mut BTreeMap<String, String>,
    ) {
        let Some(input) = tgt.props.get(key) else {
            return;
        };
        if input.is_empty() {
            props.insert(out_key.to_owned(), String::new());
            return;
        }
        let mut prepro = genex::preprocess(input, rule, "");
        if !prepro.is_empty() {
            self.resolve_genex(&mut prepro, tgt);
            props.insert(out_key.to_owned(), prepro);
        }
    }

    /// `PopulateInterfaceProperty` (raw copy variant).
    fn raw_property(&self, key: &str, tgt: &Target, props: &mut BTreeMap<String, String>) {
        if let Some(input) = tgt.props.get(key) {
            props.insert(key.to_owned(), input.to_owned());
        }
    }

    /// `CheckInterfaceDirs`; returns false when an item embeds a genex
    /// mid-string (`hadFatalError`) so the property is dropped.
    fn check_interface_dirs(&self, prepro: &str, tgt: &Target, prop: &str) -> bool {
        let install_dir = self.ctx.var_safe(tgt.makefile, "CMAKE_INSTALL_PREFIX");
        let top_source = &self.ctx.interp.home_source;
        let top_binary = &self.ctx.interp.home_binary;
        let in_source_build = top_source == top_binary;
        let sub = |a: &str, b: &str| !b.is_empty() && (a == b || is_subdirectory(a, b));
        let mut had_fatal = false;
        for item in genex::split(prepro) {
            let genex_pos = genex::find(&item);
            if genex_pos == Some(0) {
                continue;
            }
            if item.starts_with(self.import_prefix_slash()) {
                continue;
            }
            if genex_pos.is_some() {
                had_fatal = true;
            }
            if !is_full_path(&item) {
                self.ctx.error(
                    self.depender_backtrace(tgt),
                    format!(
                        "Target \"{}\" {prop} property contains relative path:\n  \"{item}\"",
                        tgt.name
                    ),
                );
            }
            let in_binary = sub(&item, top_binary);
            let in_source = sub(&item, top_source);
            if sub(&item, &install_dir)
                && (!in_binary || sub(&install_dir, top_binary))
                && (!in_source || sub(&install_dir, top_source))
            {
                continue;
            }
            if in_binary {
                self.ctx.error(
                    self.depender_backtrace(tgt),
                    format!(
                        "Target \"{}\" {prop} property contains path:\n  \"{item}\"\nwhich is prefixed in the build directory.",
                        tgt.name
                    ),
                );
            }
            if !in_source_build && in_source {
                self.ctx.error(
                    self.depender_backtrace(tgt),
                    format!(
                        "Target \"{}\" {prop} property contains path:\n  \"{item}\"\nwhich is prefixed in the source directory.",
                        tgt.name
                    ),
                );
            }
        }
        !had_fatal
    }

    /// `PopulateIncludeDirectoriesInterface` (install).
    fn include_directories(
        &mut self,
        tgt: &Target,
        te: &ExportTarget,
        includes_dest: &mut String,
        props: &mut BTreeMap<String, String>,
    ) {
        const KEY: &str = "INTERFACE_INCLUDE_DIRECTORIES";
        includes_dest.clear();
        let input = tgt.props.get(KEY);
        let dirs = genex::preprocess(
            &te.includes.join(";"),
            genex::PreprocessContext::InstallInterface,
            self.import_prefix_slash(),
        );
        let mut dirs = genex::replace_install_prefix(&dirs, self.import_prefix());
        self.replace_install_prefix(&mut dirs);
        let (export_dirs, context_sensitive) = self.eval(&dirs, tgt, "");
        if context_sensitive {
            self.ctx.error(
                self.depender_backtrace(tgt),
                format!(
                    "Target \"{}\" is installed with INCLUDES DESTINATION set to a context sensitive path.  Paths which depend on the configuration, policy values or the link interface are not supported.  Consider using target_include_directories instead.",
                    tgt.name
                ),
            );
            return;
        }
        if input.is_none() && export_dirs.is_empty() {
            return;
        }
        if input == Some("") && export_dirs.is_empty() {
            props.insert(KEY.to_owned(), String::new());
            return;
        }
        let export_dirs = self.add_import_prefix(&export_dirs);
        *includes_dest = export_dirs.clone();
        let mut includes = input.unwrap_or_default().to_owned();
        if input.is_some() {
            includes.push(';');
        }
        includes.push_str(&export_dirs);
        let mut prepro = genex::preprocess(
            &includes,
            genex::PreprocessContext::InstallInterface,
            self.import_prefix_slash(),
        );
        if !prepro.is_empty() {
            self.resolve_genex(&mut prepro, tgt);
            if !self.check_interface_dirs(&prepro, tgt, KEY) {
                return;
            }
            props.insert(KEY.to_owned(), prepro);
        }
    }

    /// `PopulateCxxModuleExportProperties`.
    fn cxx_module_properties(
        &mut self,
        tgt: &Target,
        rule: genex::PreprocessContext,
        includes_dest: &str,
        props: &mut BTreeMap<String, String>,
    ) {
        if !self.have_cxx20_module_sources(tgt) {
            return;
        }
        for (key, always) in [("CXX_EXTENSIONS", false), ("CXX_MODULE_STD", true)] {
            match tgt.props.get(key) {
                Some(value) => {
                    props.insert(key.to_owned(), genex::preprocess(value, rule, ""));
                }
                None if always => {
                    props.insert(key.to_owned(), String::new());
                }
                None => {}
            }
        }
        for (key, kind) in [
            ("INCLUDE_DIRECTORIES", "include"),
            ("COMPILE_DEFINITIONS", "strings"),
            ("COMPILE_OPTIONS", "strings"),
            ("COMPILE_FEATURES", "strings"),
        ] {
            let Some(value) = tgt.props.get(key) else {
                continue;
            };
            let out_key = format!("IMPORTED_CXX_MODULES_{key}");
            let mut value = genex::preprocess(value, rule, "");
            if self.installed && kind != "strings" {
                self.replace_install_prefix(&mut value);
                value = self.add_import_prefix(&value);
                if kind == "include" && !includes_dest.is_empty() {
                    if !value.is_empty() {
                        value.push(';');
                    }
                    value.push_str(includes_dest);
                }
            }
            props.insert(out_key, value);
        }
        let Some(link) = tgt.props.get("LINK_LIBRARIES") else {
            return;
        };
        let mut value = genex::preprocess(link, rule, "");
        self.resolve_genexes(&mut value, tgt);
        props.insert("IMPORTED_CXX_MODULES_LINK_LIBRARIES".into(), value);
    }

    /// `PopulateExportProperties`.
    fn export_properties(&self, tgt: &Target, props: &mut BTreeMap<String, String>) {
        let Some(export_props) = tgt.props.get("EXPORT_PROPERTIES") else {
            return;
        };
        for prop in expand_list(export_props, false) {
            if prop.starts_with("IMPORTED_") || prop.starts_with("INTERFACE_") {
                self.ctx.error(
                    self.depender_backtrace(tgt),
                    format!(
                        "Target \"{}\" contains property \"{prop}\" in EXPORT_PROPERTIES but IMPORTED_* and INTERFACE_* properties are reserved.",
                        tgt.name
                    ),
                );
                continue;
            }
            let Some(value) = tgt.props.get(&prop) else {
                continue;
            };
            if genex::strip(value) != *value {
                self.ctx.error(
                    self.depender_backtrace(tgt),
                    format!(
                        "Target \"{}\" contains property \"{prop}\" in EXPORT_PROPERTIES but this property contains a generator expression. This is not allowed.",
                        tgt.name
                    ),
                );
                continue;
            }
            props.insert(prop, value.to_owned());
        }
    }

    /// `PopulateCompatibleInterfaceProperties`.
    fn compatible_properties(&mut self, tgt: &Target, props: &mut BTreeMap<String, String>) {
        const KINDS: [&str; 4] = [
            "COMPATIBLE_INTERFACE_BOOL",
            "COMPATIBLE_INTERFACE_STRING",
            "COMPATIBLE_INTERFACE_NUMBER_MIN",
            "COMPATIBLE_INTERFACE_NUMBER_MAX",
        ];
        for key in KINDS {
            self.raw_property(key, tgt, props);
        }
        let mut iface_properties = BTreeSet::new();
        for key in KINDS {
            if let Some(value) = tgt.props.get(key) {
                iface_properties.extend(expand_list(value, false));
            }
        }
        if tgt.kind != TargetKind::InterfaceLibrary && tgt.kind != TargetKind::ObjectLibrary {
            for config in &self.ctx.configs {
                let ctx = self.ctx.for_config(config);
                let language = target::linker_language(&ctx, tgt, config);
                let Some(info) = super::link::link_information(&ctx, tgt, config, &language) else {
                    self.ctx.error(
                        self.depender_backtrace(tgt),
                        format!(
                            "Exporting the target \"{}\" is not allowed since its linker language cannot be determined",
                            tgt.name
                        ),
                    );
                    continue;
                };
                for dep in info
                    .items
                    .iter()
                    .filter_map(|item| ctx.interp.ext.targets.get(item.target.as_ref()?))
                    .filter(|dep| dep.kind != TargetKind::ObjectLibrary)
                {
                    for key in KINDS {
                        if let Some(value) = dep.props.get(key) {
                            iface_properties.extend(expand_list(value, false));
                        }
                    }
                }
            }
        }
        for name in iface_properties {
            self.raw_property(&format!("INTERFACE_{name}"), tgt, props);
        }
    }

    /// `PopulateCustomTransitiveInterfaceProperties`.
    fn custom_transitive(
        &mut self,
        tgt: &Target,
        rule: genex::PreprocessContext,
        props: &mut BTreeMap<String, String>,
    ) {
        self.raw_property("TRANSITIVE_COMPILE_PROPERTIES", tgt, props);
        self.raw_property("TRANSITIVE_LINK_PROPERTIES", tgt, props);
        let mut iface_properties = BTreeSet::new();
        let mut collect = |t: &Target| {
            for key in [
                "TRANSITIVE_COMPILE_PROPERTIES",
                "TRANSITIVE_LINK_PROPERTIES",
            ] {
                if let Some(value) = t.props.get(key) {
                    iface_properties.extend(expand_list(value, false));
                }
            }
        };
        collect(tgt);
        for dep in target::link_closure(self.ctx, tgt, &self.ctx.config) {
            collect(dep);
        }
        for name in iface_properties {
            self.interface_property(&name.clone(), &name, tgt, rule, props);
        }
    }

    /// `PopulateInterfaceLinkLibrariesProperty`; returns whether any link
    /// interface property survived preprocessing.
    fn link_libraries_properties(
        &mut self,
        tgt: &Target,
        rule: genex::PreprocessContext,
        props: &mut BTreeMap<String, String>,
    ) -> bool {
        if !is_linkable(tgt) {
            return false;
        }
        let mut had = false;
        for key in [
            "INTERFACE_LINK_LIBRARIES",
            "INTERFACE_LINK_LIBRARIES_DIRECT",
            "INTERFACE_LINK_LIBRARIES_DIRECT_EXCLUDE",
        ] {
            let Some(input) = tgt.props.get(key) else {
                continue;
            };
            let mut prepro = genex::preprocess(input, rule, "");
            if !prepro.is_empty() {
                self.resolve_genexes(&mut prepro, tgt);
                props.insert(key.to_owned(), prepro);
                had = true;
            }
        }
        had
    }

    /// `PopulateInterfaceProperties` + `PopulateInterfaceLinkLibrariesProperty`
    /// for `.cmake` exports (`GenerateImportTargetData` / `GenerateMainFile`
    /// usage): build exports use the `BuildInterface` rule.
    fn populate_interface_props(&mut self, record: &Record<'_>) -> BTreeMap<String, String> {
        let rule = if self.installed {
            genex::PreprocessContext::InstallInterface
        } else {
            genex::PreprocessContext::BuildInterface
        };
        self.populate_interface_props_rule(record, rule)
    }

    /// `PopulateInterfaceProperties` followed by
    /// `PopulateInterfaceLinkLibrariesProperty` with the given preprocess rule
    /// (`InstallInterface` for CPS output in both build and install trees).
    pub(super) fn populate_interface_props_rule(
        &mut self,
        record: &Record<'_>,
        link_rule: genex::PreprocessContext,
    ) -> BTreeMap<String, String> {
        let tgt = record.target;
        let rule = if self.installed {
            genex::PreprocessContext::InstallInterface
        } else {
            genex::PreprocessContext::BuildInterface
        };
        let mut props = BTreeMap::new();
        let mut includes_dest = String::new();
        if self.installed {
            self.interface_property(
                "INTERFACE_SYSTEM_INCLUDE_DIRECTORIES",
                "INTERFACE_SYSTEM_INCLUDE_DIRECTORIES",
                tgt,
                rule,
                &mut props,
            );
            self.include_directories(
                tgt,
                record.installed.unwrap(),
                &mut includes_dest,
                &mut props,
            );
            self.path_property("INTERFACE_LINK_DIRECTORIES", tgt, &mut props);
            self.path_property("INTERFACE_LINK_DEPENDS", tgt, &mut props);
            self.path_property("INTERFACE_SOURCES", tgt, &mut props);
        } else {
            // `AppendBuildInterfaceIncludes` ran at generate time via
            // `FinalizeTargetConfiguration`, so the property already carries
            // the build-interface directories.
            let include_value = tgt
                .props
                .get("INTERFACE_INCLUDE_DIRECTORIES")
                .map(str::to_owned);
            if let Some(input) = include_value.as_deref() {
                if input.is_empty() {
                    props.insert("INTERFACE_INCLUDE_DIRECTORIES".into(), String::new());
                } else {
                    let mut prepro = genex::preprocess(input, rule, "");
                    if !prepro.is_empty() {
                        self.resolve_genex(&mut prepro, tgt);
                        props.insert("INTERFACE_INCLUDE_DIRECTORIES".into(), prepro);
                    }
                }
            }
            self.interface_property(
                "INTERFACE_LINK_DIRECTORIES",
                "INTERFACE_LINK_DIRECTORIES",
                tgt,
                rule,
                &mut props,
            );
            self.interface_property(
                "INTERFACE_LINK_DEPENDS",
                "INTERFACE_LINK_DEPENDS",
                tgt,
                rule,
                &mut props,
            );
            self.interface_property(
                "INTERFACE_SOURCES",
                "INTERFACE_SOURCES",
                tgt,
                rule,
                &mut props,
            );
        }
        self.shared_properties(tgt, rule, &includes_dest, &mut props);
        let had_link = self.link_libraries_properties(tgt, link_rule, &mut props);
        if self.installed {
            if had_link && !self.options.old_link_interface {
                self.bump((2, 8, 12));
            }
            if tgt.props.contains("INTERFACE_SOURCES") {
                self.bump((3, 1, 0));
            }
        }
        props
    }

    /// `PopulateInterfaceProperties` shared tail (compile props, CXX module
    /// props, custom/exported props, compatible and transitive properties).
    fn shared_properties(
        &mut self,
        tgt: &Target,
        rule: genex::PreprocessContext,
        includes_dest: &str,
        props: &mut BTreeMap<String, String>,
    ) {
        for key in [
            "INTERFACE_COMPILE_DEFINITIONS",
            "INTERFACE_COMPILE_OPTIONS",
            "INTERFACE_PRECOMPILE_HEADERS",
            "INTERFACE_AUTOUIC_OPTIONS",
            "INTERFACE_AUTOMOC_MACRO_NAMES",
            "INTERFACE_COMPILE_FEATURES",
            "INTERFACE_LINK_OPTIONS",
        ] {
            self.interface_property(key, key, tgt, rule, props);
        }
        self.interface_property(
            "INTERFACE_POSITION_INDEPENDENT_CODE",
            "INTERFACE_POSITION_INDEPENDENT_CODE",
            tgt,
            rule,
            props,
        );
        self.interface_property("SPDX_LICENSE", "SPDX_LICENSE", tgt, rule, props);
        self.cxx_module_properties(tgt, rule, includes_dest, props);
        self.export_properties(tgt, props);
        self.compatible_properties(tgt, props);
        self.custom_transitive(tgt, rule, props);
    }

    /// `HaveCxx20ModuleSources` (with the missing-file-set diagnostic).
    fn have_cxx20_module_sources(&self, tgt: &Target) -> bool {
        let mut have = false;
        for name in expand_list(tgt.props.get("HEADER_SETS").unwrap_or_default(), false)
            .into_iter()
            .chain(expand_list(
                tgt.props.get("CXX_MODULE_SETS").unwrap_or_default(),
                false,
            ))
        {
            match tgt.file_sets.get(&name) {
                Some(set) if set.kind == "CXX_MODULES" => have = true,
                Some(_) => {}
                None => {
                    self.ctx.error(
                        self.depender_backtrace(tgt),
                        format!(
                            "Target \"{}\" is tracked to have file set \"{name}\", but it was not found.",
                            tgt.name
                        ),
                    );
                }
            }
        }
        have
    }

    /// `cge->Evaluate(lg, config, target)` for an entry string; returns the
    /// result and whether it had a context-sensitive condition.
    fn eval(&self, text: &str, tgt: &Target, config: &str) -> (String, bool) {
        self.eval_entry(text, tgt, config, None)
    }

    fn eval_entry(
        &self,
        text: &str,
        tgt: &Target,
        config: &str,
        backtrace: Option<Vec<Frame>>,
    ) -> (String, bool) {
        if genex::find(text).is_none() {
            return (text.to_owned(), false);
        }
        let key = self.ctx.target_key(tgt);
        let mut ectx = genex::EvalContext {
            config,
            head_target: Some(&key),
            current_target: Some(&key),
            evaluate_for_buildsystem: true,
            ..Default::default()
        };
        let mut host = CtxHost::new(self.ctx, tgt.makefile);
        match genex::evaluate(&genex::parse(text), &mut ectx, &mut host) {
            Ok(value) => (value, ectx.context_sensitive),
            Err(error) => {
                if !error.quiet {
                    let bt = self.ctx.backtrace(error.backtrace);
                    let bt = if bt.is_empty() {
                        backtrace.unwrap_or_default()
                    } else {
                        bt
                    };
                    self.ctx.genex_error(bt, &error);
                }
                (String::new(), ectx.context_sensitive)
            }
        }
    }

    /// `CollectExports`: resolve the export's target names, deduplicate, and
    /// record every exported target for later namespace resolution.
    pub(super) fn collect(
        &mut self,
        set: Option<&'a ExportSet>,
        targets: &[String],
        dir: usize,
    ) -> Vec<Record<'a>> {
        let mut records = Vec::new();
        let mut failed = false;
        let mut visit = |item: Option<&'a ExportTarget>, name: &str| {
            let Some(tgt) = self.find(dir, name) else {
                return;
            };
            let ptr = std::ptr::from_ref(tgt);
            if !self.exported.insert(ptr) {
                if self.installed {
                    self.report_error(format!(
                        "install({} \"{}\" ...) includes target \"{}\" more than once in the export set.",
                        if self.package.is_some() { "PACKAGE_INFO" } else { "EXPORT" },
                        self.export_label,
                        tgt.name
                    ));
                } else {
                    self.report_error(format!("given target \"{}\" more than once.", tgt.name));
                }
                failed = true;
                return;
            }
            // `GetExportTargetType`: an OBJECT library installed with no
            // OBJECTS DESTINATION is transformed to an INTERFACE library.
            let kind = if self.installed
                && tgt.kind == TargetKind::ObjectLibrary
                && item.is_some_and(|item| item.objects.is_none())
            {
                TargetKind::InterfaceLibrary
            } else {
                tgt.kind
            };
            if kind == TargetKind::InterfaceLibrary {
                self.bump((3, 0, 0));
            }
            records.push(Record {
                target: tgt,
                installed: item,
                kind,
                name: format!("{}{}", self.namespace, export_name(tgt)),
                xcframework: item
                    .and_then(|item| set.and_then(|set| set.xcframework_locations.get(&item.name)))
                    .map(String::as_str),
            });
        };
        if let Some(set) = set {
            for item in &set.targets {
                if item.namelink_only {
                    continue;
                }
                visit(Some(item), &item.name);
            }
        } else {
            for name in targets {
                visit(None, name);
            }
        }
        if failed {
            return Vec::new();
        }
        records
    }

    /// `GenerateImportTargetsConfig` — per-configuration properties.
    fn config_targets(&mut self, out: &mut String, records: &[Record<'_>], config: &str) {
        let upper = config_suffix(config).to_ascii_uppercase();
        let suffix = format!("_{upper}");
        for record in records {
            let tgt = record.target;
            let name = &record.name;
            if record.kind == TargetKind::InterfaceLibrary {
                continue;
            }
            // `PopulateImportProperties`.
            let Some((mut properties, locations)) =
                self.location_properties(record, config, &suffix)
            else {
                continue;
            };
            // `GetImportXcFrameworkLocation`.
            let xcframework = self.xcframework_location(record, config);
            // `SetImportLinkInterface` (old-style).
            self.link_interface(config, &suffix, tgt, &mut properties);
            // `GenerateImportPropertyCode`.
            writeln!(
                out,
                "# Import target \"{name}\" for configuration \"{config}\"\nset_property(TARGET {name} APPEND PROPERTY IMPORTED_CONFIGURATIONS {upper})\nset_target_properties({name} PROPERTIES"
            )
            .unwrap();
            // An XCFramework location replaces the ordinary
            // IMPORTED_LOCATION with a conditional pick below.
            let location_prop = format!("IMPORTED_LOCATION{suffix}");
            for (key, value) in &properties {
                if !xcframework.is_empty() && *key == location_prop {
                    continue;
                }
                writeln!(out, "  {key} {}", export_escape(value)).unwrap();
            }
            out.push_str("  )\n");
            if !xcframework.is_empty()
                && let Some(original) = properties.get(&location_prop)
            {
                writeln!(
                    out,
                    "if(NOT CMAKE_VERSION VERSION_LESS \"3.28\" AND IS_DIRECTORY {})",
                    export_escape(&xcframework)
                )
                .unwrap();
                writeln!(
                    out,
                    "  set_property(TARGET {name} PROPERTY {location_prop} {})",
                    export_escape(&xcframework)
                )
                .unwrap();
                writeln!(
                    out,
                    "else()\n  set_property(TARGET {name} PROPERTY {location_prop} {})",
                    export_escape(original)
                )
                .unwrap();
                out.push_str("endif()\n");
            }
            out.push('\n');
            // `GenerateImportedFileChecksCode`.
            if self.installed {
                writeln!(out, "list(APPEND _cmake_import_check_targets {name} )").unwrap();
                if !xcframework.is_empty() {
                    writeln!(
                        out,
                        "set(_cmake_import_check_xcframework_for_{name} {})",
                        export_escape(&xcframework)
                    )
                    .unwrap();
                }
                write!(out, "list(APPEND _cmake_import_check_files_for_{name} ").unwrap();
                for prop in &locations {
                    if let Some(value) = properties.get(prop) {
                        write!(out, "{} ", export_escape(value)).unwrap();
                    }
                }
                out.push_str(")\n\n");
            }
        }
    }

    /// `PopulateImportProperties`: the `SetImportLocationProperty` calls for
    /// each artifact generator plus `SetImportDetailProperties`.  Returns
    /// `None` when no import location exists for `config`.
    pub(super) fn location_properties(
        &mut self,
        record: &Record<'_>,
        config: &str,
        suffix: &str,
    ) -> Option<(BTreeMap<String, String>, BTreeSet<String>)> {
        let tgt = record.target;
        let mut properties = BTreeMap::new();
        let mut locations = BTreeSet::new();
        if self.installed {
            // `cmExportInstallFileGenerator::PopulateImportProperties`: one
            // `SetImportLocationProperty` call per install generator.
            if let Some(item) = record.installed {
                // `IsImportLibrary`: the ARCHIVE generator installs the
                // import library of shared libraries and of executables
                // with exports; only static libraries install the real
                // artifact through it.
                let implib = matches!(tgt.kind, TargetKind::SharedLibrary | TargetKind::Executable);
                for (itgen, implib) in [
                    (item.archive.as_ref(), implib),
                    (item.library.as_ref(), false),
                    (item.runtime.as_ref(), false),
                    (item.objects.as_ref(), false),
                    (item.framework.as_ref(), false),
                    (item.bundle.as_ref(), false),
                ] {
                    self.set_import_location_property(
                        tgt,
                        itgen,
                        implib,
                        config,
                        suffix,
                        &mut properties,
                        &mut locations,
                    );
                }
            }
        } else {
            // `cmExportBuildFileGenerator::SetImportLocationProperty`.
            if tgt.kind == TargetKind::ObjectLibrary {
                let prop = format!("IMPORTED_OBJECTS{suffix}");
                let base = target::object_directory(self.ctx, tgt, config);
                let files: Vec<String> = super::install::object_source_names(self.ctx, tgt)
                    .iter()
                    .map(|name| format!("{base}{name}"))
                    .collect();
                properties.insert(prop.clone(), files.join(";"));
                locations.insert(prop);
            } else {
                // The main target file; application bundles take the
                // non-real path because the bundle directory is part of it.
                let prop = format!("IMPORTED_LOCATION{suffix}");
                let location = target::full_path(
                    self.ctx,
                    tgt,
                    config,
                    target::ArtifactType::Runtime,
                    !tgt.is_app_bundle_on_apple(),
                );
                properties.insert(prop.clone(), location);
                locations.insert(prop);
                // Add the import library for windows DLLs.
                if target::has_import_library(self.ctx, tgt, config) {
                    let prop = format!("IMPORTED_IMPLIB{suffix}");
                    let mut value = target::full_path(
                        self.ctx,
                        tgt,
                        config,
                        target::ArtifactType::Import,
                        true,
                    );
                    // `cmGeneratorTarget::GetImplibGNUtoMS`.
                    if self
                        .ctx
                        .var(tgt.makefile, "CMAKE_IMPORT_LIBRARY_SUFFIX")
                        .is_some()
                        && let Some(converted) = install_name::implib_gnu_to_ms(
                            self.ctx,
                            tgt,
                            config,
                            &value,
                            Some("${CMAKE_IMPORT_LIBRARY_SUFFIX}"),
                        )
                    {
                        value = converted;
                    }
                    properties.insert(prop.clone(), value);
                    locations.insert(prop);
                }
            }
        }
        if properties.is_empty() {
            return None;
        }
        // `SetImportDetailProperties`.
        self.detail_properties(record, config, suffix, &mut properties);
        Some((properties, locations))
    }

    /// `cmExportInstallFileGenerator::SetImportLocationProperty`: the
    /// location properties one install generator (`itgen`) contributes.
    #[allow(clippy::too_many_arguments)]
    fn set_import_location_property(
        &self,
        tgt: &Target,
        itgen: Option<&InstallOptions>,
        implib: bool,
        config: &str,
        suffix: &str,
        properties: &mut BTreeMap<String, String>,
        locations: &mut BTreeSet<String>,
    ) {
        // Skip rules that do not match this configuration.
        let Some(itgen) = itgen.filter(|itgen| generates_for_config(&itgen.configurations, config))
        else {
            return;
        };
        // Construct the installed location of the target.
        let dest = self.eval(&itgen.destination, tgt, config).0;
        let mut value = String::new();
        if !is_full_path(&dest) {
            value.push_str(self.import_prefix_slash());
        }
        value.push_str(&dest);
        value.push('/');
        if implib {
            let prop = format!("IMPORTED_IMPLIB{suffix}");
            value.push_str(&install_filename(
                self.ctx,
                tgt,
                config,
                InstallFilename::ImplibReal,
            ));
            properties.insert(prop.clone(), value);
            locations.insert(prop);
        } else if tgt.kind == TargetKind::ObjectLibrary {
            let prop = format!("IMPORTED_OBJECTS{suffix}");
            // `GetInstallObjectNames`: each object below the per-config
            // `computeInstallObjectDir` subdirectory.
            let files: Vec<String> = object_names(self.ctx, tgt)
                .iter()
                .map(|name| format!("{value}{}/{name}", object_subdir(tgt, config)))
                .collect();
            properties.insert(prop.clone(), files.join(";"));
            locations.insert(prop);
        } else {
            if tgt.is_framework_on_apple() && target::has_import_library(self.ctx, tgt, config) {
                // Store as well the implib that lives inside the framework.
                let prop = format!("IMPORTED_IMPLIB{suffix}");
                properties.insert(
                    prop.clone(),
                    format!(
                        "{value}{}",
                        install_filename(self.ctx, tgt, config, InstallFilename::ImplibReal)
                    ),
                );
                locations.insert(prop);
            }
            let prop = format!("IMPORTED_LOCATION{suffix}");
            if tgt.is_app_bundle_on_apple() {
                value.push_str(&install_filename(
                    self.ctx,
                    tgt,
                    config,
                    InstallFilename::Normal,
                ));
                value.push_str(".app/");
                if !target::apple_embedded(self.ctx, tgt) {
                    value.push_str("Contents/MacOS/");
                }
                value.push_str(&install_filename(
                    self.ctx,
                    tgt,
                    config,
                    InstallFilename::Normal,
                ));
            } else {
                value.push_str(&install_filename(
                    self.ctx,
                    tgt,
                    config,
                    InstallFilename::Real,
                ));
            }
            properties.insert(prop.clone(), value);
            locations.insert(prop);
        }
    }

    /// `cmExportInstallFileGenerator::GetImportXcFrameworkLocation` and the
    /// build-tree equivalent in `cmExportBuildCMakeConfigGenerator`'s
    /// `GenerateImportTargetsConfig`.
    fn xcframework_location(&self, record: &Record<'_>, config: &str) -> String {
        let Some(mut location) = record.xcframework.map(str::to_owned) else {
            return String::new();
        };
        if location.is_empty() {
            return location;
        }
        if self.installed {
            location = genex::preprocess(
                &location,
                genex::PreprocessContext::InstallInterface,
                self.import_prefix_slash(),
            );
            location = self.eval(&location, record.target, config).0;
            if !location.is_empty()
                && !is_full_path(&location)
                && !location.starts_with(self.import_prefix_slash())
            {
                return format!("{}{location}", self.import_prefix_slash());
            }
        } else {
            location = genex::preprocess(&location, genex::PreprocessContext::BuildInterface, "");
            location = self.eval(&location, record.target, config).0;
            if !location.is_empty() && !is_full_path(&location) {
                // `LG->GetCurrentBinaryDirectory()`.
                location = format!(
                    "{}/{location}",
                    self.ctx.interp.makefiles[self.error_dir].binary_dir
                );
            }
        }
        location
    }

    /// `SetImportDetailProperties`.
    fn detail_properties(
        &mut self,
        record: &Record<'_>,
        config: &str,
        suffix: &str,
        props: &mut BTreeMap<String, String>,
    ) {
        let tgt = record.target;
        // Add the soname for unix shared libraries.
        if matches!(
            tgt.kind,
            TargetKind::SharedLibrary | TargetKind::ModuleLibrary
        ) && !tgt.platform.dll
        {
            let names = target::names(self.ctx, tgt, config);
            if target::has_soname(self.ctx, tgt, config) {
                let mut value = String::new();
                if is_on(
                    &self
                        .ctx
                        .var_safe(tgt.makefile, "CMAKE_PLATFORM_HAS_INSTALLNAME"),
                ) {
                    // `cmExportInstallFileGenerator::InstallNameDir` /
                    // `cmExportBuildFileGenerator::InstallNameDir`.
                    value = if self.installed {
                        install_name::install_name_dir_for_install_tree(
                            self.ctx,
                            tgt,
                            config,
                            self.import_prefix(),
                        )
                    } else {
                        install_name::install_name_dir_for_build_tree(self.ctx, tgt, config)
                    };
                }
                value.push_str(&names.shared_object);
                props.insert(format!("IMPORTED_SONAME{suffix}"), value);
            } else {
                props.insert(format!("IMPORTED_NO_SONAME{suffix}"), "TRUE".into());
            }
        }
        if !self.link_interface_exists(tgt) {
            self.managed_property(tgt, suffix, props);
            return;
        }
        // IMPORTED_LINK_INTERFACE_LANGUAGES (only static libraries
        // propagate their link implementation languages).
        if tgt.kind == TargetKind::StaticLibrary {
            let languages = target::link_implementation_languages(self.ctx, tgt, config);
            if !languages.is_empty() {
                props.insert(
                    format!("IMPORTED_LINK_INTERFACE_LANGUAGES{suffix}"),
                    languages.join(";"),
                );
            }
        }
        // IMPORTED_LINK_DEPENDENT_LIBRARIES: runtime dependencies of shared
        // libraries not already in the link interface.
        if matches!(
            tgt.kind,
            TargetKind::SharedLibrary | TargetKind::StaticLibrary | TargetKind::InterfaceLibrary
        ) && tgt.kind != TargetKind::InterfaceLibrary
        {
            // Targets are identified by themselves, other items by their text.
            let identity = |dep: Option<&Target>, name: &str| match dep {
                Some(dep) => (std::ptr::from_ref(dep) as usize, String::new()),
                None => (0, name.to_string()),
            };
            let mut emitted: HashSet<(usize, String)> =
                target::evaluated_links(self.ctx, tgt, tgt, "INTERFACE_LINK_LIBRARIES")
                    .iter()
                    .map(|name| identity(self.resolve(tgt.makefile, name), name))
                    .collect();
            let old_missing = self.missing.len();
            let old_external = self.external.len();
            let mut shared_deps = Vec::new();
            for name in target::evaluated_links(self.ctx, tgt, tgt, "LINK_LIBRARIES") {
                let dep = self.resolve(tgt.makefile, &name);
                if emitted.insert(identity(dep, &name))
                    && dep.is_some_and(|d| d.kind == TargetKind::SharedLibrary)
                {
                    let mut item = name.clone();
                    self.add_target_namespace(&mut item, tgt, tgt.makefile);
                    shared_deps.push(item);
                }
            }
            self.missing.truncate(old_missing);
            self.external.truncate(old_external);
            if !shared_deps.is_empty() {
                props.insert(
                    format!("IMPORTED_LINK_DEPENDENT_LIBRARIES{suffix}"),
                    shared_deps.join(";"),
                );
            }
        }
        // IMPORTED_LINK_INTERFACE_MULTIPLICITY (static libraries).
        if tgt.kind == TargetKind::StaticLibrary {
            let value = tgt
                .props
                .get(&format!("LINK_INTERFACE_MULTIPLICITY{suffix}"))
                .or_else(|| tgt.props.get("LINK_INTERFACE_MULTIPLICITY"))
                .and_then(|value| value.trim().parse::<u32>().ok())
                .unwrap_or(0);
            if value > 0 {
                props.insert(
                    format!("IMPORTED_LINK_INTERFACE_MULTIPLICITY{suffix}"),
                    value.to_string(),
                );
            }
        }
        self.managed_property(tgt, suffix, props);
    }

    /// `cmGeneratorTarget::GetManagedType` → IMPORTED_COMMON_LANGUAGE_RUNTIME.
    fn managed_property(&self, tgt: &Target, suffix: &str, props: &mut BTreeMap<String, String>) {
        let managed = match tgt.kind {
            // `GetType() > SHARED_LIBRARY` ⇒ Undefined (emit).
            TargetKind::ModuleLibrary
            | TargetKind::ObjectLibrary
            | TargetKind::InterfaceLibrary
            | TargetKind::Utility
            | TargetKind::GlobalTarget
            | TargetKind::UnknownLibrary => true,
            TargetKind::StaticLibrary => false,
            TargetKind::Executable | TargetKind::SharedLibrary => {
                tgt.props.contains("COMMON_LANGUAGE_RUNTIME") || self.is_csharp_only(tgt)
            }
        };
        if !managed {
            return;
        }
        let value = tgt
            .props
            .get("COMMON_LANGUAGE_RUNTIME")
            .map(str::to_owned)
            .unwrap_or_else(|| {
                if self.is_csharp_only(tgt) {
                    "CSharp".to_owned()
                } else {
                    String::new()
                }
            });
        props.insert(format!("IMPORTED_COMMON_LANGUAGE_RUNTIME{suffix}"), value);
    }

    /// `cmGeneratorTarget::IsCSharpOnly`.
    fn is_csharp_only(&self, tgt: &Target) -> bool {
        if !matches!(
            tgt.kind,
            TargetKind::SharedLibrary | TargetKind::StaticLibrary | TargetKind::Executable
        ) {
            return false;
        }
        let mut languages: BTreeSet<String> =
            target::link_implementation_languages(self.ctx, tgt, &self.ctx.config)
                .into_iter()
                .collect();
        if let Some(lang) = tgt.props.get("LINKER_LANGUAGE").filter(|v| !v.is_empty()) {
            languages.insert(lang.to_owned());
        }
        languages.len() == 1 && languages.contains("CSharp")
    }

    /// `GetLinkInterface` presence: an explicit interface or an implicit one
    /// (non-executable, non-module).
    fn link_interface_exists(&self, tgt: &Target) -> bool {
        if tgt.kind == TargetKind::Executable && !exe_with_exports(tgt) {
            return false;
        }
        let explicit = [
            "INTERFACE_LINK_LIBRARIES",
            "INTERFACE_LINK_LIBRARIES_DIRECT",
            "INTERFACE_LINK_LIBRARIES_DIRECT_EXCLUDE",
        ]
        .iter()
        .any(|key| tgt.props.get(key).is_some());
        explicit || !matches!(tgt.kind, TargetKind::Executable | TargetKind::ModuleLibrary)
    }

    /// `SetImportLinkInterface` (old-style LINK_INTERFACE_LIBRARIES).
    fn link_interface(
        &mut self,
        config: &str,
        suffix: &str,
        tgt: &Target,
        props: &mut BTreeMap<String, String>,
    ) {
        let _ = config;
        if !self.link_interface_exists(tgt) {
            return;
        }
        let content = tgt
            .props
            .get(&format!("LINK_INTERFACE_LIBRARIES{suffix}"))
            .or_else(|| tgt.props.get("LINK_INTERFACE_LIBRARIES"));
        let Some(content) = content else { return };
        if !self.options.old_link_interface {
            self.ctx.error(
                self.depender_backtrace(tgt),
                format!(
                    "Target \"{}\" has policy CMP0022 enabled, but also has old-style LINK_INTERFACE_LIBRARIES properties populated, but it was exported without the EXPORT_LINK_INTERFACE_LIBRARIES to export the old-style properties",
                    tgt.name
                ),
            );
            return;
        }
        let out_key = format!("IMPORTED_LINK_INTERFACE_LIBRARIES{suffix}");
        if content.is_empty() {
            props.insert(out_key, String::new());
            return;
        }
        let rule = if self.installed {
            genex::PreprocessContext::InstallInterface
        } else {
            genex::PreprocessContext::BuildInterface
        };
        let mut prepro = genex::preprocess(content, rule, "");
        if !prepro.is_empty() {
            self.resolve_genexes(&mut prepro, tgt);
            props.insert(out_key, prepro);
        }
    }
}

fn write_properties(out: &mut String, properties: &BTreeMap<String, String>) {
    for (key, value) in properties {
        writeln!(out, "  {key} {}", export_escape(value)).unwrap();
    }
}

/// `cmInstallTargetGenerator::NameType` values the export writers use.
#[derive(Clone, Copy, PartialEq, Eq)]
enum InstallFilename {
    Normal,
    Real,
    Implib,
    ImplibReal,
}

/// `cmInstallTargetGenerator::GetInstallFilename`, including the
/// `GNUtoMS` import-library name conversion.
fn install_filename(ctx: &GenCtx, tgt: &Target, config: &str, kind: InstallFilename) -> String {
    let names = target::names(ctx, tgt, config);
    match kind {
        InstallFilename::Normal => names.output,
        InstallFilename::Real => names.real,
        InstallFilename::Implib | InstallFilename::ImplibReal => {
            let name = if kind == InstallFilename::Implib {
                names.import_library
            } else {
                names.import_real
            };
            install_name::implib_gnu_to_ms(
                ctx,
                tgt,
                config,
                &name,
                Some("${CMAKE_IMPORT_LIBRARY_SUFFIX}"),
            )
            .unwrap_or(name)
        }
    }
}

/// `cmFileSet::EvaluateDirectoryEntries`.
fn eval_dirs(
    ex: &Exporter<'_, '_>,
    file_set: &FileSet,
    tgt: &Target,
    config: &str,
) -> (Vec<String>, bool) {
    let source_dir = &ex.ctx.interp.makefiles[tgt.makefile].source_dir;
    let mut sensitive = false;
    let mut collapsed: Vec<String> = Vec::new();
    let mut result: Vec<String> = Vec::new();
    'entries: for (value, bt) in file_set.base_dirs.iter().flat_map(|(value, bt)| {
        expand_list(value, false)
            .into_iter()
            .map(|v| (v, bt.clone()))
    }) {
        let (entry, cs) = ex.eval_entry(&value, tgt, config, Some(bt.clone()));
        sensitive |= cs;
        for dir in expand_list(&entry, false) {
            let dir = if is_full_path(&dir) {
                dir
            } else {
                format!("{source_dir}/{dir}")
            };
            let collapsed_dir = collapse_full_path(&dir, source_dir);
            for (i, prior) in collapsed.iter().enumerate() {
                if is_subdirectory(&collapsed_dir, prior) || is_subdirectory(prior, &collapsed_dir)
                {
                    ex.ctx.error(
                        bt.clone(),
                        format!(
                            "Base directories in file set cannot be subdirectories of each other:\n  {}\n  {dir}",
                            result[i]
                        ),
                    );
                    continue 'entries;
                }
            }
            collapsed.push(collapsed_dir);
            result.push(dir);
        }
    }
    (result, sensitive)
}

/// `cmFileSet::EvaluateFileEntry` over all entries → relDir → files map.
fn eval_files(
    ex: &Exporter<'_, '_>,
    file_set: &FileSet,
    tgt: &Target,
    config: &str,
    dirs: &[String],
) -> (BTreeMap<String, Vec<String>>, bool) {
    let source_dir = &ex.ctx.interp.makefiles[tgt.makefile].source_dir;
    let mut sensitive = false;
    let mut files: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for (value, bt) in file_set.files.iter().flat_map(|(value, bt)| {
        expand_list(value, false)
            .into_iter()
            .map(|v| (v, bt.clone()))
    }) {
        let (entry, cs) = ex.eval_entry(&value, tgt, config, Some(bt.clone()));
        sensitive |= cs;
        for file in expand_list(&entry, false) {
            let file = if is_full_path(&file) {
                file
            } else {
                format!("{source_dir}/{file}")
            };
            let collapsed = collapse_full_path(&file, source_dir);
            let rel_dir = dirs.iter().find_map(|dir| {
                let base = collapse_full_path(dir, source_dir);
                is_subdirectory(&collapsed, &base).then(|| {
                    let rel = collapsed
                        .strip_prefix(&format!("{base}/"))
                        .unwrap_or(&collapsed);
                    filename_path(rel)
                })
            });
            match rel_dir {
                Some(rel_dir) => files.entry(rel_dir).or_default().push(file),
                None => {
                    let mut e = format!(
                        "File:\n  {file}\nmust be in one of the file set's base directories:"
                    );
                    for dir in dirs {
                        e.push_str("\n  ");
                        e.push_str(dir);
                    }
                    ex.ctx.error(bt.clone(), e);
                    return (files, sensitive);
                }
            }
        }
    }
    (files, sensitive)
}

/// `GetFileSetDirectories`/`GetFileSetFiles`.
fn file_set_dirs_files(
    ex: &Exporter<'_, '_>,
    tgt: &Target,
    file_set: &FileSet,
    set_name: &str,
    record: &Record<'_>,
) -> (String, String) {
    let config = &ex.ctx.config;
    let kind = &file_set.kind;
    let module_error = |what: &str| {
        ex.report_error(format!(
            "The \"{}\" target's interface file set \"{set_name}\" of type \"{kind}\" contains context-sensitive {what} which is not supported.",
            tgt.name
        ));
        (String::new(), String::new())
    };
    if ex.installed {
        let dest_text = record
            .installed
            .and_then(|item| item.file_sets.get(set_name))
            .cloned()
            .unwrap_or_default();
        let (unescaped, dest_sensitive) = ex.eval(&dest_text, tgt, config);
        if dest_sensitive && kind == "CXX_MODULES" {
            return module_error("base file entries");
        }
        let mut dest = escape_nowrap(&unescaped);
        if !is_full_path(&unescaped) {
            dest = format!("{}{dest}", ex.import_prefix_slash());
        }
        let (dirs, dir_sensitive) = eval_dirs(ex, file_set, tgt, config);
        let (files, mut sensitive) = eval_files(ex, file_set, tgt, config, &dirs);
        sensitive |= dest_sensitive | dir_sensitive;
        if sensitive && kind == "CXX_MODULES" {
            return module_error("base file entries");
        }
        let mut file_out = Vec::new();
        for (rel, names) in &files {
            let prefix = if rel.is_empty() {
                String::new()
            } else {
                format!("{rel}/")
            };
            for file in names {
                file_out.push(format!(
                    "\"{}/{}{}\"",
                    dest,
                    escape_nowrap(&prefix),
                    escape_nowrap(&filename_name(file))
                ));
            }
        }
        (format!("\"{dest}\""), file_out.join(" "))
    } else {
        let (dirs, sensitive) = eval_dirs(ex, file_set, tgt, config);
        if sensitive && kind == "CXX_MODULES" {
            return module_error("base directory entries");
        }
        let dirs_out: Vec<String> = dirs
            .iter()
            // Kitware emits the first directory for a single configuration.
            .take(1)
            .map(|d| format!("\"{}\"", escape_nowrap(d)))
            .collect();
        let (files, file_sensitive) = eval_files(ex, file_set, tgt, config, &dirs);
        if file_sensitive && kind == "CXX_MODULES" {
            return module_error("file entries");
        }
        let mut file_out = Vec::new();
        for names in files.values() {
            for file in names {
                file_out.push(format!("\"{}\"", escape_nowrap(file)));
            }
        }
        (dirs_out.join(" "), file_out.join(" "))
    }
}

/// `GenerateTargetFileSets`.
fn write_target_file_sets(ex: &Exporter<'_, '_>, out: &mut String, record: &Record<'_>) {
    let tgt = record.target;
    let names: Vec<String> = expand_list(
        tgt.props.get("INTERFACE_HEADER_SETS").unwrap_or_default(),
        false,
    )
    .into_iter()
    .chain(expand_list(
        tgt.props
            .get("INTERFACE_CXX_MODULE_SETS")
            .unwrap_or_default(),
        false,
    ))
    .collect();
    if names.is_empty() {
        return;
    }
    let target_name = &record.name;
    let find_set = |name: &str| {
        tgt.file_sets.get(name).or_else(|| {
            ex.ctx.error(
                ex.depender_backtrace(tgt),
                format!(
                    "File set \"{name}\" is listed in interface file sets of {} but has not been created",
                    tgt.name
                ),
            );
            None
        })
    };
    out.push_str("if(NOT CMAKE_VERSION VERSION_LESS \"3.23.0\")\n");
    writeln!(out, "  target_sources({target_name}").unwrap();
    let mut sets = Vec::new();
    for name in &names {
        let Some(set) = find_set(name) else { return };
        sets.push((name, set));
    }
    for (name, set) in &sets {
        let (dirs, files) = file_set_dirs_files(ex, tgt, set, name, record);
        writeln!(
            out,
            "    INTERFACE\n      FILE_SET {}\n      TYPE {}\n      BASE_DIRS {dirs}\n      FILES {files}",
            escape_for_cmake(name),
            escape_for_cmake(&set.kind)
        )
        .unwrap();
    }
    write!(
        out,
        "  )\nelse()\n  set_property(TARGET {target_name}\n    APPEND PROPERTY INTERFACE_INCLUDE_DIRECTORIES"
    )
    .unwrap();
    for (name, set) in &sets {
        if set.kind == "HEADERS" {
            let (dirs, _) = file_set_dirs_files(ex, tgt, set, name, record);
            write!(out, "\n      {dirs}").unwrap();
        }
    }
    out.push_str("\n  )\nendif()\n\n");
}

/// `GenerateImportTargetCode`.
fn import_target_code(ctx: &GenCtx, out: &mut String, record: &Record<'_>) {
    let tgt = record.target;
    let name = &record.name;
    writeln!(out, "# Create imported target {name}").unwrap();
    match record.kind {
        TargetKind::Executable => writeln!(out, "add_executable({name} IMPORTED)").unwrap(),
        kind => {
            let k = match kind {
                TargetKind::StaticLibrary => "STATIC",
                TargetKind::SharedLibrary => "SHARED",
                TargetKind::ModuleLibrary => "MODULE",
                TargetKind::UnknownLibrary => "UNKNOWN",
                TargetKind::ObjectLibrary => "OBJECT",
                TargetKind::InterfaceLibrary => "INTERFACE",
                _ => unreachable!(),
            };
            writeln!(out, "add_library({name} {k} IMPORTED)").unwrap();
        }
    }
    // Mark the imported executable if it has exports.
    if exe_with_exports(tgt)
        || (tgt.is_shared_library_with_exports() && target::has_import_library(ctx, tgt, ""))
    {
        writeln!(out, "set_property(TARGET {name} PROPERTY ENABLE_EXPORTS 1)").unwrap();
    }
    // Mark the imported library if it is a framework.
    if tgt.is_framework_on_apple() {
        writeln!(out, "set_property(TARGET {name} PROPERTY FRAMEWORK 1)").unwrap();
    }
    // Mark the imported executable if it is an application bundle.
    if tgt.is_app_bundle_on_apple() {
        writeln!(out, "set_property(TARGET {name} PROPERTY MACOSX_BUNDLE 1)").unwrap();
    }
    if tgt.is_cf_bundle_on_apple() {
        writeln!(out, "set_property(TARGET {name} PROPERTY BUNDLE 1)").unwrap();
    }
    // Mark the imported library if it is an AIX shared library archive.
    if tgt.is_archived_aix_shared_library() {
        writeln!(
            out,
            "set_property(TARGET {name} PROPERTY AIX_SHARED_LIBRARY_ARCHIVE 1)"
        )
        .unwrap();
    }
    if let Some(value) = tgt.props.get("DEPRECATION").filter(|v| !v.is_empty()) {
        writeln!(
            out,
            "set_property(TARGET {name} PROPERTY DEPRECATION {})",
            export_escape(value)
        )
        .unwrap();
    }
    if is_on_opt(tgt.props.get("IMPORTED_NO_SYSTEM")) {
        writeln!(
            out,
            "set_property(TARGET {name} PROPERTY IMPORTED_NO_SYSTEM 1)"
        )
        .unwrap();
    }
    if is_on_opt(tgt.props.get("EXPORT_NO_SYSTEM")) {
        writeln!(out, "set_property(TARGET {name} PROPERTY SYSTEM 0)").unwrap();
    }
    out.push('\n');
}

/// `PopulateInterfaceProperties` + `GenerateInterfaceProperties` +
/// `GenerateTargetFileSets` for one record.
fn write_target(ex: &mut Exporter<'_, '_>, out: &mut String, record: &Record<'_>) {
    import_target_code(ex.ctx, out, record);
    let props = ex.populate_interface_props(record);
    if !props.is_empty() {
        writeln!(out, "set_target_properties({} PROPERTIES", record.name).unwrap();
        write_properties(out, &props);
        out.push_str(")\n\n");
    }
    write_target_file_sets(ex, out, record);
}

/// `GenerateMissingTargetsCheckCode`.
fn missing_targets(out: &mut String, missing: &[String]) {
    if missing.is_empty() {
        out.push_str(
            "# This file does not depend on other imported targets which have\n# been exported from the same project but in a separate export set.\n\n",
        );
        return;
    }
    out.push_str("# Make sure the targets which have been exported in some other\n# export set exist.\nunset(${CMAKE_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets)\nforeach(_target ");
    let mut emitted = BTreeSet::new();
    for target in missing {
        if emitted.insert(target) {
            write!(out, "\"{target}\" ").unwrap();
        }
    }
    out.push_str(
        ")\n  if(NOT TARGET \"${_target}\" )\n    set(${CMAKE_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets \"${${CMAKE_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets} ${_target}\")\n  endif()\nendforeach()\n\nif(DEFINED ${CMAKE_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets)\n  if(CMAKE_FIND_PACKAGE_NAME)\n    set( ${CMAKE_FIND_PACKAGE_NAME}_FOUND FALSE)\n    set( ${CMAKE_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE \"The following imported targets are referenced, but are missing: ${${CMAKE_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets}\")\n  else()\n    message(FATAL_ERROR \"The following imported targets are referenced, but are missing: ${${CMAKE_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets}\")\n  endif()\nendif()\nunset(${CMAKE_FIND_PACKAGE_NAME}_NOT_FOUND_MESSAGE_targets)\n\n",
    );
}

/// `GenerateFindDependencyCalls`.
fn package_dependencies(ex: &Exporter<'_, '_>, out: &mut String, set: &ExportSet) {
    out.push_str("include(CMakeFindDependencyMacro)\n");
    let mut deps: Vec<(String, String, Vec<String>)> = set.package_dependencies.clone();
    let mut inferred = BTreeMap::new();
    for ptr in &ex.external {
        let tgt = unsafe { &**ptr };
        let call = tgt.find_package_stack.last();
        let name = tgt
            .props
            .get("EXPORT_FIND_PACKAGE_NAME")
            .filter(|n| !n.is_empty())
            .map(str::to_owned)
            .or_else(|| call.map(|(name, _)| name.clone()));
        let Some(name) = name else { continue };
        if name.is_empty() {
            continue;
        }
        match deps.iter_mut().find(|(pkg, _, _)| *pkg == name) {
            Some((_, enabled, _)) => {
                if enabled.is_empty() || enabled.eq_ignore_ascii_case("auto") {
                    *enabled = "ON".to_owned();
                }
            }
            None => {
                let index = inferred.entry(name).or_insert(u32::MAX);
                if let Some((_, call_index)) = call {
                    *index = *call_index;
                }
            }
        }
    }
    let mut inferred: Vec<_> = inferred.into_iter().collect();
    inferred.sort_by_key(|(_, index)| *index);
    deps.extend(
        inferred
            .into_iter()
            .map(|(name, _)| (name, "ON".to_owned(), Vec::new())),
    );
    for (pkg, enabled, args) in &deps {
        if !is_on(enabled) {
            continue;
        }
        write!(out, "find_dependency({pkg}").unwrap();
        for arg in args {
            write!(out, " {}", escape_for_cmake(arg)).unwrap();
        }
        out.push_str(")\n");
    }
    out.push_str("\n\n");
}

/// `GenerateImportPrefix`.
fn write_prefix(ctx: &GenCtx, out: &mut String, index: usize, dest: &str) {
    let prefix = ctx.var_safe(index, "CMAKE_INSTALL_PREFIX");
    if is_full_path(dest) {
        writeln!(out, "# The installation prefix configured by this project.\nset(_IMPORT_PREFIX \"{prefix}\")\n").unwrap();
        return;
    }
    let absolute = format!("{prefix}/{dest}");
    out.push_str("# Compute the installation prefix relative to this file.\nget_filename_component(_IMPORT_PREFIX \"${CMAKE_CURRENT_LIST_FILE}\" PATH)\n");
    if [
        "/lib/",
        "/lib64/",
        "/libx32/",
        "/usr/lib/",
        "/usr/lib64/",
        "/usr/libx32/",
    ]
    .iter()
    .any(|path| format!("{absolute}/").starts_with(path))
    {
        write!(
            out,
            "# Use original install prefix when loaded through a\n# cross-prefix symbolic link such as /lib -> /usr/lib.\nget_filename_component(_realCurr \"${{_IMPORT_PREFIX}}\" REALPATH)\nget_filename_component(_realOrig \"{absolute}\" REALPATH)\nif(_realCurr STREQUAL _realOrig)\n  set(_IMPORT_PREFIX \"{absolute}\")\nendif()\nunset(_realOrig)\nunset(_realCurr)\n"
        )
        .unwrap();
    }
    let mut dest = dest.to_owned();
    while !dest.is_empty() {
        out.push_str("get_filename_component(_IMPORT_PREFIX \"${_IMPORT_PREFIX}\" PATH)\n");
        dest = filename_path(&dest);
    }
    out.push_str("if(_IMPORT_PREFIX STREQUAL \"/\")\n  set(_IMPORT_PREFIX \"\")\nendif()\n\n");
}

/// `GenerateCxxModuleConfigInformation` (build): one include per config.
fn build_module_files(
    ex: &Exporter<'_, '_>,
    dir: &Path,
    name: &str,
    records: &[Record<'_>],
) -> std::io::Result<()> {
    // GenerateCxxModuleConfigInformation: with more than one configuration
    // each per-config file is optional.
    let configs = export_configs(ex.ctx);
    let optional = if configs.len() > 1 { " OPTIONAL" } else { "" };
    let mut main_content = String::new();
    for config in &configs {
        let config = module_config_suffix(config);
        writeln!(
            main_content,
            "include(\"${{CMAKE_CURRENT_LIST_DIR}}/cxx-modules-{name}-{config}.cmake\"{optional})"
        )
        .unwrap();
    }
    write_if_different(
        &dir.join(format!("cxx-modules-{name}.cmake")),
        &main_content,
    )?;
    // GenerateImportCxxModuleConfigTargetInclusion.
    for config in &configs {
        let config = module_config_suffix(config);
        let mut content = String::new();
        for record in records {
            if ex.have_cxx20_module_sources(record.target) {
                let fs_name = filesystem_export_name(record.target);
                writeln!(
                    content,
                    "include(\"${{CMAKE_CURRENT_LIST_DIR}}/target-{fs_name}-{config}.cmake\")"
                )
                .unwrap();
            }
        }
        write_if_different(
            &dir.join(format!("cxx-modules-{name}-{config}.cmake")),
            &content,
        )?;
    }
    Ok(())
}

