/// `cmExportCMakeConfigGenerator::GeneratePolicyHeaderCode`.
fn policy_header(version: (u32, u32, u32)) -> String {
    let (major, minor, patch) = version;
    format!(
        "# Generated by CMake\n\nif(\"${{CMAKE_MAJOR_VERSION}}.${{CMAKE_MINOR_VERSION}}\" LESS 2.8)\n   message(FATAL_ERROR \"CMake >= {major}.{minor}.{patch} required\")\nendif()\nif(CMAKE_VERSION VERSION_LESS \"{major}.{minor}.{patch}\")\n   message(FATAL_ERROR \"CMake >= {major}.{minor}.{patch} required\")\nendif()\ncmake_policy(PUSH)\ncmake_policy(VERSION {major}.{minor}.{patch}...3.31)\n"
    )
}

/// `cmExportCMakeConfigGenerator::GenerateImportHeaderCode`.
fn import_header(out: &mut String, config: &str) {
    out.push_str(
        "#----------------------------------------------------------------\n# Generated CMake target import file",
    );
    if config.is_empty() {
        out.push_str(".\n");
    } else {
        writeln!(out, " for configuration \"{config}\".").unwrap();
    }
    out.push_str(
        "#----------------------------------------------------------------\n\n# Commands may need to know the format version.\nset(CMAKE_IMPORT_FILE_VERSION 1)\n\n",
    );
}

