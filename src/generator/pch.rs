//! Precompiled-header paths and options of `cmGeneratorTarget`
//! (GetPrecompileHeaders, GetPchHeader, GetPchSource, GetPchFileObject,
//! GetPchFile, GetPchCreateCompileOptions, GetPchUseCompileOptions) for a
//! single architecture (`GetPchArchs` yields one empty arch off Apple).

use super::ctx::GenCtx;
use super::target as gt;
use crate::state::Target;
use crate::util::is_on_opt;
use std::path::Path;

/// The languages with precompiled-header support.
pub const PCH_LANGUAGES: [&str; 4] = ["C", "CXX", "OBJC", "OBJCXX"];

fn supported(language: &str) -> bool {
    PCH_LANGUAGES.contains(&language)
}

/// `cmGeneratorTarget::GetPchArchs`: the Apple architectures that need
/// per-arch PCH files, or a single empty architecture.
pub fn pch_archs(ctx: &GenCtx, target: &Target, config: &str, language: &str) -> Vec<String> {
    // EmitUniversalBinaryFlags is always on for Ninja, which is never Xcode.
    let archs = super::flags::apple_archs(ctx, target, config, language);
    if archs.len() < 2 {
        vec![String::new()]
    } else {
        archs
    }
}

/// `cmGeneratorTarget::GetPrecompileHeaders` (values only).
pub fn precompile_headers(
    ctx: &GenCtx,
    target: &Target,
    config: &str,
    language: &str,
) -> Vec<String> {
    let key = ctx.target_key(target);
    let mut host = super::genex_host::CtxHost::new(ctx, target.makefile);
    match crate::genex::target_usage(&mut host, &key, "PRECOMPILE_HEADERS", config, language) {
        Ok(items) => items.into_iter().map(|item| item.value).collect(),
        Err(error) => {
            if !error.quiet {
                let backtrace = ctx.backtrace(error.backtrace);
                ctx.genex_error(backtrace, &error);
            }
            Vec::new()
        }
    }
}

/// The target whose PCH a target uses (`PRECOMPILE_HEADERS_REUSE_FROM`).
pub fn reuse_target<'a>(ctx: &GenCtx<'a>, target: &'a Target) -> Option<&'a Target> {
    let name = target.props.get("PRECOMPILE_HEADERS_REUSE_FROM")?;
    ctx.target(name)
}

/// `GetPchHeader`: the header path, or empty. The first query writes it.
pub fn pch_header(
    ctx: &GenCtx,
    target: &Target,
    config: &str,
    language: &str,
    arch: &str,
) -> String {
    if !supported(language) || is_on_opt(target.props.get("DISABLE_PRECOMPILE_HEADERS")) {
        return String::new();
    }
    // cmGeneratorTarget::PchHeaders caches per language, config and arch.
    let key = format!(
        "pch:header:{}:{config}:{language}:{arch}",
        ctx.target_key(target)
    );
    if let Some(cached) = ctx.memo.borrow().get(&key) {
        return cached.clone();
    }
    let header = compute_pch_header(ctx, target, config, language, arch);
    ctx.memo.borrow_mut().insert(key, header.clone());
    header
}

fn compute_pch_header(
    ctx: &GenCtx,
    target: &Target,
    config: &str,
    language: &str,
    arch: &str,
) -> String {
    let reuse = target.props.get("PRECOMPILE_HEADERS_REUSE_FROM");
    let headers = precompile_headers(ctx, target, config, language);
    if reuse.is_none() && headers.is_empty() {
        return String::new();
    }
    let owner = match reuse {
        Some(_) => match reuse_target(ctx, target) {
            Some(owner) => owner,
            None => return String::new(),
        },
        None => target,
    };
    let extension = match language {
        "C" => ".h",
        "CXX" => ".hxx",
        "OBJC" => ".objc.h",
        _ => ".objcxx.hxx",
    };
    let mut directory = gt::support_directory(ctx, owner);
    if ctx.multi_config {
        directory += &format!("/{config}");
    }
    let suffix = if arch.is_empty() {
        String::new()
    } else {
        format!("_{arch}")
    };
    let header = format!("{directory}/cmake_pch{suffix}{extension}");
    if reuse.is_none() {
        write_pch_header(ctx, target, language, headers, &header);
    }
    header
}

/// `cmFileTimes::Copy` of the modification time.
fn copy_file_times(from: &str, to: &str) {
    if let Ok(meta) = std::fs::metadata(from)
        && let Ok(modified) = meta.modified()
        && let Ok(file) = std::fs::File::options().write(true).open(to)
    {
        let accessed = meta.accessed().unwrap_or(modified);
        let times = std::fs::FileTimes::new()
            .set_modified(modified)
            .set_accessed(accessed);
        let _ = file.set_times(times);
    }
}

/// `cmSystemTools::MoveFileIfDifferent`.
fn move_file_if_different(from: &str, to: &str) {
    let same = match (std::fs::read(from), std::fs::read(to)) {
        (Ok(a), Ok(b)) => a == b,
        _ => false,
    };
    if same {
        let _ = std::fs::remove_file(from);
    } else {
        let _ = std::fs::rename(from, to);
    }
}

fn write_pch_header(
    ctx: &GenCtx,
    target: &Target,
    language: &str,
    headers: Vec<String>,
    header: &str,
) {
    let mut text = String::from("/* generated by CMake */\n\n");
    if let Some(prologue) = ctx.var(target.makefile, "CMAKE_PCH_PROLOGUE") {
        text += &format!("{prologue}\n");
    }
    if language == "CXX" {
        text += "#ifdef __cplusplus\n";
    }
    let mut first_on_disk = None;
    for value in headers {
        if value.is_empty() {
            continue;
        }
        if value.starts_with(['<', '"']) {
            text += &format!("#include {value}\n");
        } else {
            text += &format!("#include \"{value}\"\n");
        }
        if first_on_disk.is_none() && Path::new(&value).exists() {
            first_on_disk = Some(value);
        }
    }
    if language == "CXX" {
        text += "#endif // __cplusplus\n";
    }
    if let Some(epilogue) = ctx.var(target.makefile, "CMAKE_PCH_EPILOGUE") {
        text += &format!("{epilogue}\n");
    }
    if let Some(parent) = Path::new(header).parent() {
        let _ = std::fs::create_dir_all(parent);
    }
    let tmp = format!("{header}.tmp");
    let _ = std::fs::write(&tmp, &text);
    if let Some(first) = &first_on_disk {
        copy_file_times(first, &tmp);
    }
    move_file_if_different(&tmp, header);
}

/// `GetPchSource`: the source path, or empty. The first query writes it.
pub fn pch_source(
    ctx: &GenCtx,
    target: &Target,
    config: &str,
    language: &str,
    arch: &str,
) -> String {
    if !supported(language) {
        return String::new();
    }
    let header = pch_header(ctx, target, config, language, arch);
    if header.is_empty() {
        return String::new();
    }
    let key = format!(
        "pch:source:{}:{config}:{language}:{arch}",
        ctx.target_key(target)
    );
    if let Some(cached) = ctx.memo.borrow().get(&key) {
        return cached.clone();
    }
    let source = compute_pch_source(ctx, target, language, arch);
    if !target.props.contains("PRECOMPILE_HEADERS_REUSE_FROM") {
        let tmp = format!("{source}.tmp");
        let _ = std::fs::write(&tmp, "/* generated by CMake */\n");
        copy_file_times(&header, &tmp);
        move_file_if_different(&tmp, &source);
    }
    ctx.memo.borrow_mut().insert(key, source.clone());
    source
}

fn compute_pch_source(ctx: &GenCtx, target: &Target, language: &str, arch: &str) -> String {
    let owner = reuse_target(ctx, target).unwrap_or(target);
    let link_pch = is_on_opt(ctx.var(target.makefile, "CMAKE_LINK_PCH").as_deref());
    let extension = match (link_pch, language) {
        (false, "C") => ".h.c",
        (false, "CXX") => ".hxx.cxx",
        (false, "OBJC") => ".objc.h.m",
        (false, _) => ".objcxx.hxx.mm",
        (true, "C") => ".c",
        (true, "CXX") => ".cxx",
        (true, "OBJC") => ".m",
        (true, _) => ".mm",
    };
    let suffix = if arch.is_empty() {
        String::new()
    } else {
        format!("_{arch}")
    };
    format!(
        "{}/cmake_pch{suffix}{extension}",
        gt::support_directory(ctx, owner)
    )
}

/// `GetPchFileObject`: the object file compiled from the PCH source.
pub fn pch_file_object(
    ctx: &GenCtx,
    target: &Target,
    config: &str,
    language: &str,
    arch: &str,
) -> String {
    let source = pch_source(ctx, target, config, language, arch);
    if source.is_empty() {
        return String::new();
    }
    let sources = gt::sources(ctx, target, config);
    match sources.iter().find(|info| info.path == source) {
        Some(info) if !info.object_name.is_empty() => {
            format!(
                "{}{}",
                gt::object_directory(ctx, target, config),
                info.object_name
            )
        }
        _ => String::new(),
    }
}

/// `GetPchFile`.
pub fn pch_file(ctx: &GenCtx, target: &Target, config: &str, language: &str, arch: &str) -> String {
    let extension = ctx.var_safe(target.makefile, "CMAKE_PCH_EXTENSION");
    if is_on_opt(ctx.var(target.makefile, "CMAKE_LINK_PCH").as_deref()) {
        let owner = reuse_target(ctx, target).unwrap_or(target);
        let object = pch_file_object(ctx, owner, config, language, arch);
        if extension.is_empty() {
            return String::new();
        }
        let stem = object.rfind('.').map_or("", |dot| &object[..dot]);
        format!("{stem}{extension}")
    } else {
        format!(
            "{}{extension}",
            pch_header(ctx, target, config, language, arch)
        )
    }
}

fn substitute(options: String, header: &str, file: &str) -> String {
    options
        .replace("<PCH_HEADER>", header)
        .replace("<PCH_FILE>", file)
}

/// `GetPchCreateCompileOptions`.
pub fn pch_create_options(
    ctx: &GenCtx,
    target: &Target,
    config: &str,
    language: &str,
    arch: &str,
) -> String {
    let dir = target.makefile;
    let mut options = String::new();
    if is_on_opt(target.props.get("PCH_WARN_INVALID")) {
        options = ctx.var_safe(
            dir,
            &format!("CMAKE_{language}_COMPILE_OPTIONS_INVALID_PCH"),
        );
    }
    if is_on_opt(target.props.get("PCH_INSTANTIATE_TEMPLATES")) {
        let instantiate = ctx.var_safe(
            dir,
            &format!("CMAKE_{language}_COMPILE_OPTIONS_INSTANTIATE_TEMPLATES_PCH"),
        );
        if !instantiate.is_empty() {
            options = format!("{options};{instantiate}");
        }
    }
    let create = ctx.var_safe(dir, &format!("CMAKE_{language}_COMPILE_OPTIONS_CREATE_PCH"));
    options = format!("{options};{create}");
    let header = pch_header(ctx, target, config, language, arch);
    let file = pch_file(ctx, target, config, language, arch);
    substitute(options, &header, &file)
}

/// `GetPchUseCompileOptions`.
pub fn pch_use_options(
    ctx: &GenCtx,
    target: &Target,
    config: &str,
    language: &str,
    arch: &str,
) -> String {
    let dir = target.makefile;
    let mut options = String::new();
    if is_on_opt(target.props.get("PCH_WARN_INVALID")) {
        options = ctx.var_safe(
            dir,
            &format!("CMAKE_{language}_COMPILE_OPTIONS_INVALID_PCH"),
        );
    }
    let property = format!("{language}_COMPILE_OPTIONS_USE_PCH");
    let value = target.props.get(&property).unwrap_or_default();
    let value = if value.is_empty() {
        ctx.var_safe(dir, &format!("CMAKE_{property}"))
    } else {
        value.to_owned()
    };
    options = format!("{options};{value}");
    let header = pch_header(ctx, target, config, language, arch);
    let file = pch_file(ctx, target, config, language, arch);
    substitute(options, &header, &file)
}
