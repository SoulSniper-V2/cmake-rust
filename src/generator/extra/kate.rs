//! `cmExtraKateGenerator`: `.kateproject` files.

use std::collections::BTreeSet;

use super::{Shared, file_exists};
use crate::generator::ctx::GenCtx;
use crate::generator::ninja::GlobalTarget;
use crate::state::TargetKind;

/// `cmExtraKateGenerator::GetPathBasename`.
fn path_basename(path: &str) -> &str {
    let trimmed = path.trim_end_matches(['/', '\\']);
    trimmed.rsplit(['/', '\\']).next().unwrap_or(trimmed)
}

/// `cmExtraKateGenerator::GenerateProjectName`.
fn generate_project_name(s: &Shared, dir: usize) -> String {
    let name = s.project_name(dir);
    let build_type = s.build_type(dir);
    let base = path_basename(s.binary_dir(dir));
    format!(
        "{}{}@{}",
        name,
        if build_type.is_empty() {
            String::new()
        } else {
            format!("-{build_type}")
        },
        base
    )
}

/// `cmExtraKateGenerator::Generate`.
pub fn generate(ctx: &GenCtx, globals: &[GlobalTarget]) {
    let s = Shared::new(ctx, globals);
    let dir = 0;
    let project_name = generate_project_name(&s, dir);
    let gen_name = s.var_safe(0, "CMAKE_GENERATOR");
    let use_ninja = gen_name == "Ninja" || gen_name == "Ninja Multi-Config";

    create_kate_project_file(&s, dir, &project_name, use_ninja);
    // CreateDummyKateProjectFile
    let dummy = format!("{}/{project_name}.kateproject", s.binary_dir(dir));
    let cmake_command = std::env::args()
        .next()
        .unwrap_or_else(|| "cmake".to_owned());
    let _ = std::fs::write(
        dummy,
        format!("#Generated by {cmake_command}, do not edit.\n"),
    );
}

/// `cmExtraKateGenerator::GenerateFilesString`.
fn generate_files_string(s: &Shared, dir: usize) -> String {
    let mode = s
        .var_safe(dir, "CMAKE_KATE_FILES_MODE")
        .to_ascii_uppercase();
    const GIT: &str = "\"git\": 1 ";
    const SVN: &str = "\"svn\": 1 ";
    const HG: &str = "\"hg\": 1 ";
    const FOSSIL: &str = "\"fossil\": 1 ";
    match mode.as_str() {
        "SVN" => return SVN.to_owned(),
        "GIT" => return GIT.to_owned(),
        "HG" => return HG.to_owned(),
        "FOSSIL" => return FOSSIL.to_owned(),
        _ => {}
    }
    if mode != "LIST" {
        // Walk up the source tree looking for a VCS checkout marker.
        let mut start = s.source_dir(dir).to_owned();
        loop {
            if file_exists(&format!("{start}/.git")) {
                return GIT.to_owned();
            }
            if file_exists(&format!("{start}/.svn")) {
                return SVN.to_owned();
            }
            if file_exists(&format!("{start}/.hg")) {
                return HG.to_owned();
            }
            if file_exists(&format!("{start}/.fslckout")) {
                return FOSSIL.to_owned();
            }
            let Some((parent, _)) = start.rsplit_once('/') else {
                break;
            };
            if parent.is_empty() {
                break;
            }
            start = parent.to_owned();
        }
    }

    // LIST mode / no VCS: all list files and real sources.
    let mut files: BTreeSet<String> = BTreeSet::new();
    for d in 0..s.makefile_count() {
        for list_file in s.list_files(d) {
            if !list_file.contains("/CMakeFiles/") {
                files.insert(list_file.clone());
            }
        }
        for sf in s.ctx.interp.ext.sources.get(&d).into_iter().flatten() {
            if sf.generated {
                continue;
            }
            // sf->ResolveFullPath(): location directory + name, relative
            // to the directory's source dir when not absolute.
            let full = if sf.location.directory.starts_with('/') {
                format!("{}/{}", sf.location.directory, sf.location.name)
            } else if sf.location.directory.is_empty() {
                format!("{}/{}", s.source_dir(d), sf.location.name)
            } else {
                format!(
                    "{}/{}/{}",
                    s.source_dir(d),
                    sf.location.directory,
                    sf.location.name
                )
            };
            files.insert(full);
        }
    }
    let mut tmp = String::from("\"list\": [");
    let mut sep = "";
    for f in &files {
        tmp.push_str(sep);
        tmp.push_str(" \"");
        tmp.push_str(f);
        tmp.push('"');
        sep = ",";
    }
    tmp.push_str("] ");
    tmp
}

/// `cmExtraKateGenerator::AppendTarget`.
#[allow(clippy::too_many_arguments)]
fn append_target(
    out: &mut String,
    sep: &mut char,
    target: &str,
    configs: &[String],
    make: &str,
    make_args: &str,
    path: &str,
    home_output_dir: &str,
    use_ninja: bool,
) {
    for conf in configs {
        out.push_str("\t\t\t");
        out.push(*sep);
        out.push_str("{\"name\":\"");
        out.push_str(target);
        if configs.len() > 1 {
            out.push(':');
            out.push_str(conf);
        }
        out.push_str("\", \"build_cmd\":\"");
        out.push_str(make);
        out.push_str(" -C \\\"");
        out.push_str(if use_ninja { home_output_dir } else { path });
        out.push_str("\\\" ");
        if use_ninja && configs.len() > 1 {
            out.push_str(&format!(" -f build-{conf}.ninja"));
        }
        out.push_str(make_args);
        out.push(' ');
        out.push_str(target);
        out.push_str("\"}\n");
        *sep = ',';
    }
}

/// `cmExtraKateGenerator::CreateKateProjectFile`.
fn create_kate_project_file(s: &Shared, dir: usize, project_name: &str, use_ninja: bool) {
    let filename = format!("{}/.kateproject", s.binary_dir(dir));
    let mut out = String::new();
    out.push_str("{\n\t\"name\": \"");
    out.push_str(project_name);
    out.push_str("\",\n\t\"directory\": \"");
    out.push_str(s.source_dir(dir));
    out.push_str("\",\n\t\"files\": [ { ");
    out.push_str(&generate_files_string(s, dir));
    out.push_str("} ],\n");

    // WriteTargets
    let make = s.var_safe(dir, "CMAKE_MAKE_PROGRAM");
    let make_args = s.var_safe(dir, "CMAKE_KATE_MAKE_ARGUMENTS");
    let home_output_dir = s.binary_dir(dir);
    // GetGeneratorConfigs(IncludeEmptyConfig): single-config -> [""].
    // mf->GetGeneratorConfigs(cmMakefile::IncludeEmptyConfig).
    let configs: Vec<String> = s.ctx.configs.clone();
    out.push_str("\t\"build\": {\n\t\t\"directory\": \"");
    out.push_str(home_output_dir);
    out.push_str("\",\n\t\t\"default_target\": \"all\",\n\t\t\"clean_target\": \"clean\",\n");
    out.push_str("\t\t\"build\": \"");
    out.push_str(&make);
    out.push_str(" -C \\\"");
    out.push_str(home_output_dir);
    out.push_str("\\\" ");
    out.push_str(&make_args);
    out.push_str(" all\",\n");
    out.push_str("\t\t\"clean\": \"");
    out.push_str(&make);
    out.push_str(" -C \\\"");
    out.push_str(home_output_dir);
    out.push_str("\\\" ");
    out.push_str(&make_args);
    out.push_str(" clean\",\n");
    out.push_str("\t\t\"quick\": \"");
    out.push_str(&make);
    out.push_str(" -C \\\"");
    out.push_str(home_output_dir);
    out.push_str("\\\" ");
    out.push_str(&make_args);
    out.push_str(" install\",\n");
    out.push_str("\t\t\"targets\":[\n");

    let mut sep = ' ';
    append_target(
        &mut out,
        &mut sep,
        "all",
        &configs,
        &make,
        &make_args,
        home_output_dir,
        home_output_dir,
        use_ninja,
    );
    append_target(
        &mut out,
        &mut sep,
        "clean",
        &configs,
        &make,
        &make_args,
        home_output_dir,
        home_output_dir,
        use_ninja,
    );

    for d in 0..s.makefile_count() {
        let current_dir = s.binary_dir(d);
        // lg->GetCurrentBinaryDirectory() == lg->GetBinaryDirectory(): the
        // directory is the top-level binary directory.
        let top_level = current_dir == s.home_binary();
        for target in s.targets(d) {
            match target.kind {
                TargetKind::GlobalTarget => {
                    let mut insert = top_level;
                    if insert && target.name == "edit_cache" {
                        let edit = s.var(d, "CMAKE_EDIT_COMMAND");
                        if edit.as_deref().is_none_or(|e| e.contains("ccmake")) {
                            insert = false;
                        }
                    }
                    if insert {
                        append_target(
                            &mut out,
                            &mut sep,
                            &target.name,
                            &configs,
                            &make,
                            &make_args,
                            current_dir,
                            home_output_dir,
                            use_ninja,
                        );
                    }
                }
                TargetKind::Utility => {
                    let name = &target.name;
                    if (name.starts_with("Nightly") && name != "Nightly")
                        || (name.starts_with("Continuous") && name != "Continuous")
                        || (name.starts_with("Experimental") && name != "Experimental")
                    {
                        continue;
                    }
                    append_target(
                        &mut out,
                        &mut sep,
                        name,
                        &configs,
                        &make,
                        &make_args,
                        current_dir,
                        home_output_dir,
                        use_ninja,
                    );
                }
                TargetKind::Executable
                | TargetKind::StaticLibrary
                | TargetKind::SharedLibrary
                | TargetKind::ModuleLibrary
                | TargetKind::ObjectLibrary => {
                    append_target(
                        &mut out,
                        &mut sep,
                        &target.name,
                        &configs,
                        &make,
                        &make_args,
                        current_dir,
                        home_output_dir,
                        use_ninja,
                    );
                    if !use_ninja {
                        append_target(
                            &mut out,
                            &mut sep,
                            &format!("{}/fast", target.name),
                            &configs,
                            &make,
                            &make_args,
                            current_dir,
                            home_output_dir,
                            use_ninja,
                        );
                    }
                }
                _ => {}
            }
        }
        // The generator's global targets (GLOBAL_TARGET rows, last in the
        // directory's target list) only for the top-level directory.
        if top_level {
            for name in s.global_target_names(d) {
                let mut insert = true;
                // Only add "edit_cache" if it is not ccmake, which does not
                // work within the IDE.
                if name == "edit_cache" {
                    let edit = s.var(d, "CMAKE_EDIT_COMMAND");
                    if edit.as_deref().is_none_or(|e| e.contains("ccmake")) {
                        insert = false;
                    }
                }
                if insert {
                    append_target(
                        &mut out,
                        &mut sep,
                        name,
                        &configs,
                        &make,
                        &make_args,
                        current_dir,
                        home_output_dir,
                        use_ninja,
                    );
                }
            }
        }
        // Ninja local generators have no per-object file targets.
    }
    out.push_str("\t] }\n");
    out.push_str("}\n");
    let _ = std::fs::write(filename, out);
}
