const MOC_UNDERSCORE_LEN: usize = 4; // Length of "moc_"
const UI_UNDERSCORE_LEN: usize = 3; // Length of "ui_"

/// `cmQtAutoMocUicT::ParseCacheT::FileT`.
#[derive(Default)]
struct ParseData {
    moc_macro: String,
    moc_underscore: Vec<IncludeKey>,
    moc_dot: Vec<IncludeKey>,
    moc_depends: Vec<String>,
    uic_include: Vec<IncludeKey>,
    #[allow(dead_code)]
    uic_depends: Vec<String>,
}

impl ParseData {
    /// `FileT::Clear`.
    fn clear(&mut self) {
        self.moc_macro.clear();
        self.moc_underscore.clear();
        self.moc_dot.clear();
        self.moc_depends.clear();
        self.uic_include.clear();
        self.uic_depends.clear();
    }
}

type ParseHandle = Rc<RefCell<ParseData>>;

/// `cmQtAutoMocUicT::ParseCacheT`.
#[derive(Default)]
struct ParseCache {
    /// `std::unordered_map` order matters for ParseCache.txt.
    map: LibMap<ParseHandle>,
}

impl ParseCache {
    /// `GetOrInsert`: (handle, inserted).
    fn get_or_insert(&mut self, file_name: &str) -> (ParseHandle, bool) {
        if let Some(handle) = self.map.get(file_name) {
            return (handle.clone(), false);
        }
        let handle = Rc::new(RefCell::new(ParseData::default()));
        self.map.insert(file_name.to_owned(), handle.clone());
        (handle, true)
    }

    /// `ReadFromFile`.
    fn read_from_file(&mut self, file_name: &str) -> bool {
        let Ok(content) = std::fs::read(file_name) else {
            return false;
        };
        let content = String::from_utf8_lossy(&content);
        let mut current: Option<ParseHandle> = None;
        for raw_line in content.split('\n') {
            let mut line = raw_line;
            // Check if this an empty or a comment line
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            // Drop carriage return character at the end
            if let Some(stripped) = line.strip_suffix('\r') {
                line = stripped;
                if line.is_empty() {
                    continue;
                }
            }
            // Check if this a file name line
            if !line.starts_with(' ') {
                current = Some(self.get_or_insert(line).0);
                continue;
            }
            // Bad line or bad file handle
            let Some(handle) = &current else {
                continue;
            };
            if line.len() < 6 {
                continue;
            }
            let value = &line[5..];
            let mut data = handle.borrow_mut();
            if let Some(rest) = line.strip_prefix(" mmc:") {
                let _ = rest;
                data.moc_macro = value.to_owned();
            } else if line.starts_with(" miu:") {
                data.moc_underscore
                    .push(IncludeKey::new(value.to_owned(), MOC_UNDERSCORE_LEN));
            } else if line.starts_with(" mid:") {
                data.moc_dot.push(IncludeKey::new(value.to_owned(), 0));
            } else if line.starts_with(" mdp:") {
                data.moc_depends.push(value.to_owned());
            } else if line.starts_with(" uic:") {
                data.uic_include
                    .push(IncludeKey::new(value.to_owned(), UI_UNDERSCORE_LEN));
            } else if line.starts_with(" udp:") {
                data.uic_depends.push(value.to_owned());
            }
        }
        true
    }

    /// `WriteToFile` (`cmGeneratedFileStream`: copy-if-different).
    fn write_to_file(&self, file_name: &str) -> bool {
        let mut out = String::from("# Generated by CMake. Changes will be overwritten.\n");
        for (name, handle) in self.map.iter() {
            out.push_str(name);
            out.push('\n');
            let data = handle.borrow();
            if !data.moc_macro.is_empty() {
                out.push_str(&format!(" mmc:{}\n", data.moc_macro));
            }
            for item in &data.moc_underscore {
                out.push_str(&format!(" miu:{}\n", item.key));
            }
            for item in &data.moc_dot {
                out.push_str(&format!(" mid:{}\n", item.key));
            }
            for item in &data.moc_depends {
                out.push_str(&format!(" mdp:{item}\n"));
            }
            for item in &data.uic_include {
                out.push_str(&format!(" uic:{}\n", item.key));
            }
            for item in &data.uic_depends {
                out.push_str(&format!(" udp:{item}\n"));
            }
        }
        crate::fsutil::write_if_different(std::path::Path::new(file_name), out.as_bytes()).is_ok()
    }
}

