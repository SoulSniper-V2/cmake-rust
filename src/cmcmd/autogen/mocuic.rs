/// `cmCryptoHash(SHA256)`: append every item plus `;`, hex digest.
pub(crate) fn settings_hash<'a>(items: impl Iterator<Item = &'a str>) -> String {
    let mut hasher = sha2::Sha256::new();
    for item in items {
        hasher.update(item.as_bytes());
        hasher.update(b";");
    }
    let digest = hasher.finalize();
    let mut out = String::with_capacity(digest.len() * 2);
    for byte in digest {
        out.push_str(&format!("{byte:02x}"));
    }
    out
}

/// `memchr`-style substring search over raw bytes (`std::string::find`).
fn bytes_find(haystack: &[u8], needle: &[u8]) -> Option<usize> {
    if needle.is_empty() {
        return Some(0);
    }
    haystack.windows(needle.len()).position(|w| w == needle)
}

fn lossy(bytes: &[u8]) -> String {
    String::from_utf8_lossy(bytes).into_owned()
}

impl MocUic {
    /// `cmQtAutoMocUicT::Process`.
    fn process(&mut self) -> bool {
        self.settings_file_read();
        self.parse_cache_read();
        if !self.create_directories() {
            return false;
        }
        self.init_jobs();
        self.run_jobs();
        if self.job_error {
            return false;
        }
        if !self.parse_cache_write() {
            return false;
        }
        if !self.settings_file_write() {
            return false;
        }
        true
    }

    /// `SettingsFileRead`.
    fn settings_file_read(&mut self) {
        // Compose current settings strings
        if self.mconst.enabled {
            self.settings_string_moc = settings_hash(
                std::iter::once(self.mconst.executable.as_str())
                    .chain(self.mconst.options_definitions.iter().map(String::as_str))
                    .chain(self.mconst.options_includes.iter().map(String::as_str))
                    .chain(self.mconst.options_extra.iter().map(String::as_str))
                    .chain(self.mconst.predefs_cmd.iter().map(String::as_str))
                    .chain(self.mconst.depend_filters.iter().map(|f| f.key.as_str()))
                    .chain(self.mconst.macro_filters.iter().map(|f| f.key.as_str())),
            );
        }
        if self.uconst.enabled {
            let mut items: Vec<String> = vec![self.uconst.executable.clone()];
            items.extend(self.uconst.options.iter().cloned());
            for (name, options) in self.uconst.ui_files.iter() {
                items.push(name.clone());
                items.extend(options.iter().cloned());
            }
            self.settings_string_uic = settings_hash(items.iter().map(String::as_str));
        }

        // Read old settings and compare
        if let Some(content) = file_read(&self.settings_file, None) {
            let content = lossy(&content);
            if self.mconst.enabled && self.settings_string_moc != settings_find(&content, "moc") {
                self.mconst.settings_changed = true;
            }
            if self.uconst.enabled && self.settings_string_uic != settings_find(&content, "uic") {
                self.uconst.settings_changed = true;
            }
            // In case any setting changed remove the old settings file.
            // This triggers a full rebuild on the next run if the current
            // build is aborted before writing the current settings in the end.
            if self.mconst.settings_changed || self.uconst.settings_changed {
                let _ = std::fs::remove_file(&self.settings_file);
            }
        } else {
            // Settings file read failed
            if self.mconst.enabled {
                self.mconst.settings_changed = true;
            }
            if self.uconst.enabled {
                self.uconst.settings_changed = true;
            }
        }
    }

    /// `SettingsFileWrite`.
    fn settings_file_write(&mut self) -> bool {
        // Only write if any setting changed
        if !self.mconst.settings_changed && !self.uconst.settings_changed {
            return true;
        }
        if self.base.log.verbose() {
            self.base.log.info(
                GenT::Gen,
                &format!(
                    "Writing the settings file {}",
                    self.message_path(&self.settings_file)
                ),
            );
        }
        // Compose settings file content
        let mut content = String::new();
        if !self.settings_string_moc.is_empty() {
            content.push_str(&format!("moc:{}\n", self.settings_string_moc));
        }
        if !self.settings_string_uic.is_empty() {
            content.push_str(&format!("uic:{}\n", self.settings_string_uic));
        }
        // Write settings file
        let mut error = String::new();
        if !file_write(&self.settings_file, content.as_bytes(), Some(&mut error)) {
            self.base.log.error(
                GenT::Gen,
                &format!(
                    "Writing the settings file {} failed.\n{error}",
                    self.message_path(&self.settings_file)
                ),
            );
            // Remove old settings file to trigger a full rebuild on the
            // next run
            let _ = std::fs::remove_file(&self.settings_file);
            return false;
        }
        true
    }

    /// `ParseCacheRead`.
    fn parse_cache_read(&mut self) {
        let mut reason = "";
        // Don't read the cache if it is invalid
        self.beval.parse_cache_time = FileTime::load(&self.bconst.parse_cache_file);
        if !self.beval.parse_cache_time.exists() {
            reason = "Refreshing parse cache because it doesn't exist.";
        } else if self.mconst.settings_changed || self.uconst.settings_changed {
            reason = "Refreshing parse cache because the settings changed.";
        } else if self
            .beval
            .parse_cache_time
            .older(&self.bconst.cmake_executable_time)
        {
            reason = "Refreshing parse cache because it is older than the CMake executable.";
        }

        if !reason.is_empty() {
            // Don't read but refresh the complete parse cache
            if self.base.log.verbose() {
                self.base.log.info(GenT::Gen, reason);
            }
            self.beval.parse_cache_changed = true;
        } else {
            // Read parse cache
            self.beval
                .parse_cache
                .read_from_file(&self.bconst.parse_cache_file);
        }
    }

    /// `ParseCacheWrite`.
    fn parse_cache_write(&mut self) -> bool {
        if !self.beval.parse_cache_changed {
            return true;
        }
        if self.base.log.verbose() {
            self.base.log.info(
                GenT::Gen,
                &format!(
                    "Writing the parse cache file {}",
                    self.message_path(&self.bconst.parse_cache_file)
                ),
            );
        }
        if !self
            .beval
            .parse_cache
            .write_to_file(&self.bconst.parse_cache_file)
        {
            self.base.log.error(
                GenT::Gen,
                &format!(
                    "Writing the parse cache file {} failed.",
                    self.message_path(&self.bconst.parse_cache_file)
                ),
            );
            return false;
        }
        true
    }

    /// `CreateDirectories`.
    fn create_directories(&mut self) -> bool {
        // Create AUTOGEN include directory
        if std::fs::create_dir_all(&self.bconst.autogen_include_dir).is_err() {
            self.base.log.error(
                GenT::Gen,
                &format!(
                    "Creating the AUTOGEN include directory {} failed.",
                    self.message_path(&self.bconst.autogen_include_dir)
                ),
            );
            return false;
        }
        true
    }

    /// `CreateParseJobs`.
    fn create_parse_jobs(&mut self, source_map: &SourceFileMap, is_header: bool) {
        let parse_cache_time = self.beval.parse_cache_time;
        for src in source_map.values() {
            let file_name = src.borrow().file_name.clone();
            // Get or create the file parse data reference
            let (cache_entry, inserted) = self.beval.parse_cache.get_or_insert(&file_name);
            src.borrow_mut().parse_data = Some(cache_entry);
            // Create a parse job if the cache file was missing or is older
            if inserted || src.borrow().file_time.newer(&parse_cache_time) {
                self.beval.parse_cache_changed = true;
                self.jobs.push_back(if is_header {
                    Job::ParseHeader(src.clone())
                } else {
                    Job::ParseSource(src.clone())
                });
            }
        }
    }

    /// `InitJobs`.
    fn init_jobs(&mut self) {
        // Add moc_predefs.h job
        if self.mconst.enabled && !self.mconst.predefs_cmd.is_empty() {
            self.jobs.push_back(Job::MocPredefs);
        }

        // Add header/source parse jobs
        let headers = std::mem::take(&mut self.beval.headers);
        self.create_parse_jobs(&headers, true);
        self.beval.headers = headers;
        let sources = std::mem::take(&mut self.beval.sources);
        self.create_parse_jobs(&sources, false);
        self.beval.sources = sources;

        // Add parse cache evaluations jobs
        {
            // Add a fence job to ensure all parsing has finished
            self.jobs.push_back(Job::Fence);
            if self.mconst.enabled {
                self.jobs.push_back(Job::EvalCacheMoc);
            }
            if self.uconst.enabled {
                self.jobs.push_back(Job::EvalCacheUic);
            }
            // Add evaluate job
            self.jobs.push_back(Job::EvalCacheFinish);
        }
    }

    /// `WorkerPool_.Process(this)`: a FIFO queue; fences are no-ops
    /// because jobs run to completion in order.
    fn run_jobs(&mut self) {
        while let Some(job) = self.jobs.pop_front() {
            if self.aborted {
                break;
            }
            self.run_job(job);
        }
    }

    fn run_job(&mut self, job: Job) {
        match job {
            Job::MocPredefs => self.job_moc_predefs(),
            Job::Fence => {}
            Job::ParseHeader(handle) => self.job_parse(&handle, true),
            Job::ParseSource(handle) => self.job_parse(&handle, false),
            Job::EvalCacheMoc => self.job_eval_cache_moc(),
            Job::EvalCacheUic => self.job_eval_cache_uic(),
            Job::EvalCacheFinish => self.job_eval_cache_finish(),
            Job::ProbeDepsMoc => self.job_probe_deps_moc(),
            Job::ProbeDepsUic => self.job_probe_deps_uic(),
            Job::ProbeDepsFinish => self.job_probe_deps_finish(),
            Job::CompileMoc {
                mapping,
                reason,
                cache,
            } => self.job_compile_moc(&mapping, reason.as_deref(), &cache),
            Job::CompileUic { mapping, reason } => {
                self.job_compile_uic(&mapping, reason.as_deref());
            }
            Job::MocsCompilation => self.job_mocs_compilation(),
            Job::DepFilesMerge => self.job_dep_files_merge(),
            Job::Finish => {
                // `AbortSuccess`
                self.aborted = true;
            }
        }
    }
}

