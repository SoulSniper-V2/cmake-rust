/// `cmQtAutoMocUicT::MocSettingsT`.
struct MocSettings {
    enabled: bool,
    settings_changed: bool,
    relaxed_mode: bool,
    path_prefix: bool,
    can_output_dependencies: bool,
    executable_time: FileTime,
    executable: String,
    comp_file_abs: String,
    predefs_file_abs: String,
    skip_list: BTreeSet<String>,
    include_paths: Vec<String>,
    definitions: Vec<String>,
    options_includes: Vec<String>,
    options_definitions: Vec<String>,
    options_extra: Vec<String>,
    predefs_cmd: Vec<String>,
    depend_filters: Vec<KeyExp>,
    macro_filters: Vec<KeyExp>,
    regexp_include: crate::cmregex::Regex,
}

impl MocSettings {
    fn new() -> MocSettings {
        MocSettings {
            enabled: false,
            settings_changed: false,
            relaxed_mode: false,
            path_prefix: false,
            can_output_dependencies: false,
            executable_time: FileTime::default(),
            executable: String::new(),
            comp_file_abs: String::new(),
            predefs_file_abs: String::new(),
            skip_list: BTreeSet::new(),
            include_paths: Vec::new(),
            definitions: Vec::new(),
            options_includes: Vec::new(),
            options_definitions: Vec::new(),
            options_extra: Vec::new(),
            predefs_cmd: Vec::new(),
            depend_filters: Vec::new(),
            macro_filters: Vec::new(),
            regexp_include: crate::cmregex::Regex::new(
                "(^|\n)[ \t]*#[ \t]*include[ \t]+[\"<](([^ \">]+/)?moc_[^ \">/]+\\.cpp|[^ \">]+\\.moc)[\">]",
            )
            .unwrap(),
        }
    }

    fn skipped(&self, file_name: &str) -> bool {
        !self.enabled || self.skip_list.contains(file_name)
    }

    /// `MacrosString`.
    fn macros_string(&self) -> String {
        let mut res = String::new();
        for (i, filter) in self.macro_filters.iter().enumerate() {
            if i != 0 {
                res.push_str(if i == self.macro_filters.len() - 1 {
                    " or "
                } else {
                    ", "
                });
            }
            res.push_str(&filter.key);
        }
        res
    }
}

