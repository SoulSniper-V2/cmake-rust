impl MocUic {
    /// `JobEvalCacheT::MessageSearchLocations`.
    fn message_search_locations(&self) -> String {
        let mut res = String::new();
        for path in &self.search_locations {
            res.push_str("  ");
            res.push_str(&self.message_path(path));
            res.push('\n');
        }
        res
    }

    /// `JobEvalCacheMocT::MessageHeader`.
    fn message_header(&self, header_base: &str) -> String {
        self.message_path(&format!(
            "{header_base}.{{{}}}",
            self.bconst.header_extensions.join(",")
        ))
    }

    /// `JobEvalCacheMocT::Process`.
    fn job_eval_cache_moc(&mut self) {
        // Evaluate headers
        let headers: Vec<SourceFileHandle> = self.beval.headers.values().cloned().collect();
        for source in headers {
            if !self.eval_moc_header(&source) {
                return;
            }
        }
        // Evaluate sources
        let sources: Vec<SourceFileHandle> = self.beval.sources.values().cloned().collect();
        for source in sources {
            if !self.eval_moc_source(&source) {
                return;
            }
        }
    }

    /// `JobEvalCacheMocT::EvalHeader`.
    fn eval_moc_header(&mut self, source: &SourceFileHandle) -> bool {
        let (file_moc, build_path) = {
            let file = source.borrow();
            (file.moc, file.build_path.clone())
        };
        let macro_name = source
            .borrow()
            .parse_data
            .as_ref()
            .map(|d| d.borrow().moc_macro.clone())
            .unwrap_or_default();
        if !file_moc {
            return true;
        }

        if !macro_name.is_empty() {
            // Absolute build path
            let output_file = if self.bconst.multi_config {
                self.absolute_include_path(&build_path)
            } else {
                self.absolute_build_path(&build_path)
            };
            // Create a new mapping
            let handle = Rc::new(RefCell::new(Mapping {
                source_file: source.clone(),
                output_file,
                include_string: String::new(),
                includer_files: Vec::new(),
            }));
            // Register mapping in headers map
            self.register_moc_mapping(handle);
        }

        true
    }

    /// `JobEvalCacheMocT::EvalSource`.
    fn eval_moc_source(&mut self, source: &SourceFileHandle) -> bool {
        let (file_moc, file_name) = {
            let file = source.borrow();
            (file.moc, file.file_name.clone())
        };
        let (macro_name, underscore, dot) = {
            let file = source.borrow();
            match &file.parse_data {
                Some(data) => {
                    let data = data.borrow();
                    (
                        data.moc_macro.clone(),
                        data.moc_underscore.clone(),
                        data.moc_dot.clone(),
                    )
                }
                None => (String::new(), Vec::new(), Vec::new()),
            }
        };
        if !file_moc || (macro_name.is_empty() && underscore.is_empty() && dot.is_empty()) {
            return true;
        }

        let source_dir_prefix = sub_dir_prefix(&file_name);
        let source_base = crate::util::filename_without_last_extension(&file_name);

        // For relaxed mode check if the own "moc_" or ".moc" file is
        // included
        let relaxed_mode = self.mconst.relaxed_mode;
        let mut source_includes_moc_underscore = false;
        let mut source_includes_dot_moc = false;
        // Check if the sources own "moc_" or ".moc" file is included
        if relaxed_mode {
            for inc_key in &underscore {
                if inc_key.base == source_base {
                    source_includes_moc_underscore = true;
                    break;
                }
            }
        }
        for inc_key in &dot {
            if inc_key.base == source_base {
                source_includes_dot_moc = true;
                break;
            }
        }

        // Check if this source needs to be moc processed but doesn't.
        if !source_includes_dot_moc
            && !macro_name.is_empty()
            && (!relaxed_mode || !source_includes_moc_underscore)
        {
            self.log_error(
                GenT::Moc,
                &format!(
                    "{}\ncontains a {} macro, but does not include {}!\n\
                     Consider to\n  - add #include \"{source_base}.moc\"\
                     \n  - enable SKIP_AUTOMOC for this file",
                    self.message_path(&file_name),
                    quoted(&macro_name),
                    self.message_path(&format!("{source_base}.moc")),
                ),
            );
            return false;
        }

        // Evaluate "moc_" includes
        for inc_key in &underscore {
            let header_base = format!("{}{}", inc_key.dir, inc_key.base);
            let Some(header_handle) = self.find_included_header(&source_dir_prefix, &header_base)
            else {
                self.log_error(
                    GenT::Moc,
                    &format!(
                        "{}\nincludes the moc file {},\nbut a header {}\n\
                         could not be found in the following directories\n{}",
                        self.message_path(&file_name),
                        self.message_path(&inc_key.key),
                        self.message_header(&header_base),
                        self.message_search_locations()
                    ),
                );
                return false;
            };
            // The include might be handled differently in relaxed mode
            if relaxed_mode
                && !source_includes_dot_moc
                && !macro_name.is_empty()
                && inc_key.base == source_base
            {
                // Issue a warning
                self.base.log.warning(
                    GenT::Moc,
                    &format!(
                        "{}\ncontains a {} macro, but does not include {}.\n\
                         Instead it includes {}.\nRunning moc on the source\n  {}\
                         !\nBetter include {} for compatibility with regular mode.\n\
                         This is a CMAKE_AUTOMOC_RELAXED_MODE warning.\n",
                        self.message_path(&file_name),
                        quoted(&macro_name),
                        self.message_path(&format!("{source_base}.moc")),
                        self.message_path(&inc_key.key),
                        self.message_path(&file_name),
                        self.message_path(&format!("{source_base}.moc")),
                    ),
                );

                // Create mapping
                if !self.register_moc_included(&inc_key.key, source.clone(), source.clone()) {
                    return false;
                }
                continue;
            }

            // Check if header is skipped
            if self.mconst.skipped(&header_handle.borrow().file_name) {
                continue;
            }
            // Create mapping
            if !self.register_moc_included(&inc_key.key, source.clone(), header_handle) {
                return false;
            }
        }

        // Evaluate ".moc" includes
        if relaxed_mode {
            // Relaxed mode
            for inc_key in &dot {
                // Check if this is the sources own .moc file
                let own_moc = inc_key.base == source_base;
                if own_moc && !macro_name.is_empty() {
                    // Create mapping for the regular use case
                    if !self.register_moc_included(&inc_key.key, source.clone(), source.clone()) {
                        return false;
                    }
                    continue;
                }
                // Try to find a header instead but issue a warning.
                // This is for KDE4 compatibility.
                let header_base = format!("{}{}", inc_key.dir, inc_key.base);
                let Some(header_handle) =
                    self.find_included_header(&source_dir_prefix, &header_base)
                else {
                    self.log_error(
                        GenT::Moc,
                        &format!(
                            "{}\nincludes the moc file {},\nwhich seems to be the \
                             moc file from a different source file.\n\
                             CMAKE_AUTOMOC_RELAXED_MODE:\nAlso a matching header {}\n\
                             could not be found in the following directories\n{}",
                            self.message_path(&file_name),
                            self.message_path(&inc_key.key),
                            self.message_header(&header_base),
                            self.message_search_locations()
                        ),
                    );
                    return false;
                };
                // Check if header is skipped
                if self.mconst.skipped(&header_handle.borrow().file_name) {
                    continue;
                }
                // Issue a warning
                if own_moc && macro_name.is_empty() {
                    self.base.log.warning(
                        GenT::Moc,
                        &format!(
                            "{}\nincludes the moc file {}, but does not contain a\n\
                             {} macro.\nRunning moc on the header\n  {}!\n\
                             Better include {} for a compatibility with regular mode.\n\
                             This is a CMAKE_AUTOMOC_RELAXED_MODE warning.\n",
                            self.message_path(&file_name),
                            self.message_path(&inc_key.key),
                            self.mconst.macros_string(),
                            self.message_path(&header_handle.borrow().file_name),
                            self.message_path(&format!("moc_{}.cpp", inc_key.base)),
                        ),
                    );
                } else {
                    self.base.log.warning(
                        GenT::Moc,
                        &format!(
                            "{}\nincludes the moc file {} instead of {}.\n\
                             Running moc on the header\n  {}!\nBetter include {} \
                             for compatibility with regular mode.\n\
                             This is a CMAKE_AUTOMOC_RELAXED_MODE warning.\n",
                            self.message_path(&file_name),
                            self.message_path(&inc_key.key),
                            self.message_path(&format!("moc_{}.cpp", inc_key.base)),
                            self.message_path(&header_handle.borrow().file_name),
                            self.message_path(&format!("moc_{}.cpp", inc_key.base)),
                        ),
                    );
                }
                // Create mapping
                if !self.register_moc_included(&inc_key.key, source.clone(), header_handle) {
                    return false;
                }
            }
        } else {
            // Strict mode
            for inc_key in &dot {
                // Check if this is the sources own .moc file
                let own_moc = inc_key.base == source_base;
                if !own_moc {
                    // Don't allow <BASE>.moc include other than own in
                    // regular mode
                    self.log_error(
                        GenT::Moc,
                        &format!(
                            "{}\nincludes the moc file {},\nwhich seems to be the \
                             moc file from a different source file.\nThis is not \
                             supported.  Include {} to run moc on this source file.",
                            self.message_path(&file_name),
                            self.message_path(&inc_key.key),
                            self.message_path(&format!("{source_base}.moc")),
                        ),
                    );
                    return false;
                }
                // Accept but issue a warning if moc isn't required
                if macro_name.is_empty() {
                    self.base.log.warning(
                        GenT::Moc,
                        &format!(
                            "{}\nincludes the moc file {}, but does not contain a {} macro.",
                            self.message_path(&file_name),
                            self.message_path(&inc_key.key),
                            self.mconst.macros_string(),
                        ),
                    );
                }
                // Create mapping
                if !self.register_moc_included(&inc_key.key, source.clone(), source.clone()) {
                    return false;
                }
            }
        }

        true
    }

    /// `JobEvalCacheMocT::FindIncludedHeader`.
    fn find_included_header(
        &mut self,
        includer_dir: &str,
        include_base: &str,
    ) -> Option<SourceFileHandle> {
        // Clear search locations
        self.search_locations.clear();

        // Search in vicinity of the source
        if let Some(handle) = self.find_header(&format!("{includer_dir}{include_base}")) {
            return Some(handle);
        }
        // Search in include directories
        let include_paths = self.mconst.include_paths.clone();
        for path in &include_paths {
            let base_path = format!("{path}/{include_base}");
            if let Some(handle) = self.find_header(&base_path) {
                return Some(handle);
            }
        }
        None
    }

    /// The `findHeader` closure of `FindIncludedHeader`.
    fn find_header(&mut self, base_path: &str) -> Option<SourceFileHandle> {
        for ext in &self.bconst.header_extensions {
            let test_path = crate::util::collapse_full_path(
                &format!("{base_path}.{ext}"),
                &self.base.project_dirs.current_source,
            );
            let file_time = FileTime::load(&test_path);
            if !file_time.exists() {
                // File not found
                continue;
            }

            // Return a known file if it exists already
            if let Some(handle) = self.beval.headers.get(&test_path) {
                return Some(handle.clone());
            }

            // Created and return discovered file entry
            if !self.meval.headers_discovered.contains_key(&test_path) {
                self.meval.headers_discovered.insert(
                    test_path.clone(),
                    Rc::new(RefCell::new(SourceFile {
                        file_name: test_path.clone(),
                        file_time,
                        parse_data: None,
                        build_path: String::new(),
                        is_header: true,
                        moc: true,
                        uic: false,
                    })),
                );
            }
            return self.meval.headers_discovered.get(&test_path).cloned();
        }
        self.search_locations.push(parent_dir(base_path));
        None
    }

    /// `JobEvalCacheMocT::RegisterIncluded`.
    fn register_moc_included(
        &mut self,
        include_string: &str,
        includer_file_handle: SourceFileHandle,
        source_file_handle: SourceFileHandle,
    ) -> bool {
        // Check if this file is already included
        if let Some(handle) = self.meval.includes.get(include_string) {
            // Check if the output file would be generated from different
            // source files
            let same_source = {
                let h = handle.borrow();
                Rc::ptr_eq(&h.source_file, &source_file_handle)
            };
            if !same_source {
                let mut files = format!(
                    "  {}\n",
                    self.message_path(&includer_file_handle.borrow().file_name)
                );
                for item in &handle.borrow().includer_files {
                    files.push_str(&format!(
                        "  {}\n",
                        self.message_path(&item.borrow().file_name)
                    ));
                }
                self.log_error(
                    GenT::Moc,
                    &format!(
                        "The source files\n{files}contain the same include string {}, \
                         but\nthe moc file would be generated from different source \
                         files\n  {} and\n  {}.\nConsider to\n  - not include the \
                         \"moc_<NAME>.cpp\" file\n  - add a directory prefix to a \
                         \"<NAME>.moc\" include (e.g \"sub/<NAME>.moc\")\n  - rename \
                         the source file(s)\n",
                        self.message_path(include_string),
                        self.message_path(&source_file_handle.borrow().file_name),
                        self.message_path(&handle.borrow().source_file.borrow().file_name),
                    ),
                );
                return false;
            }

            // The same mapping already exists. Just add to the includers
            // list.
            handle
                .borrow_mut()
                .includer_files
                .push(includer_file_handle);
            return true;
        }

        // Create a new mapping
        let handle = Rc::new(RefCell::new(Mapping {
            source_file: source_file_handle,
            output_file: self.absolute_include_path(include_string),
            include_string: include_string.to_owned(),
            includer_files: vec![includer_file_handle],
        }));
        self.meval
            .includes
            .insert(include_string.to_owned(), handle.clone());
        // Register mapping in sources/headers map
        self.register_moc_mapping(handle);
        true
    }

    /// `JobEvalCacheMocT::RegisterMapping`.
    fn register_moc_mapping(&mut self, mapping_handle: MappingHandle) {
        let (is_header, file_name, include_string_empty) = {
            let m = mapping_handle.borrow();
            let s = m.source_file.borrow();
            (
                s.is_header,
                s.file_name.clone(),
                m.include_string.is_empty(),
            )
        };
        let reg_map = if is_header {
            &mut self.meval.header_mappings
        } else {
            &mut self.meval.source_mappings
        };
        // Check if source file already gets mapped
        match reg_map.entry(file_name) {
            std::collections::btree_map::Entry::Vacant(e) => {
                // Yet unknown mapping
                e.insert(mapping_handle);
            }
            std::collections::btree_map::Entry::Occupied(mut e) => {
                // Mappings with include string override those without
                if !include_string_empty {
                    e.insert(mapping_handle);
                }
            }
        }
    }
}

// - Uic eval jobs ----------------------------------------------------------

impl MocUic {
    /// `JobEvalCacheUicT::Process`.
    fn job_eval_cache_uic(&mut self) {
        // Prepare buffers
        self.search_locations = Vec::with_capacity((self.uconst.search_paths.len() + 1) * 2);

        // Evaluate headers
        let headers: Vec<SourceFileHandle> = self.beval.headers.values().cloned().collect();
        for source in headers {
            if !self.eval_uic_file(&source) {
                return;
            }
        }
        // Evaluate sources
        let sources: Vec<SourceFileHandle> = self.beval.sources.values().cloned().collect();
        for source in sources {
            if !self.eval_uic_file(&source) {
                return;
            }
        }
    }

    /// `JobEvalCacheUicT::EvalFile`.
    fn eval_uic_file(&mut self, source_file_handle: &SourceFileHandle) -> bool {
        let (file_uic, file_name) = {
            let file = source_file_handle.borrow();
            (file.uic, file.file_name.clone())
        };
        let include = {
            let file = source_file_handle.borrow();
            file.parse_data
                .as_ref()
                .map(|d| d.borrow().uic_include.clone())
                .unwrap_or_default()
        };
        if !file_uic || include.is_empty() {
            return true;
        }

        let source_dir_prefix = sub_dir_prefix(&file_name);
        for inc_key in &include {
            // Find .ui file
            self.uic_name = format!("{}.ui", inc_key.base);
            if !self.find_included_ui(&source_dir_prefix, &inc_key.dir) {
                self.log_error(
                    GenT::Uic,
                    &format!(
                        "{}\nincludes the uic file {},\nbut the user interface file \
                         {}\ncould not be found in the following directories\n{}",
                        self.message_path(&file_name),
                        self.message_path(&inc_key.key),
                        self.message_path(&self.uic_name.clone()),
                        self.message_search_locations()
                    ),
                );
                return false;
            }
            // Check if the file is skipped
            let ui_file_name = self
                .uic_file_handle
                .as_ref()
                .map(|h| h.borrow().file_name.clone())
                .unwrap_or_default();
            if self.uconst.skipped(&ui_file_name) {
                continue;
            }
            // Register mapping
            if !self.register_uic_mapping(&inc_key.key, source_file_handle.clone()) {
                return false;
            }
        }
        true
    }

    /// `JobEvalCacheUicT::FindIncludedUi`.
    fn find_included_ui(&mut self, source_dir_prefix: &str, include_prefix: &str) -> bool {
        // Clear locations buffer
        self.search_locations.clear();

        // Vicinity of the source
        if !include_prefix.is_empty()
            && self.find_ui(&format!(
                "{source_dir_prefix}{include_prefix}{}",
                self.uic_name
            ))
        {
            return true;
        }
        if self.find_ui(&format!("{source_dir_prefix}{}", self.uic_name)) {
            return true;
        }
        // Additional AUTOUIC search paths
        let search_paths = self.uconst.search_paths.clone();
        if !search_paths.is_empty() {
            for s_path in &search_paths {
                if self.find_ui(&format!("{s_path}/{}", self.uic_name)) {
                    return true;
                }
            }
            if !include_prefix.is_empty() {
                for s_path in &search_paths {
                    if self.find_ui(&format!("{s_path}/{include_prefix}{}", self.uic_name)) {
                        return true;
                    }
                }
            }
        }

        false
    }

    /// The `findUi` closure of `FindIncludedUi`.
    fn find_ui(&mut self, test_path: &str) -> bool {
        let full_path =
            crate::util::collapse_full_path(test_path, &self.base.project_dirs.current_source);
        let file_time = FileTime::load(&full_path);
        if !file_time.exists() {
            self.search_locations.push(parent_dir(&full_path));
            return false;
        }
        // .ui file found in files system!
        // Get or create .ui file handle
        let handle = self
            .ueval
            .ui_files
            .entry(full_path.clone())
            .or_insert_with(|| {
                Rc::new(RefCell::new(SourceFile {
                    file_name: full_path.clone(),
                    file_time,
                    parse_data: None,
                    build_path: String::new(),
                    is_header: false,
                    moc: false,
                    uic: false,
                }))
            })
            .clone();
        self.uic_file_handle = Some(handle);
        true
    }

    /// `JobEvalCacheUicT::RegisterMapping`.
    fn register_uic_mapping(
        &mut self,
        include_string: &str,
        includer_file_handle: SourceFileHandle,
    ) -> bool {
        if let Some(handle) = self.ueval.includes.get(include_string) {
            let ui_file_handle = self.uic_file_handle.clone().unwrap();
            let same_source = {
                let h = handle.borrow();
                Rc::ptr_eq(&h.source_file, &ui_file_handle)
            };
            if !same_source {
                // The output file already gets generated - from a
                // different .ui file!
                let mut files = format!(
                    "  {}\n",
                    self.message_path(&includer_file_handle.borrow().file_name)
                );
                for item in &handle.borrow().includer_files {
                    files.push_str(&format!(
                        "  {}\n",
                        self.message_path(&item.borrow().file_name)
                    ));
                }
                self.log_error(
                    GenT::Uic,
                    &format!(
                        "The source files\n{files}contain the same include string {}, \
                         but\nthe uic file would be generated from different user \
                         interface files\n  {} and\n  {}.\nConsider to\n  - add a \
                         directory prefix to a \"ui_<NAME>.h\" include (e.g \
                         \"sub/ui_<NAME>.h\")\n  - rename the <NAME>.ui file(s) and \
                         adjust the \"ui_<NAME>.h\" include(s)\n",
                        quoted(include_string),
                        self.message_path(&ui_file_handle.borrow().file_name),
                        self.message_path(&handle.borrow().source_file.borrow().file_name),
                    ),
                );
                return false;
            }
            // Add includer file to existing mapping
            handle
                .borrow_mut()
                .includer_files
                .push(includer_file_handle);
        } else {
            // New mapping handle
            let handle = Rc::new(RefCell::new(Mapping {
                source_file: self.uic_file_handle.clone().unwrap(),
                output_file: self.absolute_include_path(include_string),
                include_string: include_string.to_owned(),
                includer_files: vec![includer_file_handle],
            }));
            // Register mapping
            self.ueval
                .includes
                .insert(include_string.to_owned(), handle);
        }
        true
    }
}

// - Eval finish / probe jobs ------------------------------------------------

impl MocUic {
    /// `JobEvalCacheFinishT::Process`.
    fn job_eval_cache_finish(&mut self) {
        // Add discovered header parse jobs
        let discovered = std::mem::take(&mut self.meval.headers_discovered);
        self.create_parse_jobs(&discovered, true);
        self.meval.headers_discovered = discovered;

        // Add dependency probing jobs
        {
            // Add fence job to ensure all parsing has finished
            self.jobs.push_back(Job::Fence);
            if self.mconst.enabled {
                self.jobs.push_back(Job::ProbeDepsMoc);
            }
            if self.uconst.enabled {
                self.jobs.push_back(Job::ProbeDepsUic);
            }
            // Add probe finish job
            self.jobs.push_back(Job::ProbeDepsFinish);
        }
    }

    /// `JobMocPredefsT::Process`.
    fn job_moc_predefs(&mut self) {
        // (Re)generate moc_predefs.h on demand
        let verbose = self.base.log.verbose();
        let mut reason = String::new();
        if !self.moc_predefs_update(if verbose { Some(&mut reason) } else { None }) {
            return;
        }
        let predefs_file_abs = self.mconst.predefs_file_abs.clone();
        {
            // Compose command
            let mut cmd = self.mconst.predefs_cmd.clone();
            // Add definitions
            cmd.extend(self.mconst.options_definitions.iter().cloned());
            // Add includes
            cmd.extend(self.mconst.options_includes.iter().cloned());

            // Execute command
            let result = self.job_run_process(
                GenT::Moc,
                &cmd,
                if verbose { Some(reason.as_str()) } else { None },
            );
            if result.error() {
                self.log_command_error(
                    GenT::Moc,
                    &format!(
                        "The content generation command for {} failed.\n{}",
                        self.message_path(&predefs_file_abs),
                        result.error_message
                    ),
                    &cmd,
                    &lossy(&result.stdout),
                );
                return;
            }

            // (Re)write predefs file only on demand
            if file_differs(&predefs_file_abs, &result.stdout) {
                if !file_write(&predefs_file_abs, &result.stdout, None) {
                    self.log_error(
                        GenT::Moc,
                        &format!("Writing {} failed.", self.message_path(&predefs_file_abs)),
                    );
                    return;
                }
            } else {
                // Touch to update the time stamp
                if verbose {
                    self.base.log.info(
                        GenT::Moc,
                        &format!("Touching {}", self.message_path(&predefs_file_abs)),
                    );
                }
                if !touch(&predefs_file_abs, false) {
                    self.log_error(
                        GenT::Moc,
                        &format!("Touching {} failed.", self.message_path(&predefs_file_abs)),
                    );
                    return;
                }
            }
        }

        // Read file time afterwards
        self.meval.predefs_time = FileTime::load(&predefs_file_abs);
        if !self.meval.predefs_time.exists() {
            self.log_error(
                GenT::Moc,
                &format!(
                    "Reading the file time of {} failed.",
                    self.message_path(&predefs_file_abs)
                ),
            );
        }
    }

    /// `JobMocPredefsT::Update`.
    fn moc_predefs_update(&self, reason: Option<&mut String>) -> bool {
        let mut reason = reason;
        // Test if the file exists
        if !FileTime::load(&self.mconst.predefs_file_abs).exists() {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because it doesn't exist.",
                    self.message_path(&self.mconst.predefs_file_abs)
                );
            }
            return true;
        }

        // Test if the settings changed
        if self.mconst.settings_changed {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because the moc settings changed.",
                    self.message_path(&self.mconst.predefs_file_abs)
                );
            }
            return true;
        }

        // Test if the executable is newer
        {
            let exec = &self.mconst.predefs_cmd[0];
            let exec_time = FileTime::load(exec);
            if exec_time.exists() {
                let predefs_time = FileTime::load(&self.mconst.predefs_file_abs);
                if predefs_time.older(&exec_time) {
                    if let Some(reason) = &mut reason {
                        **reason = format!(
                            "Generating {} because it is older than {}.",
                            self.message_path(&self.mconst.predefs_file_abs),
                            self.message_path(exec)
                        );
                    }
                    return true;
                }
            }
        }

        false
    }

    /// `JobProbeDepsMocT::Process`.
    fn job_probe_deps_moc(&mut self) {
        // Create moc header jobs
        let header_mappings: Vec<MappingHandle> =
            self.meval.header_mappings.values().cloned().collect();
        for mapping in header_mappings {
            // Register if this mapping is a candidate for
            // mocs_compilation.cpp
            let comp_file = mapping.borrow().include_string.is_empty();
            if comp_file {
                let build_path = mapping.borrow().source_file.borrow().build_path.clone();
                self.meval.comp_files.push(build_path);
            }
            if !self.probe_deps_moc_generate(&mapping, comp_file) {
                return;
            }
        }

        // Create moc source jobs
        let source_mappings: Vec<MappingHandle> =
            self.meval.source_mappings.values().cloned().collect();
        for mapping in source_mappings {
            if !self.probe_deps_moc_generate(&mapping, false) {
                return;
            }
        }
    }

    /// `JobProbeDepsMocT::Generate`.
    fn probe_deps_moc_generate(&mut self, mapping: &MappingHandle, comp_file: bool) -> bool {
        let verbose = self.base.log.verbose();
        let mut reason = String::new();
        if self.probe_deps_moc(mapping, if verbose { Some(&mut reason) } else { None }) {
            // Register the parent directory for creation
            let output_dir = parent_dir(&mapping.borrow().output_file);
            self.meval.output_dirs.insert(output_dir);
            // Fetch the cache entry for the source file
            let source_file = mapping.borrow().source_file.borrow().file_name.clone();
            let (cache_entry, _) = self.beval.parse_cache.get_or_insert(&source_file);
            // Add moc job
            self.jobs.push_back(Job::CompileMoc {
                mapping: mapping.clone(),
                reason: if verbose { Some(reason) } else { None },
                cache: cache_entry,
            });
            // Check if a moc job for a mocs_compilation.cpp entry was
            // generated
            if comp_file {
                self.meval.comp_updated = true;
            }
        }
        true
    }

    /// `JobProbeDepsMocT::Probe`.
    fn probe_deps_moc(&mut self, mapping: &MappingHandle, reason: Option<&mut String>) -> bool {
        let mut reason = reason;
        let (source_file, output_file, source_time) = {
            let m = mapping.borrow();
            let s = m.source_file.borrow();
            (s.file_name.clone(), m.output_file.clone(), s.file_time)
        };

        // Test if the output file exists
        let output_file_time = FileTime::load(&output_file);
        if !output_file_time.exists() {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because it doesn't exist, from {}",
                    self.message_path(&output_file),
                    self.message_path(&source_file)
                );
            }
            return true;
        }

        // Test if any setting changed
        if self.mconst.settings_changed {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because the moc settings changed, from {}",
                    self.message_path(&output_file),
                    self.message_path(&source_file)
                );
            }
            return true;
        }

        // Test if the source file is newer
        if output_file_time.older(&source_time) {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because it's older than its source file, from {}",
                    self.message_path(&output_file),
                    self.message_path(&source_file)
                );
            }
            return true;
        }

        // Test if the moc_predefs file is newer
        if !self.mconst.predefs_file_abs.is_empty()
            && output_file_time.older(&self.meval.predefs_time)
        {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because it's older than {}, from {}",
                    self.message_path(&output_file),
                    self.message_path(&self.mconst.predefs_file_abs),
                    self.message_path(&source_file)
                );
            }
            return true;
        }

        // Test if the moc executable is newer
        if output_file_time.older(&self.mconst.executable_time) {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because it's older than the moc executable, from {}",
                    self.message_path(&output_file),
                    self.message_path(&source_file)
                );
            }
            return true;
        }

        // Test if a dependency file is newer
        {
            // Check dependency timestamps
            let source_dir = sub_dir_prefix(&source_file);
            let parse_data = mapping.borrow().source_file.borrow().parse_data.clone();
            if let Some(parse_data) = parse_data {
                let mut data = parse_data.borrow_mut();
                let mut index = 0;
                while index < data.moc_depends.len() {
                    let dep = data.moc_depends[index].clone();

                    // Find dependency file
                    let Some((dep_name, dep_time)) = self.find_dependency(&source_dir, &dep) else {
                        if let Some(reason) = &mut reason {
                            **reason = format!(
                                "Generating {} from {}, because its dependency {} vanished.",
                                self.message_path(&output_file),
                                self.message_path(&source_file),
                                self.message_path(&dep)
                            );
                        }
                        data.moc_depends.remove(index);
                        self.beval.parse_cache_changed = true;
                        return true;
                    };

                    // Test if dependency file is older
                    if output_file_time.older(&dep_time) {
                        if let Some(reason) = &mut reason {
                            **reason = format!(
                                "Generating {}, because it's older than its dependency \
                                 file {}, from {}",
                                self.message_path(&output_file),
                                self.message_path(&dep_name),
                                self.message_path(&source_file)
                            );
                        }
                        return true;
                    }
                    index += 1;
                }
            }
        }

        false
    }

    /// `JobProbeDepsMocT::FindDependency` (empty pair -> `None`).
    fn find_dependency(
        &self,
        source_dir: &str,
        include_string: &str,
    ) -> Option<(String, FileTime)> {
        // moc's dependency file contains absolute paths
        if self.mconst.can_output_dependencies {
            let time = FileTime::load(include_string);
            if time.exists() {
                return Some((include_string.to_owned(), time));
            }
            return None;
        }
        // Search in vicinity of the source
        {
            let name = format!("{source_dir}{include_string}");
            let time = FileTime::load(&name);
            if time.exists() {
                return Some((name, time));
            }
        }
        // Search in include directories
        for include_path in &self.mconst.include_paths {
            let name = format!("{include_path}/{include_string}");
            let time = FileTime::load(&name);
            if time.exists() {
                return Some((name, time));
            }
        }
        None
    }

    /// `JobProbeDepsUicT::Process`.
    fn job_probe_deps_uic(&mut self) {
        let includes: Vec<MappingHandle> = self.ueval.includes.values().cloned().collect();
        for mapping in includes {
            let verbose = self.base.log.verbose();
            let mut reason = String::new();
            if !self.probe_deps_uic(&mapping, if verbose { Some(&mut reason) } else { None }) {
                continue;
            }

            // Register the parent directory for creation
            let output_dir = parent_dir(&mapping.borrow().output_file);
            self.ueval.output_dirs.insert(output_dir);
            // Add uic job
            self.jobs.push_back(Job::CompileUic {
                mapping,
                reason: if verbose { Some(reason) } else { None },
            });
        }
    }

    /// `JobProbeDepsUicT::Probe`.
    fn probe_deps_uic(&self, mapping: &MappingHandle, reason: Option<&mut String>) -> bool {
        let mut reason = reason;
        let (source_file, output_file, source_time) = {
            let m = mapping.borrow();
            let s = m.source_file.borrow();
            (s.file_name.clone(), m.output_file.clone(), s.file_time)
        };

        // Test if the build file exists
        let output_file_time = FileTime::load(&output_file);
        if !output_file_time.exists() {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because it doesn't exist, from {}",
                    self.message_path(&output_file),
                    self.message_path(&source_file)
                );
            }
            return true;
        }

        // Test if the uic settings changed
        if self.uconst.settings_changed {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because the uic settings changed, from {}",
                    self.message_path(&output_file),
                    self.message_path(&source_file)
                );
            }
            return true;
        }

        // Test if the source file is newer
        if output_file_time.older(&source_time) {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {} because it's older than the source file {}",
                    self.message_path(&output_file),
                    self.message_path(&source_file)
                );
            }
            return true;
        }

        // Test if the uic executable is newer
        if output_file_time.older(&self.uconst.executable_time) {
            if let Some(reason) = &mut reason {
                **reason = format!(
                    "Generating {}, because it's older than the uic executable, from {}",
                    self.message_path(&output_file),
                    self.message_path(&source_file)
                );
            }
            return true;
        }

        false
    }

    /// `JobProbeDepsFinishT::Process`.
    fn job_probe_deps_finish(&mut self) {
        // Create output directories
        {
            let (gen_type, output_dirs) = if self.mconst.enabled && self.uconst.enabled {
                let mut set = self.meval.output_dirs.clone();
                set.extend(self.ueval.output_dirs.iter().cloned());
                (GenT::Gen, set)
            } else if self.mconst.enabled {
                (GenT::Moc, self.meval.output_dirs.clone())
            } else if self.uconst.enabled {
                (GenT::Uic, self.ueval.output_dirs.clone())
            } else {
                (GenT::Gen, BTreeSet::new())
            };
            for dir_name in &output_dirs {
                if std::fs::create_dir_all(dir_name).is_err() {
                    self.log_error(
                        gen_type,
                        &format!("Creating directory {} failed.", self.message_path(dir_name)),
                    );
                    break;
                }
            }
        }

        if self.mconst.enabled {
            // Add mocs compilations job
            self.jobs.push_back(Job::MocsCompilation);
        }

        if !self.bconst.dep_file.is_empty() {
            // Add job to merge dep files
            self.jobs.push_back(Job::DepFilesMerge);
        }

        // Add finish job
        self.jobs.push_back(Job::Finish);
    }
}

// - Compile jobs --------------------------------------------------------------

impl MocUic {
    /// `JobCompileMocT::Process`.
    fn job_compile_moc(
        &mut self,
        mapping: &MappingHandle,
        reason: Option<&str>,
        cache: &ParseHandle,
    ) {
        let (source_file, is_header) = {
            let m = mapping.borrow();
            let s = m.source_file.borrow();
            (s.file_name.clone(), s.is_header)
        };
        let output_file = mapping.borrow().output_file.clone();
        let includers: Vec<String> = mapping
            .borrow()
            .includer_files
            .iter()
            .map(|h| h.borrow().file_name.clone())
            .collect();

        // Remove output file in case the case of the source file has
        // changed
        let _ = std::fs::remove_file(&output_file);

        // Compose moc command
        let mut cmd: Vec<String> = Vec::new();
        {
            cmd.push(self.mconst.executable.clone());
            // Add definitions
            cmd.extend(self.mconst.options_definitions.iter().cloned());
            // Add includes
            cmd.extend(self.mconst.options_includes.iter().cloned());
            // Add predefs include
            if !self.mconst.predefs_file_abs.is_empty() {
                cmd.push("--include".to_owned());
                cmd.push(self.mconst.predefs_file_abs.clone());
            }
            // Add path prefix on demand
            if self.mconst.path_prefix && is_header {
                for dir in &self.mconst.include_paths {
                    let Some(rest) = source_file.strip_prefix(dir.as_str()) else {
                        continue;
                    };
                    if let Some(rest) = rest.strip_prefix('/') {
                        match rest.rfind('/') {
                            Some(pos) => {
                                cmd.push("-p".to_owned());
                                cmd.push(rest[..pos].to_owned());
                            }
                            None => {
                                cmd.push("-p".to_owned());
                                cmd.push("./".to_owned());
                            }
                        }
                        break;
                    }
                }
            }
            // Add extra options
            cmd.extend(self.mconst.options_extra.iter().cloned());
            if self.mconst.can_output_dependencies {
                cmd.push("--output-dep-file".to_owned());
            }
            // Add output file
            cmd.push("-o".to_owned());
            cmd.push(output_file.clone());
            // Add source file
            cmd.push(source_file.clone());
        }

        // Execute moc command
        let result = self.job_run_process(GenT::Moc, &cmd, reason);
        if result.error() {
            // Moc command failed
            let mut includers_text = String::new();
            if !includers.is_empty() {
                includers_text.push_str("included by\n");
                for item in &includers {
                    includers_text.push_str(&format!("  {}\n", self.message_path(item)));
                }
            }
            self.log_command_error(
                GenT::Moc,
                &format!(
                    "The moc process failed to compile\n  {}\ninto\n  {}\n{}{}",
                    self.message_path(&source_file),
                    self.message_path(&output_file),
                    includers_text,
                    result.error_message
                ),
                &cmd,
                &lossy(&result.stdout),
            );
            return;
        }

        // Moc command success. Print moc output.
        if !result.stdout.is_empty() {
            self.base.log.info(GenT::Moc, &lossy(&result.stdout));
        }

        // Extract dependencies from the dep file moc generated for us
        if self.mconst.can_output_dependencies {
            let depfile = format!("{output_file}.d");
            if self.base.log.verbose() {
                self.base.log.info(
                    GenT::Moc,
                    &format!("Reading dependencies from {}", self.message_path(&depfile)),
                );
            }
            if !std::path::Path::new(&depfile).exists() {
                self.base.log.warning(
                    GenT::Moc,
                    &format!(
                        "Dependency file {} does not exist.",
                        self.message_path(&depfile)
                    ),
                );
                return;
            }
            cache.borrow_mut().moc_depends = self.dependencies_from_dep_file(&depfile);
        }
    }

    /// `JobCompileUicT::Process`.
    fn job_compile_uic(&mut self, mapping: &MappingHandle, reason: Option<&str>) {
        let source_file = mapping.borrow().source_file.borrow().file_name.clone();
        let output_file = mapping.borrow().output_file.clone();
        let includers: Vec<String> = mapping
            .borrow()
            .includer_files
            .iter()
            .map(|h| h.borrow().file_name.clone())
            .collect();

        // Compose uic command
        let mut cmd: Vec<String> = vec![self.uconst.executable.clone()];
        {
            let mut all_opts = self.uconst.options.clone();
            if let Some(opts) = self.uconst.ui_files.get(&source_file) {
                uic_merge_options(&mut all_opts, opts, self.bconst.qt_version.major >= 5);
            }
            cmd.extend(all_opts);
        }
        cmd.push("-o".to_owned());
        cmd.push(output_file.clone());
        cmd.push(source_file.clone());

        let result = self.job_run_process(GenT::Uic, &cmd, reason);
        if !result.error() {
            // Uic command success
            // Print uic output
            if !result.stdout.is_empty() {
                self.base.log.info(GenT::Uic, &lossy(&result.stdout));
            }
        } else {
            // Uic command failed
            let mut includers_text = String::new();
            for item in &includers {
                includers_text.push_str(&format!("  {}\n", self.message_path(item)));
            }
            self.log_command_error(
                GenT::Uic,
                &format!(
                    "The uic process failed to compile\n  {}\ninto\n  {}\
                     \nincluded by\n{}{}",
                    self.message_path(&source_file),
                    self.message_path(&output_file),
                    includers_text,
                    result.error_message
                ),
                &cmd,
                &lossy(&result.stdout),
            );
        }
    }

    /// `JobMocsCompilationT::Process`.
    fn job_mocs_compilation(&mut self) {
        let comp_abs = self.mconst.comp_file_abs.clone();

        // Compose mocs compilation file content
        let mut content =
            "// This file is autogenerated. Changes will be overwritten.\n".to_owned();

        if self.meval.comp_files.is_empty() {
            // Placeholder content
            content.push_str(
                "// No files found that require moc or the moc files are included\n\
                 enum some_compilers { need_more_than_nothing };\n",
            );
        } else {
            // Valid content
            let mc = self.bconst.multi_config;
            let wrap_front = if mc { "<" } else { "\"" };
            let wrap_back = if mc { ">\n" } else { "\"\n" };
            for file in &self.meval.comp_files {
                content.push_str(&format!("#include {wrap_front}{file}{wrap_back}"));
            }
        }

        if file_differs(&comp_abs, content.as_bytes()) {
            // Actually write mocs compilation file
            if self.base.log.verbose() {
                self.base.log.info(
                    GenT::Moc,
                    &format!(
                        "Generating MOC compilation {}",
                        self.message_path(&comp_abs)
                    ),
                );
            }
            if !file_write(&comp_abs, content.as_bytes(), None) {
                self.log_error(
                    GenT::Moc,
                    &format!(
                        "Writing MOC compilation {} failed.",
                        self.message_path(&comp_abs)
                    ),
                );
            }
        } else if self.meval.comp_updated {
            // Only touch mocs compilation file
            if self.base.log.verbose() {
                self.base.log.info(
                    GenT::Moc,
                    &format!("Touching MOC compilation {}", self.message_path(&comp_abs)),
                );
            }
            if !touch(&comp_abs, false) {
                self.log_error(
                    GenT::Moc,
                    &format!(
                        "Touching MOC compilation {} failed.",
                        self.message_path(&comp_abs)
                    ),
                );
            }
        }
    }

    /// `dependenciesFromDepFile`.
    fn dependencies_from_dep_file(&self, file_path: &str) -> Vec<String> {
        let Ok(content) = std::fs::read(file_path) else {
            return Vec::new();
        };
        let Some(rules) = super::super::depfile::parse(&lossy(&content)) else {
            return Vec::new();
        };
        // Moc outputs a depfile with exactly one rule.
        // Discard the rule and return the dependencies.
        rules
            .into_iter()
            .next()
            .map(|rule| rule.dependencies)
            .unwrap_or_default()
    }
}

/// `escapeDependencyPath` (re-implementation of what moc does when
/// writing depfiles).
fn escape_dependency_path(path: &str) -> String {
    let mut escaped_path: Vec<u8> = Vec::with_capacity(path.len());
    let mut backslash_count = 0usize;
    for &byte in path.as_bytes() {
        if byte == b'\\' {
            backslash_count += 1;
        } else {
            if byte == b'$' {
                escaped_path.push(b'$');
            } else if byte == b'#' {
                escaped_path.push(b'\\');
            } else if byte == b' ' {
                // Double the amount of written backslashes,
                // and add one more to escape the space.
                escaped_path.extend(std::iter::repeat_n(b'\\', backslash_count + 1));
            }
            backslash_count = 0;
        }
        escaped_path.push(byte);
    }
    lossy(&escaped_path)
}

// - Depfile merge job --------------------------------------------------------

impl MocUic {
    /// `JobDepFilesMergeT::initialDependencies`.
    fn initial_dependencies(&self) -> Vec<String> {
        let mut dependencies = Vec::new();
        dependencies.extend(self.bconst.list_files.iter().cloned());
        dependencies.extend(self.beval.headers.keys().cloned());
        dependencies.extend(self.beval.sources.keys().cloned());
        dependencies
    }

    /// `processDepFile` closure of `JobDepFilesMergeT`.
    fn process_dep_file(&self, moc_output_file: &str) -> Vec<String> {
        let f = format!("{moc_output_file}.d");
        if !std::path::Path::new(&f).exists() {
            return Vec::new();
        }
        self.dependencies_from_dep_file(&f)
    }

    /// `JobDepFilesMergeT::Process`.
    fn job_dep_files_merge(&mut self) {
        if self.base.log.verbose() {
            self.base.log.info(
                GenT::Moc,
                &format!(
                    "Merging MOC dependencies into {}",
                    self.message_path(&self.bconst.dep_file)
                ),
            );
        }

        let mut dependencies = self.initial_dependencies();
        // Header mappings then source mappings
        let mapping_keys: Vec<String> = self
            .meval
            .header_mappings
            .keys()
            .chain(self.meval.source_mappings.keys())
            .cloned()
            .collect();
        for key in mapping_keys {
            let output_file = self
                .meval
                .header_mappings
                .get(&key)
                .or_else(|| self.meval.source_mappings.get(&key))
                .map(|m| m.borrow().output_file.clone())
                .unwrap_or_default();
            let (cache_entry, _) = self.beval.parse_cache.get_or_insert(&key);
            let mut entry = cache_entry.borrow_mut();
            if entry.moc_depends.is_empty() {
                entry.moc_depends = self.process_dep_file(&output_file);
            }
            dependencies.extend(entry.moc_depends.iter().cloned());
        }

        // Remove SKIP_AUTOMOC files.
        // Also remove AUTOUIC header files to avoid cyclic dependency.
        let uic_outputs: BTreeSet<String> = self
            .ueval
            .includes
            .values()
            .map(|m| m.borrow().output_file.clone())
            .collect();
        dependencies.retain(|dep| !self.mconst.skipped(dep) && !uic_outputs.contains(dep));

        // Remove duplicates to make the depfile smaller
        dependencies.sort();
        dependencies.dedup();

        // Add form files
        for uif in self.ueval.ui_files.keys() {
            dependencies.push(uif.clone());
        }

        // Write the file
        let mut ofs = match std::fs::File::create(&self.bconst.dep_file) {
            Ok(file) => file,
            Err(_) => {
                self.log_error(
                    GenT::Gen,
                    &format!(
                        "Cannot open {} for writing.",
                        self.message_path(&self.bconst.dep_file)
                    ),
                );
                return;
            }
        };
        use std::io::Write as _;
        let _ = writeln!(ofs, "{}: \\", self.bconst.dep_file_rule_name);
        for file in &dependencies {
            let _ = writeln!(ofs, "\t{} \\", escape_dependency_path(file));
            if ofs.flush().is_err() {
                self.log_error(
                    GenT::Gen,
                    &format!(
                        "Writing depfile {} failed.",
                        self.message_path(&self.bconst.dep_file)
                    ),
                );
                return;
            }
        }

        // Add the CMake executable to re-new cache data if necessary.
        // Also, this is the last entry, so don't add a backslash.
        let _ = writeln!(
            ofs,
            "\t{}",
            escape_dependency_path(&self.bconst.cmake_executable)
        );
    }
}
