impl MocUic {
    /// `JobParseT::ReadFile`: clear parse data, read the file, warn on
    /// empty. Returns the content bytes.
    fn job_parse_read(&mut self, handle: &SourceFileHandle) -> Option<Vec<u8>> {
        // Clear old parse information
        let file_name = handle.borrow().file_name.clone();
        if let Some(data) = &handle.borrow().parse_data {
            data.borrow_mut().clear();
        }
        // Write info
        if self.base.log.verbose() {
            self.base.log.info(
                GenT::Gen,
                &format!("Parsing {}", self.message_path(&file_name)),
            );
        }
        // Read file content
        let mut error = String::new();
        let content = match file_read(&file_name, Some(&mut error)) {
            Some(content) => content,
            None => {
                self.log_error(
                    GenT::Gen,
                    &format!("Could not read {}.\n{error}", self.message_path(&file_name)),
                );
                return None;
            }
        };
        // Warn if empty
        if content.is_empty() {
            self.base.log.warning(
                GenT::Gen,
                &format!("{} is empty.", self.message_path(&file_name)),
            );
            return None;
        }
        Some(content)
    }

    /// `JobParseT::MocMacro`.
    fn moc_macro(&self, content: &[u8], data: &ParseHandle) {
        for filter in &self.mconst.macro_filters {
            // Run a simple find string check
            if bytes_find(content, filter.key.as_bytes()).is_none() {
                continue;
            }
            // Run the expensive regular expression check loop
            if filter.exp.find_bytes(content, 0, false).is_some() {
                // Keep detected macro name
                data.borrow_mut().moc_macro = filter.key.clone();
                return;
            }
        }
    }

    /// `JobParseT::MocDependencies`.
    fn moc_dependencies(&self, content: &[u8], data: &ParseHandle) {
        if self.mconst.depend_filters.is_empty() || self.mconst.can_output_dependencies {
            return;
        }

        // Find dependency strings
        let mut parse_depends: BTreeSet<String> = BTreeSet::new();
        for filter in &self.mconst.depend_filters {
            // Run a simple find string check
            if bytes_find(content, filter.key.as_bytes()).is_none() {
                continue;
            }
            // Run the expensive regular expression check loop
            let mut offset = 0;
            while let Some(m) = filter.exp.find_bytes(content, offset, false) {
                if let Some((s, e)) = m.groups[1] {
                    let dep = lossy(&content[s..e]);
                    if !dep.is_empty() {
                        parse_depends.insert(dep);
                    }
                }
                offset = m.groups[0].map_or(content.len(), |(_, e)| e);
            }
        }

        // Store dependency strings
        let mut data = data.borrow_mut();
        data.moc_depends.reserve(parse_depends.len());
        for item in parse_depends {
            // Replace end of line characters in filenames
            data.moc_depends.push(item.replace(['\n', '\r'], " "));
        }
    }

    /// `JobParseT::MocIncludes`.
    fn moc_includes(&self, content: &[u8], data: &ParseHandle) {
        if bytes_find(content, b"moc").is_none() {
            return;
        }

        let mut underscore: BTreeSet<String> = BTreeSet::new();
        let mut dot: BTreeSet<String> = BTreeSet::new();
        let mut offset = 0;
        while let Some(m) = self
            .mconst
            .regexp_include
            .find_bytes(content, offset, false)
        {
            if let Some((s, e)) = m.groups[2] {
                let inc_string = lossy(&content[s..e]);
                let inc_base = crate::util::filename_without_last_extension(&inc_string);
                if inc_base.starts_with("moc_") {
                    // moc_<BASE>.cpp
                    underscore.insert(inc_string);
                } else {
                    // <BASE>.moc
                    dot.insert(inc_string);
                }
            }
            offset = m.groups[0].map_or(content.len(), |(_, e)| e);
        }
        let mut data = data.borrow_mut();
        data.moc_underscore = sorted_keys(&underscore, MOC_UNDERSCORE_LEN);
        data.moc_dot = sorted_keys(&dot, 0);
    }

    /// `JobParseT::UicIncludes`.
    fn uic_includes(&self, content: &[u8], data: &ParseHandle) {
        if bytes_find(content, b"ui_").is_none() {
            return;
        }

        let mut includes: BTreeSet<String> = BTreeSet::new();
        let mut offset = 0;
        while let Some(m) = self
            .uconst
            .regexp_include
            .find_bytes(content, offset, false)
        {
            if let Some((s, e)) = m.groups[2] {
                includes.insert(lossy(&content[s..e]));
            }
            offset = m.groups[0].map_or(content.len(), |(_, e)| e);
        }
        data.borrow_mut().uic_include = sorted_keys(&includes, UI_UNDERSCORE_LEN);
    }

    /// `JobParseHeaderT::Process` / `JobParseSourceT::Process`.
    fn job_parse(&mut self, handle: &SourceFileHandle, is_header: bool) {
        let Some(content) = self.job_parse_read(handle) else {
            return;
        };
        let (moc, uic) = {
            let file = handle.borrow();
            (file.moc, file.uic)
        };
        let Some(data) = handle.borrow().parse_data.clone() else {
            return;
        };
        // Moc parsing
        if moc {
            self.moc_macro(&content, &data);
            self.moc_dependencies(&content, &data);
            if !is_header {
                self.moc_includes(&content, &data);
            }
        }
        // Uic parsing
        if uic {
            self.uic_includes(&content, &data);
        }
    }
}

