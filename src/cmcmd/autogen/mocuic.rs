//! `cmQtAutoMocUicT`: the AUTOMOC + AUTOUIC build-time generator behind
//! `cmake -E cmake_autogen`.  The upstream `cmWorkerPool` job queue is
//! executed sequentially; the fences are ordering barriers that a FIFO
//! queue preserves exactly, and every job is deterministic, so the
//! observable behavior is identical.

