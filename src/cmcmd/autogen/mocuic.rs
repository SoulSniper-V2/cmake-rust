/// `cmQtAutoMocUicT`.
pub(crate) struct MocUic {
    base: GeneratorBase,
    bconst: BaseSettings,
    beval: BaseEval,
    mconst: MocSettings,
    meval: MocEval,
    uconst: UicSettings,
    ueval: UicEval,
    settings_file: String,
    settings_string_moc: String,
    settings_string_uic: String,
    /// `JobError_`.
    job_error: bool,
    aborted: bool,
    jobs: VecDeque<Job>,
    /// `JobEvalCacheT::SearchLocations` scratch.
    search_locations: Vec<String>,
    /// `JobEvalCacheUicT` scratch state.
    uic_name: String,
    uic_file_handle: Option<SourceFileHandle>,
}

/// `cmQtAutoMocUic` entry point.
pub(crate) fn run(info_file: &str, config: &str, executable_config: &str) -> bool {
    let mut generator = MocUic {
        base: GeneratorBase::new(GenT::Gen),
        bconst: BaseSettings::default(),
        beval: BaseEval::default(),
        mconst: MocSettings::new(),
        meval: MocEval::default(),
        uconst: UicSettings::new(),
        ueval: UicEval::default(),
        settings_file: String::new(),
        settings_string_moc: String::new(),
        settings_string_uic: String::new(),
        job_error: false,
        aborted: false,
        jobs: VecDeque::new(),
        search_locations: Vec::new(),
        uic_name: String::new(),
        uic_file_handle: None,
    };
    let Some(json) = generator
        .base
        .run_init(info_file, config, executable_config)
    else {
        return false;
    };
    if !generator.init_from_info(&json) {
        return false;
    }
    generator.process()
}

// - Logging helpers ---------------------------------------------------

impl MocUic {
    /// `JobT::LogError` (error logging with automatic abort).
    fn log_error(&mut self, gen_type: GenT, message: &str) {
        self.aborted = true;
        self.job_error = true;
        self.base.log.error(gen_type, message);
    }

    /// `JobT::LogCommandError`.
    fn log_command_error(
        &mut self,
        gen_type: GenT,
        message: &str,
        command: &[String],
        output: &str,
    ) {
        self.aborted = true;
        self.job_error = true;
        self.base
            .log
            .error_command(gen_type, message, command, output);
    }

    fn message_path(&self, path: &str) -> String {
        self.base.message_path(path)
    }

    /// `JobT::RunProcess` (verbose command echo, run in `AutogenBuildDir`).
    fn job_run_process(
        &mut self,
        gen_type: GenT,
        command: &[String],
        info_message: Option<&str>,
    ) -> ProcessResult {
        if self.base.log.verbose() {
            let info = info_message.unwrap_or("");
            self.base.log.info(
                gen_type,
                &format!(
                    "{}{}{}\n",
                    info,
                    if info.is_empty() || info.ends_with('\n') {
                        ""
                    } else {
                        "\n"
                    },
                    quoted_command(command)
                ),
            );
        }
        run_process(command, &self.bconst.autogen_build_dir)
    }

    fn absolute_build_path(&self, relative_path: &str) -> String {
        format!("{}/{}", self.bconst.autogen_build_dir, relative_path)
    }

    fn absolute_include_path(&self, relative_path: &str) -> String {
        format!("{}/{}", self.bconst.autogen_include_dir, relative_path)
    }
}

// - InitFromInfo -------------------------------------------------------

impl MocUic {
    /// `cmQtAutoMocUicT::InitFromInfo`.
    fn init_from_info(&mut self, json: &serde_json::Value) -> bool {
        let info = Info::new(
            json,
            &self.base.info_config,
            &self.base.info_file,
            self.base.gen_type,
            &self.base.log,
        );
        let mut _thread_count = 0u32;
        // -- Required settings
        if !info.get_bool("MULTI_CONFIG", &mut self.bconst.multi_config, true)
            || !info.get_bool("CROSS_CONFIG", &mut self.bconst.cross_config, true)
            || !info.get_bool("USE_BETTER_GRAPH", &mut self.bconst.use_better_graph, true)
            || !info.get_uint("QT_VERSION_MAJOR", &mut self.bconst.qt_version.major, true)
            || !info.get_uint("QT_VERSION_MINOR", &mut self.bconst.qt_version.minor, true)
            || !info.get_uint("PARALLEL", &mut _thread_count, false)
            || !info.get_string("BUILD_DIR", &mut self.bconst.autogen_build_dir, true)
            || !info.get_string_config("INCLUDE_DIR", &mut self.bconst.autogen_include_dir, true)
            || !info.get_string("CMAKE_EXECUTABLE", &mut self.bconst.cmake_executable, true)
            || !info.get_string_config("PARSE_CACHE_FILE", &mut self.bconst.parse_cache_file, true)
            || !info.get_string_config("SETTINGS_FILE", &mut self.settings_file, true)
            || !info.get_array("CMAKE_LIST_FILES", &mut self.bconst.list_files, true)
            || !info.get_array(
                "HEADER_EXTENSIONS",
                &mut self.bconst.header_extensions,
                true,
            )
        {
            return false;
        }
        if self.bconst.use_better_graph {
            if !info.get_string_config("DEP_FILE", &mut self.bconst.dep_file, false)
                || !info.get_string_config(
                    "DEP_FILE_RULE_NAME",
                    &mut self.bconst.dep_file_rule_name,
                    false,
                )
            {
                return false;
            }
            if self.bconst.cross_config {
                let moc_key = format!("QT_MOC_EXECUTABLE_{}", self.base.executable_config);
                let uic_key = format!("QT_UIC_EXECUTABLE_{}", self.base.executable_config);
                if !info.get_string(&moc_key, &mut self.mconst.executable, false)
                    || !info.get_string(&uic_key, &mut self.uconst.executable, false)
                {
                    return false;
                }
            } else if !info.get_string_config(
                "QT_MOC_EXECUTABLE",
                &mut self.mconst.executable,
                false,
            ) || !info.get_string_config(
                "QT_UIC_EXECUTABLE",
                &mut self.uconst.executable,
                false,
            ) {
                return false;
            }
        } else if !info.get_string("QT_MOC_EXECUTABLE", &mut self.mconst.executable, false)
            || !info.get_string("QT_UIC_EXECUTABLE", &mut self.uconst.executable, false)
            || !info.get_string("DEP_FILE", &mut self.bconst.dep_file, false)
            || !info.get_string(
                "DEP_FILE_RULE_NAME",
                &mut self.bconst.dep_file_rule_name,
                false,
            )
        {
            return false;
        }

        // -- Checks
        self.bconst.cmake_executable_time = FileTime::load(&self.bconst.cmake_executable);
        if !self.bconst.cmake_executable_time.exists() {
            return info.log_error(format!(
                "The CMake executable {} does not exist.",
                self.message_path(&self.bconst.cmake_executable)
            ));
        }

        // -- Moc
        if !self.mconst.executable.is_empty() {
            // -- Moc is enabled
            self.mconst.enabled = true;

            // -- Temporary buffers
            let mut macro_names: Vec<String> = Vec::new();
            let mut depend_filters: Vec<String> = Vec::new();

            // -- Required settings
            if !info.get_bool("MOC_RELAXED_MODE", &mut self.mconst.relaxed_mode, false)
                || !info.get_bool("MOC_PATH_PREFIX", &mut self.mconst.path_prefix, true)
                || !info.get_array_set("MOC_SKIP", &mut self.mconst.skip_list, false)
                || !info.get_array_config("MOC_DEFINITIONS", &mut self.mconst.definitions, false)
                || !info.get_array_config("MOC_INCLUDES", &mut self.mconst.include_paths, false)
                || !info.get_array("MOC_OPTIONS", &mut self.mconst.options_extra, false)
                || !info.get_string_config(
                    "MOC_COMPILATION_FILE",
                    &mut self.mconst.comp_file_abs,
                    true,
                )
                || !info.get_array("MOC_PREDEFS_CMD", &mut self.mconst.predefs_cmd, false)
                || !info.get_string_config(
                    "MOC_PREDEFS_FILE",
                    &mut self.mconst.predefs_file_abs,
                    !self.mconst.predefs_cmd.is_empty(),
                )
                || !info.get_array("MOC_MACRO_NAMES", &mut macro_names, true)
                || !info.get_array("MOC_DEPEND_FILTERS", &mut depend_filters, false)
            {
                return false;
            }

            // -- Evaluate settings
            for item in macro_names {
                let key = item.clone();
                let pattern = format!("[\n][ \t]*{{?[ \t]*{item}[^a-zA-Z0-9_]");
                self.mconst.macro_filters.push(KeyExp {
                    key,
                    exp: crate::cmregex::Regex::new(&pattern).unwrap(),
                });
            }
            // Can moc output dependencies or do we need dependency filters?
            if self.bconst.qt_version.ge(5, 15) {
                self.mconst.can_output_dependencies = true;
            } else {
                let val = info.value("MOC_DEPEND_FILTERS");
                if !val.is_array() {
                    return info.log_error("MOC_DEPEND_FILTERS JSON value is not an array.".into());
                }
                for (ii, pair_val) in val
                    .as_array()
                    .map_or(&[][..], Vec::as_slice)
                    .iter()
                    .enumerate()
                {
                    macro_rules! test_entry {
                        ($test:expr, $msg:expr) => {
                            if !($test) {
                                info.log_error(format!("MOC_DEPEND_FILTERS filter {ii}: {}", $msg));
                                return false;
                            }
                        };
                    }
                    test_entry!(pair_val.is_array(), "JSON value is not an array.");
                    test_entry!(
                        pair_val.as_array().map_or(&[][..], Vec::as_slice).len() == 2,
                        "JSON array size invalid."
                    );
                    let pair = pair_val.as_array().map_or(&[][..], Vec::as_slice);
                    let key_val = &pair[0];
                    let exp_val = &pair[1];
                    test_entry!(
                        key_val.is_string(),
                        "JSON value for keyword is not a string."
                    );
                    test_entry!(
                        exp_val.is_string(),
                        "JSON value for regular expression is not a string."
                    );
                    let key = key_val.as_str().unwrap_or_default();
                    let exp = exp_val.as_str().unwrap_or_default();
                    test_entry!(!key.is_empty(), "Keyword is empty.");
                    test_entry!(!exp.is_empty(), "Regular expression is empty.");
                    let compiled = crate::cmregex::Regex::new(exp);
                    let exp_ok = compiled.is_ok();
                    if !exp_ok {
                        test_entry!(
                            false,
                            format!(
                                "Regular expression compilation failed.\nKeyword: {}\nExpression: {}",
                                quoted(key),
                                quoted(exp)
                            )
                        );
                    }
                    self.mconst.depend_filters.push(KeyExp {
                        key: key.to_owned(),
                        exp: compiled.unwrap(),
                    });
                }
            }
            // Check if moc executable exists (by reading the file time)
            self.mconst.executable_time = FileTime::load(&self.mconst.executable);
            if !self.mconst.executable_time.exists() {
                return info.log_error(format!(
                    "The moc executable {} does not exist.",
                    self.message_path(&self.mconst.executable)
                ));
            }
        }

        // -- Uic
        if !self.uconst.executable.is_empty() {
            // Uic is enabled
            self.uconst.enabled = true;

            // -- Required settings
            if !info.get_array_set("UIC_SKIP", &mut self.uconst.skip_list, false)
                || !info.get_array("UIC_SEARCH_PATHS", &mut self.uconst.search_paths, false)
                || !info.get_array_config("UIC_OPTIONS", &mut self.uconst.options, false)
            {
                return false;
            }
            // .ui files
            {
                let val = info.value("UIC_UI_FILES");
                if !val.is_array() {
                    return info.log_error("UIC_UI_FILES JSON value is not an array.".into());
                }
                for (ii, entry) in val
                    .as_array()
                    .map_or(&[][..], Vec::as_slice)
                    .iter()
                    .enumerate()
                {
                    macro_rules! test_entry {
                        ($test:expr, $msg:expr) => {
                            if !($test) {
                                info.log_error(format!("UIC_UI_FILES entry {ii}: {}", $msg));
                                return false;
                            }
                        };
                    }
                    test_entry!(entry.is_array(), "JSON value is not an array.");
                    test_entry!(
                        entry.as_array().map_or(&[][..], Vec::as_slice).len() == 2,
                        "JSON array size invalid."
                    );
                    let pair = entry.as_array().map_or(&[][..], Vec::as_slice);
                    let entry_name = &pair[0];
                    let entry_options = &pair[1];
                    test_entry!(
                        entry_name.is_string(),
                        "JSON value for name is not a string."
                    );
                    test_entry!(
                        entry_options.is_array(),
                        "JSON value for options is not an array."
                    );
                    let options = self
                        .uconst
                        .ui_files
                        .entry_or_default(entry_name.as_str().unwrap_or_default());
                    Info::json_array_vec(options, entry_options);
                }
            }

            // -- Evaluate settings
            // Check if uic executable exists (by reading the file time)
            self.uconst.executable_time = FileTime::load(&self.uconst.executable);
            if !self.uconst.executable_time.exists() {
                return info.log_error(format!(
                    "The uic executable {} does not exist.",
                    self.message_path(&self.uconst.executable)
                ));
            }
        }

        // -- Headers
        {
            let val = info.value("HEADERS");
            if !val.is_array() {
                return info.log_error("HEADERS JSON value is not an array.".into());
            }
            for (ii, entry) in val
                .as_array()
                .map_or(&[][..], Vec::as_slice)
                .iter()
                .enumerate()
            {
                macro_rules! test_entry {
                    ($test:expr, $msg:expr) => {
                        if !($test) {
                            info.log_error(format!("HEADERS entry {ii}: {}", $msg));
                            return false;
                        }
                    };
                }
                test_entry!(entry.is_array(), "JSON value is not an array.");
                test_entry!(
                    entry.as_array().map_or(&[][..], Vec::as_slice).len() == 4,
                    "JSON array size invalid."
                );
                let pair = entry.as_array().map_or(&[][..], Vec::as_slice);
                let (entry_name, entry_flags, entry_build, entry_configs) =
                    (&pair[0], &pair[1], &pair[2], &pair[3]);
                test_entry!(
                    entry_name.is_string(),
                    "JSON value for name is not a string."
                );
                test_entry!(
                    entry_flags.is_string(),
                    "JSON value for flags is not a string."
                );
                test_entry!(
                    entry_configs.is_null() || entry_configs.is_array(),
                    "JSON value for configs is not null or array."
                );
                test_entry!(
                    entry_build.is_string(),
                    "JSON value for build path is not a string."
                );

                let name = entry_name.as_str().unwrap_or_default().to_owned();
                let flags = entry_flags.as_str().unwrap_or_default();
                let build = entry_build.as_str().unwrap_or_default().to_owned();
                test_entry!(flags.len() == 2, "Invalid flags string size");

                if let Some(configs) = entry_configs.as_array() {
                    let mut config_found = false;
                    for config in configs {
                        test_entry!(
                            config.is_string(),
                            "JSON value in config array is not a string."
                        );
                        config_found = config_found
                            || config.as_str().unwrap_or_default() == self.base.info_config;
                    }
                    if !config_found {
                        continue;
                    }
                }

                let file_time = FileTime::load(&name);
                if !file_time.exists() {
                    return info.log_error(format!(
                        "The header file {} does not exist.",
                        self.message_path(&name)
                    ));
                }

                let is_moc = flags.as_bytes()[0] == b'M';
                let is_uic = flags.as_bytes()[1] == b'U';
                let mut build_path = String::new();
                if is_moc && self.mconst.enabled {
                    if build.is_empty() {
                        return info.log_error(format!("Header file {ii} build path is empty"));
                    }
                    build_path = build;
                }
                self.beval.headers.insert(
                    name.clone(),
                    Rc::new(RefCell::new(SourceFile {
                        file_name: name,
                        file_time,
                        parse_data: None,
                        build_path,
                        is_header: true,
                        moc: is_moc,
                        uic: is_uic,
                    })),
                );
            }
        }

        // -- Sources
        {
            let val = info.value("SOURCES");
            if !val.is_array() {
                return info.log_error("SOURCES JSON value is not an array.".into());
            }
            for (ii, entry) in val
                .as_array()
                .map_or(&[][..], Vec::as_slice)
                .iter()
                .enumerate()
            {
                macro_rules! test_entry {
                    ($test:expr, $msg:expr) => {
                        if !($test) {
                            info.log_error(format!("SOURCES entry {ii}: {}", $msg));
                            return false;
                        }
                    };
                }
                test_entry!(entry.is_array(), "JSON value is not an array.");
                test_entry!(
                    entry.as_array().map_or(&[][..], Vec::as_slice).len() == 3,
                    "JSON array size invalid."
                );
                let pair = entry.as_array().map_or(&[][..], Vec::as_slice);
                let (entry_name, entry_flags, entry_configs) = (&pair[0], &pair[1], &pair[2]);
                test_entry!(
                    entry_name.is_string(),
                    "JSON value for name is not a string."
                );
                test_entry!(
                    entry_flags.is_string(),
                    "JSON value for flags is not a string."
                );
                test_entry!(
                    entry_configs.is_null() || entry_configs.is_array(),
                    "JSON value for configs is not null or array."
                );

                let name = entry_name.as_str().unwrap_or_default().to_owned();
                let flags = entry_flags.as_str().unwrap_or_default();
                test_entry!(flags.len() == 2, "Invalid flags string size");

                if let Some(configs) = entry_configs.as_array() {
                    let mut config_found = false;
                    for config in configs {
                        test_entry!(
                            config.is_string(),
                            "JSON value in config array is not a string."
                        );
                        config_found = config_found
                            || config.as_str().unwrap_or_default() == self.base.info_config;
                    }
                    if !config_found {
                        continue;
                    }
                }

                let file_time = FileTime::load(&name);
                if !file_time.exists() {
                    return info.log_error(format!(
                        "The source file {} does not exist.",
                        self.message_path(&name)
                    ));
                }

                self.beval.sources.insert(
                    name.clone(),
                    Rc::new(RefCell::new(SourceFile {
                        file_name: name,
                        file_time,
                        parse_data: None,
                        build_path: String::new(),
                        is_header: false,
                        moc: flags.as_bytes()[0] == b'M',
                        uic: flags.as_bytes()[1] == b'U',
                    })),
                );
            }
        }

        // -- Init derived information
        // Moc variables
        if self.mconst.enabled {
            // Compose moc includes list
            {
                // Compute framework paths
                let mut framework_paths: BTreeSet<String> = BTreeSet::new();
                for path in &self.mconst.include_paths {
                    if let Some(prefix) = path.strip_suffix(".framework/Headers") {
                        // Go up twice to get to the framework root
                        let mut components: Vec<&str> =
                            prefix.split('/').filter(|c| !c.is_empty()).collect();
                        components.pop();
                        let joined = components.join("/");
                        framework_paths.insert(format!("/{joined}"));
                    }
                }
                // Append includes
                for path in &self.mconst.include_paths {
                    self.mconst.options_includes.push(format!("-I{path}"));
                }
                // Append framework includes
                for path in &framework_paths {
                    self.mconst.options_includes.push("-F".to_owned());
                    self.mconst.options_includes.push(path.clone());
                }
            }

            // Compose moc definitions list
            for def in &self.mconst.definitions {
                self.mconst.options_definitions.push(format!("-D{def}"));
            }
        }

        true
    }
}

