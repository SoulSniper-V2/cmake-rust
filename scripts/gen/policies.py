#!/usr/bin/env python3
"""Generate src/policy_table.rs from Kitware's Source/cmPolicies.h (pinned 4.1.0)."""
import re, sys
from pathlib import Path
src = Path(sys.argv[1]).read_text()
body = src[src.index("#define CM_FOR_EACH_POLICY_TABLE"):]
body = body[:body.index("\n\n")]
body = body.replace("\\\n", " ")
entries = []
for m in re.finditer(r'SELECT\(\s*POLICY,\s*(CMP\d{4}),\s*((?:"(?:[^"\\]|\\.)*"\s*)+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(NEW|WARN)\s*\)', body):
    pid, desc, a, b, c, status = m.groups()
    text = "".join(re.findall(r'"((?:[^"\\]|\\.)*)"', desc))
    entries.append((pid, text, int(a), int(b), int(c), status))
out = ["// @generated by scripts/gen/policies.py from Kitware CMake 4.1.0 Source/cmPolicies.h", "",
       "pub struct PolicyInfo { pub id: &'static str, pub doc: &'static str, pub version: (u32, u32, u32), pub removed: bool }", "",
       f"pub const POLICIES: [PolicyInfo; {len(entries)}] = ["]
for pid, text, a, b, c, status in entries:
    out.append(f'    PolicyInfo {{ id: "{pid}", doc: "{text}", version: ({a}, {b}, {c}), removed: {"true" if status == "NEW" else "false"} }},')
out.append("];")
Path(sys.argv[2]).write_text("\n".join(out) + "\n")
print(len(entries))
