#!/usr/bin/env python3
"""Generate src/commands/file/curl_strerror.rs: curl_easy_strerror of the
curl that Kitware CMake 4.1.0 vendors (Utilities/cmcurl, curl 8.14.1).

Usage: scripts/gen/curl_strerror.py <kitware>/Utilities/cmcurl src/commands/file/curl_strerror.rs
"""
import re, sys
from pathlib import Path
root = Path(sys.argv[1])
header = (root / "include/curl/curl.h").read_text()
start = header.index("  CURLE_OK = 0,")
enum = header[start:header.index("} CURLcode;", start)]
enum = re.sub(r"/\*.*?\*/", "", enum, flags=re.S)
values = {}
value = -1
for item in enum.split(","):
    item = item.strip()
    if not item:
        continue
    m = re.fullmatch(r"(CURLE_\w+)(?:\s*=\s*(\d+))?", item)
    if not m:
        continue
    value = int(m.group(2)) if m.group(2) else value + 1
    values[m.group(1)] = value
source = (root / "lib/strerror.c").read_text()
body = source[source.index("curl_easy_strerror(CURLcode error)"):]
body = body[:body.index("\n}\n")]
switch = body[body.index("switch(error) {"):body.index("  default:")] if "  default:" in body else body
cases = []
pending = []
for line in switch.splitlines():
    line = line.strip()
    m = re.match(r"case (CURLE_\w+):", line)
    if m:
        pending.append(m.group(1))
        continue
    m = re.match(r'return "((?:[^"\\]|\\.)*)";', line)
    if m and pending:
        for name in pending:
            cases.append((values[name], name, m.group(1)))
        pending = []
fallback = re.search(r'return "((?:[^"\\]|\\.)*)";\s*#endif\s*$', body.rstrip() + "\n#endif")
out = ["// @generated by scripts/gen/curl_strerror.py from Kitware CMake 4.1.0",
       "// Utilities/cmcurl (curl 8.14.1) include/curl/curl.h and lib/strerror.c.",
       "",
       "/// `curl_easy_strerror` of the curl Kitware CMake vendors.",
       "pub fn curl_easy_strerror(code: i32) -> &'static str {",
       "    match code {"]
for value, name, text in sorted(cases):
    out.append(f'        {value} => "{text}", // {name}')
out.append('        _ => "Unknown error",')
out += ["    }", "}"]
Path(sys.argv[2]).write_text("\n".join(out) + "\n")
print(len(cases), "codes")
